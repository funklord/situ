def _stuffing(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	code = _named_code(decl)
	if code not in DERIVED_STUFFING:
		return None
	if code == "cobs":
		return _cobs(decl, prefix)
	if code in BIT_STUFFING:
		return _bit_stuffing(decl, prefix, code)
	if code == "smtp_dot":
		return _smtp_dot(decl, prefix)
	if code in ESCAPE_STUFFING:
		return _escape_stuffing(decl, prefix, code)
	return None


def _escape_stuffing(decl: ast.CodecDecl, prefix: str, code: str) -> list[str]:
	"""An escape-stuffed byte code: SLIP and PPP's asynchronous framing.

	Both keep every payload byte and make the ones that would be mistaken for
	framing unmistakable by putting an escape in front. That is the opposite
	trade from COBS, which removes the delimiter value from the body entirely
	and pays a pointer per group for it; here the payload is untouched and the
	worst case is two bytes out for one in, when every byte needs escaping.

	The decoder differs between the two and the comments say why: PPP's
	escape is defined as a transformation, so reversing it needs no table and
	covers escapes this generator never enumerated.
	"""
	title, delim, esc, xor, pairs = ESCAPE_STUFFING[code]
	name = ident(prefix, decl.name)

	lines = [
		"",
		f"/* {decl.name}: {title}.",
		" *",
		f" * A payload byte equal to the delimiter (0x{delim:02X}) or to the"
		f" escape",
		f" * (0x{esc:02X}) is sent as the escape followed by a substitute, so"
		" neither",
		" * can be mistaken for the end of a frame. Every other byte is sent as",
		" * it stands.",
		" *",
		" * `out` needs 2 * len + 1 bytes: twice the payload if every byte has",
		" * to be escaped, plus the trailing delimiter. Returns the length",
		" * written.",
		" */",
		f"uint32_t {name}_encode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"\tuint32_t read;",
		"\tuint32_t written = 0;",
		"",
		"\tfor (read = 0; read < len; read++) {",
		"\t\tswitch (in[read]) {",
	]

	for literal, escaped in pairs:
		lines += [
			f"\t\tcase 0x{literal:02X}u:",
			f"\t\t\tout[written++] = (uint8_t)0x{esc:02X}u;",
			f"\t\t\tout[written++] = (uint8_t)0x{escaped:02X}u;",
			"\t\t\tbreak;",
		]

	lines += [
		"\t\tdefault:",
		"\t\t\tout[written++] = in[read];",
		"\t\t\tbreak;",
		"\t\t}",
		"\t}",
		"",
		f"\tout[written++] = (uint8_t)0x{delim:02X}u;\t/* the frame"
		" delimiter */",
		"\treturn written;",
		"}",
		"",
	]

	if xor is None:
		undo = [
			"\t\tswitch (in[read++]) {",
			*[line for literal, escaped in pairs for line in (
				f"\t\tcase 0x{escaped:02X}u:",
				f"\t\t\tout[written++] = (uint8_t)0x{literal:02X}u;",
				"\t\t\tbreak;")],
			"\t\tdefault:",
			"\t\t\t/* An escape this code does not define. Refusing beats",
			"\t\t\t * inventing a byte: the frame is not what it claims. */",
			"\t\t\treturn 0;",
			"\t\t}",
		]
		note = [
			" * The substitutions are a table rather than a transformation --"
			f" 0x{pairs[0][0]:02X}",
			f" * becomes 0x{pairs[0][1]:02X} and 0x{pairs[1][0]:02X} becomes"
			f" 0x{pairs[1][1]:02X}, which is no single operation on either --",
			" * so an escape sequence outside it is refused rather than"
			" guessed.",
		]
	else:
		undo = [
			f"\t\t/* RFC 1662: an escaped byte is the original exclusive-ored",
			f"\t\t * with 0x{xor:02X}, so undoing it is the same operation"
			" again. */",
			f"\t\tout[written++] = (uint8_t)(in[read++] ^ 0x{xor:02X}u);",
		]
		note = [
			f" * The escape is defined as a transformation -- exclusive-or"
			f" with 0x{xor:02X} --",
			" * rather than as a table, so this reverses any escaped byte and"
			" not",
			" * only the two that must always be escaped. That matters: a peer",
			" * whose ACCM asks it to escape control characters sends escapes",
			" * this generator never enumerated, and they decode correctly"
			" here.",
			" *",
			" * Encoding escapes only the two that are mandatory, which is what"
			" an",
			" * ACCM of zero asks for. A link that negotiated a different one"
			" is",
			" * asking the sender for escapes this does not add.",
		]

	lines += [
		"/* The inverse, stopping at the delimiter.",
		" *",
		*note,
		" */",
		f"uint32_t {name}_decode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"\tuint32_t read = 0;",
		"\tuint32_t written = 0;",
		"",
		"\twhile (read < len) {",
		"\t\tconst uint8_t byte = in[read++];",
		"",
		f"\t\tif (byte == (uint8_t)0x{delim:02X}u) {{",
		"\t\t\tbreak;\t\t/* the delimiter ends the frame */",
		"\t\t}",
		f"\t\tif (byte != (uint8_t)0x{esc:02X}u) {{",
		"\t\t\tout[written++] = byte;",
		"\t\t\tcontinue;",
		"\t\t}",
		"\t\tif (read >= len) {",
		"\t\t\treturn 0;\t/* truncated: an escape ended the input */",
		"\t\t}",
		*undo,
		"\t}",
		"",
		"\treturn written;",
		"}",
	]
	return lines


def _smtp_dot(decl: ast.CodecDecl, prefix: str) -> list[str]:
	"""SMTP dot-stuffing, RFC 5321 section 4.5.2.

	A line beginning with a period is sent with two, and the receiver removes
	one. That is what makes `CRLF . CRLF` an unambiguous terminator: a body
	line of a single dot arrives as two dots, so the only bare dot on its own
	line is the one that ends the body.

	`unit = stream` rather than `byte`, and the schema says why: the trigger is
	"the start of a line", which cannot be evaluated from one byte without
	knowing what preceded it. Both directions here carry that state in a flag
	rather than looking backwards, so neither needs the buffer to be a whole
	message.

	The terminator is not written or consumed here. The region is delimited
	*and* coded, and the scan runs on the encoded bytes -- which is the order
	the stuffing exists to make safe (13.6).
	"""
	name = ident(prefix, decl.name)

	return [
		"",
		f"/* {decl.name}: SMTP dot-stuffing (RFC 5321 section 4.5.2).",
		" *",
		" * A line beginning with `.` is sent with two. The receiver removes"
		" one,",
		" * which is what leaves `CRLF . CRLF` unambiguous as a terminator.",
		" *",
		" * `out` needs len + the number of dot-led lines, which the declared",
		" * `ratio_bounded(4, 3)` bounds at one added byte per three: a body of",
		" * nothing but `.CRLF` is the worst case. Returns the length written.",
		" */",
		f"uint32_t {name}_encode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"	uint32_t read;",
		"	uint32_t written = 0;",
		"	int at_line_start = 1;	/* the body starts at the start of a line */",
		"",
		"	for (read = 0; read < len; read++) {",
		"		if (at_line_start && in[read] == (uint8_t)'.') {",
		"			out[written++] = (uint8_t)'.';",
		"		}",
		"		out[written++] = in[read];",
		"",
		"		/* A line ends at LF. Testing for it rather than for CRLF is what",
		"		 * keeps this a stream: a CR at the end of one call and an LF at",
		"		 * the start of the next would otherwise be missed. */",
		"		at_line_start = in[read] == (uint8_t)'\\n';",
		"	}",
		"",
		"	return written;",
		"}",
		"",
		f"/* The inverse. A line of `..` becomes `.`; a line of one `.` is the",
		" * terminator and never reaches here, because the scan that framed the",
		" * region stopped at it. */",
		f"uint32_t {name}_decode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"	uint32_t read;",
		"	uint32_t written = 0;",
		"	int at_line_start = 1;",
		"",
		"	for (read = 0; read < len; read++) {",
		"		if (at_line_start && in[read] == (uint8_t)'.') {",
		"			/* Drop the added one and keep whatever follows, which for a",
		"			 * line that was `.` alone is the CRLF. */",
		"			at_line_start = 0;",
		"			continue;",
		"		}",
		"		out[written++] = in[read];",
		"		at_line_start = in[read] == (uint8_t)'\\n';",
		"	}",
		"",
		"	return written;",
		"}",
	]


def _cobs(decl: ast.CodecDecl, prefix: str) -> list[str]:
	"""Consistent Overhead Byte Stuffing, as Cheshire and Baker defined it.

	Every zero byte is removed from the payload and replaced by a pointer to
	the next one, so a zero can be used as an unambiguous frame delimiter. The
	overhead is one byte per 254, which is where `ratio_bounded(255, 254)`
	comes from -- and the reason it is *bounded* rather than exact is that how
	many bytes it adds depends entirely on the content.
	"""
	name = ident(prefix, decl.name)

	return [
		"",
		f"/* {decl.name}: COBS (Cheshire and Baker).",
		" *",
		" * A zero byte becomes a pointer to the next one, so no zero survives in",
		" * the body and a zero can delimit the frame. The output length depends",
		" * on the content, which is exactly why interior addressing does not",
		" * survive this and why it belongs at the outermost layer.",
		" *",
		" * `out` needs len + len/254 + 2 bytes. Returns the length written.",
		" */",
		f"uint32_t {name}_encode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"\tuint32_t read = 0;",
		"\tuint32_t code_at = 0;",
		"\tuint32_t written = 1;",
		"\tuint8_t  code = 1;",
		"",
		"\tfor (read = 0; read < len; read++) {",
		"\t\tif (in[read] != 0u) {",
		"\t\t\tout[written++] = in[read];",
		"\t\t\tcode++;",
		"\t\t\t/* A full group is flushed only when more input follows. At",
		"\t\t\t * the very end there is nothing for a new group to hold, and",
		"\t\t\t * opening one would spend a second overhead byte -- which is",
		"\t\t\t * the one thing COBS promises not to do. */",
		"\t\t\tif (code != 0xFFu || read + 1u >= len) {",
		"\t\t\t\tcontinue;",
		"\t\t\t}",
		"\t\t}",
		"",
		"\t\tout[code_at] = code;",
		"\t\tcode_at = written++;",
		"\t\tcode = 1;",
		"\t}",
		"",
		"\tout[code_at] = code;",
		"\tout[written++] = 0u;\t\t/* the delimiter */",
		"\treturn written;",
		"}",
		"",
		f"uint32_t {name}_decode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"\tuint32_t read = 0;",
		"\tuint32_t written = 0;",
		"",
		"\twhile (read < len) {",
		"\t\tuint8_t code = in[read];",
		"\t\tuint8_t at;",
		"",
		"\t\tif (code == 0u) {",
		"\t\t\tbreak;\t\t/* the delimiter ends the frame */",
		"\t\t}",
		"\t\tread++;",
		"",
		"\t\tfor (at = 1u; at < code; at++) {",
		"\t\t\tif (read >= len) {",
		"\t\t\t\treturn 0;\t/* truncated: a code ran past the end */",
		"\t\t\t}",
		"\t\t\tout[written++] = in[read++];",
		"\t\t}",
		"",
		"\t\tif (code != 0xFFu && read < len && in[read] != 0u) {",
		"\t\t\tout[written++] = 0u;",
		"\t\t}",
		"\t}",
		"",
		"\treturn written;",
		"}",
	]


#: Bit-stuffing codes: the run of ones that triggers an inserted zero, what
#: the insertion is for, and what a run one longer means to a decoder.
#:
#: Two codes rather than one with a parameter, and they are named apart for
#: the reason 26.140 names the two NRZIs apart: a decoder built on the wrong
#: run length returns bytes that are wrong from the first stuffed bit onward,
#: with nothing at run time to notice. What they share is the algorithm, so
#: the generator is one function and the run is its argument -- the opposite
#: trade from SLIP and PPP, which share a name for their shape and differ in
#: what they actually do (decision 0017's third amendment).
BIT_STUFFING: dict[str, tuple[int, tuple[str, ...], str]] = {
	"hdlc": (5,
	         ("After five consecutive ones a zero is inserted, so the flag "
	          "sequence",
	          "cannot appear inside a frame. Six bits out for five in, worst "
	          "case,",
	          "and where a frame lands in that range depends on its content."),
	         "six ones is a flag, not data"),
	"usb":  (6,
	         ("After six consecutive ones a zero is inserted, so the line "
	          "cannot",
	          "hold still: this goes out through NRZI, which transitions on a "
	          "zero,",
	          "so an unbroken run of ones would leave a receiver nothing to",
	          "recover its clock from. USB 2.0 section 7.1.9. Seven bits out "
	          "for",
	          "six in, worst case."),
	         "seven ones cannot be sent"),
}


def _bit_stuffing(decl: ast.CodecDecl, prefix: str, code: str) -> list[str]:
	"""Insert a zero after a run of ones: HDLC's five, USB's six.

	One algorithm and one constant. The worst case is `run + 1` bits out for
	`run` in, and how close to it any particular frame gets depends on the
	data -- which is `ratio_bounded` and why `kernels.STUFFING_BOUNDS` holds
	the pair rather than the schema being trusted for it.
	"""
	name = ident(prefix, decl.name)
	run, purpose, overrun = BIT_STUFFING[code]

	return [
		"",
		f"/* {decl.name}: {code.upper()} bit stuffing.",
		" *",
		*(f" * {line}" for line in purpose),
		" *",
		f" * Lengths are in bits. `out` needs len + len / {run} + 1 bits.",
		" */",
		f"uint32_t {name}_encode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"\tuint32_t at;",
		"\tuint32_t written = 0;",
		"\tuint32_t ones = 0;",
		"",
		"\tfor (at = 0; at < len; at++) {",
		"\t\tuint32_t bit = (uint32_t)situ_bits_get_msb(in, at, 1u);",
		"",
		"\t\tsitu_bits_set_msb(out, written++, 1u, bit);",
		"",
		"\t\tif (bit) {",
		"\t\t\tones++;",
		f"\t\t\tif (ones == {run}u) {{",
		"\t\t\t\tsitu_bits_set_msb(out, written++, 1u, 0u);",
		"\t\t\t\tones = 0;",
		"\t\t\t}",
		"\t\t} else {",
		"\t\t\tones = 0;",
		"\t\t}",
		"\t}",
		"",
		"\treturn written;",
		"}",
		"",
		f"uint32_t {name}_decode(const uint8_t *in, uint32_t len, uint8_t *out)",
		"{",
		"\tuint32_t at;",
		"\tuint32_t written = 0;",
		"\tuint32_t ones = 0;",
		"",
		"\tfor (at = 0; at < len; at++) {",
		"\t\tuint32_t bit = (uint32_t)situ_bits_get_msb(in, at, 1u);",
		"",
		f"\t\tif (ones == {run}u) {{",
		"\t\t\t/* A stuffed zero, which the encoder put there. */",
		"\t\t\tones = 0;",
		"\t\t\tif (bit) {",
		f"\t\t\t\treturn 0;\t/* {overrun} */",
		"\t\t\t}",
		"\t\t\tcontinue;",
		"\t\t}",
		"",
		"\t\tsitu_bits_set_msb(out, written++, 1u, bit);",
		"\t\tones = bit ? ones + 1u : 0u;",
		"\t}",
		"",
		"\treturn written;",
		"}",
	]


# ---------------------------------------------------------------------------
# Reed-Solomon over GF(2^m)
#
# Section 26.12 calls this the largest single item in the phase and it is: the
# encoder is a polynomial division like a CRC's, and the decoder is four
# separate algorithms in a row. What is written below is the standard
# construction -- syndromes, Berlekamp-Massey, Chien search, Forney -- rather
# than anything novel, because a novel error-correcting code is the last thing
# anybody wants.
#
# The tables are computed here rather than copied. A transcribed log table is
# exactly the kind of artefact that is wrong in one entry and produces a codec
# that works on most inputs.
# ---------------------------------------------------------------------------


def _gf_tables(field: int, primitive: int) -> tuple[list[int], list[int]]:
	"""Antilog and log for GF(2^m), generated from the primitive polynomial.

	The antilog table is doubled so a product of two logs can be looked up
	without a modulo, which is the usual trick and the reason the generated
	multiply is two loads and an add.
	"""
	size   = field - 1
	exp    = [0] * (2 * field)
	log    = [0] * field
	value  = 1

	for power in range(size):
		exp[power] = value
		log[value] = power
		value <<= 1
		if value & field:
			value ^= primitive

	for power in range(size, 2 * size):
		exp[power] = exp[power - size]

	return exp, log


def _reed_solomon(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	field = _number(decl, "field")
	n     = _number(decl, "n")
	k     = _number(decl, "k")

	if field != 256 or not n or not k:
		return None

	primitive  = _number(decl, "primitive", 0x11D)
	first_root = _number(decl, "first_root", 0)
	nroots     = n - k
	size       = field - 1

	exp, log = _gf_tables(field, primitive)

	# Constant term first. The division loop below indexes from the low end,
	# which is the standard formulation and the one every reference uses;
	# multiplying the roots out produces it leading-first.
	generator = list(reversed(
		_rs_generator_coefficients(nroots, first_root, exp, log, size)))
	name = ident(prefix, decl.name)

	return [
		"",
		f"/* {decl.name}: Reed-Solomon({n}, {k}) over GF({field}).",
		" *",
		f" * {nroots} parity symbols, correcting up to {nroots // 2} symbol errors",
		" * anywhere in the block. Systematic: the message sits verbatim ahead of",
		" * the parity, so a reader that trusts the block takes it with no decode",
		" * at all.",
		" *",
		f" * Primitive polynomial 0x{primitive:X}, first root alpha^{first_root}.",
		" * Every table below is computed from those two numbers rather than",
		" * copied, so a code nobody has standardised works as well as one that",
		" * has -- and no transcription can be wrong in one entry.",
		" */",
		f"#define {macro(prefix, decl.name, 'BLOCK')}  {n}u",
		f"#define {macro(prefix, decl.name, 'DATA')}   {k}u",
		f"#define {macro(prefix, decl.name, 'PARITY')} {nroots}u",
		"",
		*_gf_arithmetic(name, exp, log, size),
		*_rs_encoder(name, generator, nroots, k),
		*_rs_decoder(name, n, nroots, first_root, size),
	]


def _rs_generator_coefficients(nroots: int, first_root: int, exp: list[int],
		log: list[int], size: int) -> list[int]:
	"""Multiply out (x - alpha^(first_root + i)) for each root."""
	poly = [1]

	for root in range(nroots):
		alpha = exp[(first_root + root) % size]
		shifted = poly + [0]

		for at in range(len(poly)):
			if poly[at] and alpha:
				shifted[at + 1] ^= exp[(log[poly[at]] + log[alpha]) % size]

		poly = shifted

	return poly


def _gf_arithmetic(name: str, exp: list[int], log: list[int],
		size: int) -> list[str]:
	rows = []
	for start in range(0, len(exp), 16):
		rows.append("\t" + ", ".join(f"0x{value:02X}u"
		                             for value in exp[start:start + 16]) + ",")

	log_rows = []
	for start in range(0, len(log), 16):
		log_rows.append("\t" + ", ".join(f"0x{value:02X}u"
		                                 for value in log[start:start + 16]) + ",")

	return [
		f"/* Antilog, doubled so a product of logs needs no modulo. */",
		f"static const uint8_t {name}_exp[{len(exp)}] = {{",
		*rows,
		"};",
		"",
		f"static const uint8_t {name}_log[{len(log)}] = {{",
		*log_rows,
		"};",
		"",
		f"static uint8_t {name}_mul(uint8_t a, uint8_t b)",
		"{",
		"\tif (a == 0u || b == 0u) {",
		"\t\treturn 0u;",
		"\t}",
		f"\treturn {name}_exp[(uint32_t){name}_log[a] + (uint32_t){name}_log[b]];",
		"}",
		"",
		f"static uint8_t {name}_inv(uint8_t a)",
		"{",
		f"\treturn {name}_exp[{size}u - (uint32_t){name}_log[a]];",
		"}",
		"",
		f"/* alpha raised to a power, with the exponent reduced first. */",
		f"static uint8_t {name}_pow(uint32_t power)",
		"{",
		f"\treturn {name}_exp[power % {size}u];",
		"}",
		"",
	]


def _rs_encoder(name: str, generator: list[int], nroots: int,
		k: int) -> list[str]:
	rows = "\t" + ", ".join(f"0x{value:02X}u" for value in generator) + ","

	return [
		"/* The generator polynomial, multiplied out from its roots. */",
		f"static const uint8_t {name}_generator[{len(generator)}] = {{",
		rows,
		"};",
		"",
		"/* Systematic encode: the message is left alone and the parity is the",
		" * remainder of dividing it, shifted, by the generator. */",
		f"uint32_t {name}_encode(const uint8_t *data, uint32_t len, uint8_t *parity)",
		"{",
		f"\tuint32_t at;",
		f"\tuint32_t j;",
		"",
		f"\tif (len != {k}u) {{",
		"\t\treturn 0;",
		"\t}",
		"",
		f"\tfor (at = 0; at < {nroots}u; at++) {{",
		"\t\tparity[at] = 0u;",
		"\t}",
		"",
		"\tfor (at = 0; at < len; at++) {",
		"\t\tuint8_t feedback = (uint8_t)(data[at] ^ parity[0]);",
		"",
		f"\t\tfor (j = 0; j + 1u < {nroots}u; j++) {{",
		"\t\t\tparity[j] = (uint8_t)(parity[j + 1] ^",
		f"\t\t\t\t{name}_mul(feedback, {name}_generator[{nroots}u - 1u - j]));",
		"\t\t}",
		f"\t\tparity[{nroots}u - 1u] = {name}_mul(feedback, "
		f"{name}_generator[0]);",
		"\t}",
		"",
		f"\treturn {nroots}u;",
		"}",
		"",
	]


def _rs_decoder(name: str, n: int, nroots: int, first_root: int,
		size: int) -> list[str]:
	"""The standard four steps, in the standard order.

	Syndromes say whether anything is wrong; Berlekamp-Massey finds the error
	locator polynomial from them; a Chien search finds its roots, which are the
	error positions; Forney gives the magnitude at each. Nothing here is novel,
	deliberately: a novel error-correcting code is the last thing anybody
	wants, and the value situ adds is that the properties in the capability map
	were derived from the same description as this code.
	"""
	half = nroots // 2

	return [
		"/* Decode in place. Returns the number of symbols corrected, or -1 if",
		" * the block holds more errors than the code can correct -- which it",
		" * detects rather than guessing at, because a miscorrection is worse",
		" * than a refusal. */",
		f"int {name}_decode(uint8_t *block, uint32_t len)",
		"{",
		f"\tuint8_t syndrome[{nroots}u];",
		f"\tuint8_t lambda[{half + 1}u];",
		f"\tuint8_t previous[{half + 1}u];",
		f"\tuint8_t scratch[{half + 1}u];",
		f"\tuint8_t omega[{nroots}u];",
		f"\tuint8_t position[{half}u];",
		"\tuint32_t at;",
		"\tuint32_t j;",
		"\tuint32_t found = 0;",
		"\tuint32_t degree = 0;",
		"\tuint32_t shift = 1;",
		"\tuint8_t  discrepancy_last = 1;",
		"\tint      wrong = 0;",
		"",
		f"\tif (len != {n}u) {{",
		"\t\treturn -1;",
		"\t}",
		"",
		"\t/* 1. Syndromes: the block evaluated at each root. All zero means",
		"\t *    nothing is wrong, which is the common case and the cheap one. */",
		f"\tfor (at = 0; at < {nroots}u; at++) {{",
		"\t\tuint8_t value = 0u;",
		f"\t\tuint8_t root = {name}_pow({first_root}u + at);",
		"",
		"\t\tfor (j = 0; j < len; j++) {",
		f"\t\t\tvalue = (uint8_t)(block[j] ^ {name}_mul(value, root));",
		"\t\t}",
		"\t\tsyndrome[at] = value;",
		"\t\tif (value) {",
		"\t\t\twrong = 1;",
		"\t\t}",
		"\t}",
		"",
		"\tif (!wrong) {",
		"\t\treturn 0;",
		"\t}",
		"",
		"\t/* 2. Berlekamp-Massey: the shortest register that makes the",
		"\t *    syndromes, whose connection polynomial locates the errors. */",
		f"\tfor (at = 0; at <= {half}u; at++) {{",
		"\t\tlambda[at] = 0u;",
		"\t\tprevious[at] = 0u;",
		"\t}",
		"\tlambda[0] = 1u;",
		"\tprevious[0] = 1u;",
		"",
		f"\tfor (at = 0; at < {nroots}u; at++) {{",
		"\t\tuint8_t discrepancy = syndrome[at];",
		"",
		"\t\tfor (j = 1; j <= degree; j++) {",
		"\t\t\tdiscrepancy = (uint8_t)(discrepancy ^",
		f"\t\t\t\t{name}_mul(lambda[j], syndrome[at - j]));",
		"\t\t}",
		"",
		"\t\tif (discrepancy == 0u) {",
		"\t\t\tshift++;",
		"\t\t\tcontinue;",
		"\t\t}",
		"",
		f"\t\tfor (j = 0; j <= {half}u; j++) {{",
		"\t\t\tscratch[j] = lambda[j];",
		"\t\t}",
		f"\t\tfor (j = shift; j <= {half}u; j++) {{",
		"\t\t\tlambda[j] = (uint8_t)(lambda[j] ^",
		f"\t\t\t\t{name}_mul({name}_mul(discrepancy, "
		f"{name}_inv(discrepancy_last)),",
		"\t\t\t\t             previous[j - shift]));",
		"\t\t}",
		"",
		"\t\tif (2u * degree <= at) {",
		"\t\t\tdegree = at + 1u - degree;",
		f"\t\t\tfor (j = 0; j <= {half}u; j++) {{",
		"\t\t\t\tprevious[j] = scratch[j];",
		"\t\t\t}",
		"\t\t\tdiscrepancy_last = discrepancy;",
		"\t\t\tshift = 1;",
		"\t\t} else {",
		"\t\t\tshift++;",
		"\t\t}",
		"\t}",
		"",
		f"\tif (degree > {half}u || degree == 0u) {{",
		"\t\treturn -1;\t\t/* more errors than the code can locate */",
		"\t}",
		"",
		"\t/* 3. Chien search: every position whose evaluation vanishes is an",
		"\t *    error. Exhaustive over the block, which is what makes the cost",
		"\t *    of decoding proportional to the block and not to the errors. */",
		"\tfor (at = 0; at < len; at++) {",
		"\t\tuint8_t value = 1u;\t/* lambda[0] is always 1 */",
		f"\t\tuint8_t x = {name}_pow({size}u - ((len - 1u - at) % {size}u));",
		"\t\tuint8_t term = 1u;",
		"",
		"\t\tfor (j = 1; j <= degree; j++) {",
		f"\t\t\tterm = {name}_mul(term, x);",
		f"\t\t\tvalue = (uint8_t)(value ^ {name}_mul(lambda[j], term));",
		"\t\t}",
		"",
		"\t\tif (value == 0u) {",
		"\t\t\tif (found >= degree) {",
		"\t\t\t\treturn -1;",
		"\t\t\t}",
		"\t\t\tposition[found++] = (uint8_t)at;",
		"\t\t}",
		"\t}",
		"",
		"\tif (found != degree) {",
		"\t\treturn -1;\t\t/* the locator has roots outside the block */",
		"\t}",
		"",
		"\t/* 4. Forney: the magnitude at each located position, from the error",
		"\t *    evaluator over the formal derivative of the locator. */",
		f"\tfor (at = 0; at < {nroots}u; at++) {{",
		"\t\tuint8_t value = 0u;",
		"",
		"\t\tfor (j = 0; j <= at && j <= degree; j++) {",
		"\t\t\tvalue = (uint8_t)(value ^",
		f"\t\t\t\t{name}_mul(lambda[j], syndrome[at - j]));",
		"\t\t}",
		"\t\tomega[at] = value;",
		"\t}",
		"",
		"\tfor (at = 0; at < found; at++) {",
		f"\t\tuint8_t x = {name}_pow((len - 1u - position[at]) % {size}u);",
		f"\t\tuint8_t inverse = {name}_inv(x);",
		"\t\tuint8_t top = 0u;",
		"\t\tuint8_t bottom = 0u;",
		"\t\tuint8_t term = 1u;",
		"",
		f"\t\tfor (j = 0; j < {nroots}u; j++) {{",
		f"\t\t\ttop = (uint8_t)(top ^ {name}_mul(omega[j], term));",
		f"\t\t\tterm = {name}_mul(term, inverse);",
		"\t\t}",
		"",
		"\t\t/* The formal derivative over GF(2) keeps only the odd terms. */",
		"\t\tterm = 1u;",
		"\t\tfor (j = 1; j <= degree; j += 2u) {",
		f"\t\t\tbottom = (uint8_t)(bottom ^ {name}_mul(lambda[j], term));",
		f"\t\t\tterm = {name}_mul({name}_mul(term, inverse), inverse);",
		"\t\t}",
		"",
		"\t\tif (bottom == 0u) {",
		"\t\t\treturn -1;",
		"\t\t}",
		"",
		"\t\t{",
		f"\t\t\tuint8_t magnitude = {name}_mul(top, {name}_inv(bottom));",
		"",
		f"\t\t\tif ({first_root} == 0) {{",
		f"\t\t\t\tmagnitude = {name}_mul(magnitude, x);",
		"\t\t\t}",
		"\t\t\tblock[position[at]] = (uint8_t)(block[position[at]] ^ magnitude);",
		"\t\t}",
		"\t}",
		"",
		"\treturn (int)found;",
		"}",
	]

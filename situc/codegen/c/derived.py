# Table: line codes
# ---------------------------------------------------------------------------


def _table(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	"""A symbol map, encoded and decoded a symbol at a time.

	The map may be given outright, or named: `manchester` and `nrzi` are small
	enough to describe in the schema, and a code with a 32-entry table is
	better named than transcribed.
	"""
	kernel = decl.kernel
	assert kernel is not None

	inputs  = _number(decl, "input_bits")
	outputs = _number(decl, "output_bits")
	mapping = _symbol_map(decl, inputs, outputs)

	if mapping is None or inputs > 8 or outputs > 16:
		return None

	name = ident(prefix, decl.name)
	size = 1 << inputs

	lines = [
		"",
		f"/* {decl.name}: {inputs} bits in, {outputs} bits out, ratio "
		f"{outputs}:{inputs}.",
		" *",
		" * The ratio is exact, so an output position is a linear function of",
		" * an input one -- which is why interior offsets survive this and not",
		" * a stuffing code.",
		" */",
		f"static const uint16_t {name}_encode_table[{size}] = {{",
		"\t" + ", ".join(f"0x{mapping[symbol]:X}u" for symbol in range(size)),
		"};",
		"",
		"/* Encode `bits` input bits from `in` into `out`. Returns the number of",
		" * output bits written, which is exactly bits * "
		f"{outputs} / {inputs}. */",
		f"uint32_t {name}_encode(const uint8_t *in, uint32_t bits, uint8_t *out)",
		"{",
		"\tuint32_t at;",
		"\tuint32_t written = 0;",
		"",
		f"\tfor (at = 0; at + {inputs}u <= bits; at += {inputs}u) {{",
		f"\t\tuint32_t symbol = (uint32_t)situ_bits_get_msb(in, at, {inputs}u);",
		f"\t\tsitu_bits_set_msb(out, written, {outputs}u,",
		f"\t\t                  (uint64_t){name}_encode_table[symbol]);",
		f"\t\twritten += {outputs}u;",
		"\t}",
		"",
		"\treturn written;",
		"}",
		"",
		"/* Decode. Returns the number of input bits recovered, or 0 on a symbol",
		" * the code does not define -- which is a corrupted stream, not a",
		" * decodable one. */",
		f"uint32_t {name}_decode(const uint8_t *in, uint32_t bits, uint8_t *out)",
		"{",
		"\tuint32_t at;",
		"\tuint32_t written = 0;",
		"",
		f"\tfor (at = 0; at + {outputs}u <= bits; at += {outputs}u) {{",
		f"\t\tuint32_t code = (uint32_t)situ_bits_get_msb(in, at, {outputs}u);",
		f"\t\tuint32_t symbol;",
		"\t\tint found = 0;",
		"",
		f"\t\tfor (symbol = 0; symbol < {size}u; symbol++) {{",
		f"\t\t\tif ({name}_encode_table[symbol] == code) {{",
		f"\t\t\t\tsitu_bits_set_msb(out, written, {inputs}u, symbol);",
		f"\t\t\t\twritten += {inputs}u;",
		"\t\t\t\tfound = 1;",
		"\t\t\t\tbreak;",
		"\t\t\t}",
		"\t\t}",
		"",
		"\t\tif (!found) {",
		"\t\t\treturn 0;",
		"\t\t}",
		"\t}",
		"",
		"\treturn written;",
		"}",
	]
	return lines


def _symbol_map(decl: ast.CodecDecl, inputs: int, outputs: int
		) -> list[int] | None:
	"""The output symbol for every input symbol.

	`map = (a, b, ...)` gives it outright. A named code is looked up: the point
	of a table kernel is that the table is data, and a 4b5b table transcribed
	into a schema is a table nobody will check.
	"""
	kernel = decl.kernel
	assert kernel is not None

	if not inputs or not outputs or inputs > 8:
		return None

	named = kernel.argument("code")
	if isinstance(named, ast.NameRef) and named.name in NAMED_CODES:
		table = NAMED_CODES[named.name]
		return table if len(table) == (1 << inputs) else None

	entries = [arg.value for arg in kernel.args if arg.name == "symbol"]
	if len(entries) == (1 << inputs) and all(
			isinstance(value, ast.IntLiteral) for value in entries):
		return [value.value for value in entries
		        if isinstance(value, ast.IntLiteral)]

	return None


# Line-code tables, from the standards rather than from situ. Manchester is
# IEEE 802.3's: a one is a falling edge, encoded 10.
NAMED_CODES: dict[str, list[int]] = {
	"manchester": [0b01, 0b10],
	# ANSI X3.263 / FDDI 4b5b, the data symbols. The five-bit codes are chosen
	# to bound the run length, which is why they are not an arithmetic function
	# of the input.
	"fddi_4b5b": [
		0b11110, 0b01001, 0b10100, 0b10101,
		0b01010, 0b01011, 0b01110, 0b01111,
		0b10010, 0b10011, 0b10110, 0b10111,
		0b11010, 0b11011, 0b11100, 0b11101,
	],
}

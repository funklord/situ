from situc.layout import BITS_PER_BYTE
from situc import __version__

WORD_WIDTHS = (8, 16, 32, 64)


def generate(schema: ast.Schema, basename: str, prefix: str = "situ") -> str:
	"""Emit every derived implementation the schema binds."""
	derived = {impl.codec for impl in schema.impls()
	           if impl.kind is ast.ImplKind.DERIVED}

	lines = [
		f"/* Generated by situc {__version__} from {basename}.situ -- do not edit.",
		" *",
		" * Implementations derived from kernel descriptions (section 13.4).",
		" * The properties in the capability map and the code below come from",
		" * one description, so they cannot disagree.",
		" */",
		"",
		"#include <stdint.h>",
		"#include <stddef.h>",
		"",
		f'#include "{basename}.h"',
	]

	emitted = 0
	for decl in schema.codecs():
		if decl.name not in derived or decl.kernel is None:
			continue

		body = _for_kernel(decl, prefix)
		if body is None:
			lines.extend([
				"",
				f"/* No implementation for `{decl.name}`: a "
				f"{decl.kernel.family.value} kernel is described but not yet",
				" * generated. Its properties are derived and correct; bind an",
				f" * `impl {decl.name} extern \"...\"` to supply the code.",
				*_what_is_generated(decl),
				" */",
			])
			continue

		lines.extend(body)
		emitted += 1

	if not emitted:
		lines.extend([
			"",
			"/* Nothing derived in this schema. A translation unit with no",
			" * external definitions is not valid C, so here is one. */",
			f"extern const int {ident(prefix, basename, 'derived_none')};",
			f"const int {ident(prefix, basename, 'derived_none')} = 0;",
		])

	return "\n".join(lines) + "\n"


#: Linear block codes this build derives an implementation for.
#:
#: One entry, and named anyway. It was the literal `"hamming_7_4"` written
#: twice -- the prototype gate in `_byte_declarations` and the dispatch in
#: `_linear_block` -- which is the shape that had just cost this file a
#: silent gap in `stuffing`, in the same two places. A second code added to
#: one of them would declare a function nothing defined, or define one
#: nothing declared, and neither is visible in the diff that causes it.
DERIVED_LINEAR = ("hamming_7_4",)

#: Stuffing codes this build derives an implementation for.
#:
#: One list because there were three. The dispatch in `_stuffing` and the
#: prototype gate in `_byte_declarations` were consolidated first; `traverse`
#: held a third copy that pass did not find, and it is the one every backend
#: asks the shape question of. It lives there now and is imported here.

#: The escape-stuffed byte codes, which differ from COBS in kind: rather than
#: eliminating a byte value, they keep it and prefix it with an escape, so the
#: delimiter stays available to frame with. Each entry is the delimiter, the
#: escape, and how a byte that cannot appear literally is spelled after it.
#:
#: The two here spell that last part differently, and the difference is not
#: cosmetic. SLIP substitutes from a table -- 0xC0 becomes 0xDC and 0xDB
#: becomes 0xDD, which is not a uniform transformation of either. PPP defines
#: the escape as "the next byte, exclusive-ored with 0x20", which is a rule
#: rather than a table and is why its decoder below is the more general of the
#: two: it reverses any escaped byte, including the control characters an
#: ACCM asks a sender to escape and which no fixed table could enumerate.
ESCAPE_STUFFING: dict[str, tuple[str, int, int, int | None,
                                 tuple[tuple[int, int], ...]]] = {
	"slip": ("SLIP, RFC 1055", 0xC0, 0xDB, None,
	         ((0xC0, 0xDC), (0xDB, 0xDD))),
	"ppp_async": ("PPP asynchronous framing, RFC 1662 section 4.2",
	              0x7E, 0x7D, 0x20, ((0x7E, 0x5E), (0x7D, 0x5D))),
}


def declarations(schema: ast.Schema, prefix: str) -> list[str]:
	"""The prototypes the header needs for what `generate` emits."""
	derived = {impl.codec for impl in schema.impls()
	           if impl.kind is ast.ImplKind.DERIVED}
	lines: list[str] = []

	for decl in schema.codecs():
		if decl.name not in derived or decl.kernel is None:
			continue

		if decl.kernel.family is ast.KernelFamily.POLYNOMIAL:
			if decl.kernel.argument("field") is not None:
				lines.extend(_rs_declarations(decl, prefix))
				continue

			width = _width(decl)
			if width is None:
				continue
			lines.extend([
				"",
				f"/* `{decl.name}`: derived from a polynomial kernel. */",
				f"#define {macro(prefix, decl.name, 'WIDTH')} {width}u",
				f"uint{_accumulator(width)}_t {ident(prefix, decl.name)}"
				"(const uint8_t *data, uint32_t len);",
			])
		elif decl.kernel.family is ast.KernelFamily.TABLE:
			# Bits, unless the code pads: a padded table walks whole input
			# bytes into whole output groups and counts both in bytes. The
			# prototype said `bits` for every table, which C does not check
			# against the definition -- the types are the same and only the
			# name differs -- so base64's header lied about its own unit
			# (26.35).
			counted = "len" if table_is_padded(decl) else "bits"
			lines.extend([
				"",
				f"/* `{decl.name}`: derived from a table kernel. */",
				f"uint32_t {ident(prefix, decl.name, 'encode')}"
				f"(const uint8_t *in, uint32_t {counted}, uint8_t *out);",
				f"uint32_t {ident(prefix, decl.name, 'decode')}"
				f"(const uint8_t *in, uint32_t {counted}, uint8_t *out);",
			])
		else:
			lines.extend(_byte_declarations(decl, prefix))

	return lines


def pair_of(decl: ast.CodecDecl, prefix: str = "situ") -> tuple[str, str] | None:
	"""The `(in, count, out) -> count` encode/decode pair this kernel emits.

	Four of the six families produce that one shape, which is what
	`_byte_declarations` says: bytes in, bytes out, and a count. `None` for
	the two that do not -- a polynomial kernel is a checksum over its input
	and a linear block code is a nibble in and a codeword out, and neither is
	a transform with an inverse of the same shape.

	Asked here rather than inferred from the emitted text, because
	`gen-codec-tests` needs to know which codecs it can attack and reading a
	prototype back out of a string is how a second description starts.
	"""
	kernel = decl.kernel
	if kernel is None:
		return None

	family = kernel.family
	if family is ast.KernelFamily.POLYNOMIAL or family is ast.KernelFamily.LINEAR:
		return None
	if family is ast.KernelFamily.PERMUTATION and kernel.argument("rows") is None:
		return None
	if family is ast.KernelFamily.STUFFING and _named_code(decl) not in DERIVED_STUFFING:
		return None
	if family is ast.KernelFamily.TABLE and _symbol_map(
			decl, _number(decl, "input_bits"), _number(decl, "output_bits")) is None:
		return None

	return (ident(prefix, decl.name, "encode"), ident(prefix, decl.name, "decode"))


def _what_is_generated(decl: ast.CodecDecl) -> list[str]:
	"""Which descriptions of this family DO generate, where that is a list.

	The message above says a kernel is "not yet generated", and on its own
	that reads as though the whole family were unimplemented. It was read
	that way: decision 0017 recorded that `stuffing` "returns no
	implementation for any input at all", when three codes generated then and
	five do now. Naming them is the difference between a gap somebody can
	close and a family somebody writes off.

	**That fix reached one family of four.** `stuffing` named its codes and
	`table`, `linear_block` and `permutation` went on saying only the old
	sentence -- so a schema naming an unknown table code was told nothing
	about the eight that work, which is the reading 0017 made about stuffing
	and would have made again. The lesson was learned exactly and applied
	once, which is the shape this session found twice more the same night:
	in the workflow, where `pipefail` was added where `tee` swallowed a
	status and not where `head` did.

	`permutation` is the odd one and says something different, because what
	it declines on is not an unknown name: a bare `span` describes the extent
	of some permutation without saying which, which is enough for the
	properties and not enough for the code.
	"""
	kernel = decl.kernel
	assert kernel is not None

	if kernel.family is ast.KernelFamily.PERMUTATION:
		return [
			" *",
			*_wrap("A permutation generates from `rows` and `columns`, which "
			       "say which permutation it is. A bare `span` gives the "
			       "extent and not the mapping, so the properties follow and "
			       "the code cannot."),
		]

	catalogue = {
		ast.KernelFamily.STUFFING: ("stuffing codes", DERIVED_STUFFING),
		ast.KernelFamily.TABLE:    ("table codes", tuple(sorted(NAMED_CODES))),
		ast.KernelFamily.LINEAR:   ("linear block codes", DERIVED_LINEAR),
	}.get(kernel.family)
	if catalogue is None:
		return []

	what, codes = catalogue
	named = _named_code(decl)
	known = ", ".join(f"`{code}`" for code in codes)
	lines = [" *", *_wrap(f"The {what} this build generates are {known}.")]

	if named is not None:
		lines.extend(_wrap(f"`{named}` is not one of them."))
	elif kernel.family is ast.KernelFamily.TABLE:
		lines.extend(_wrap("This kernel names no code. A table is selected by "
		                   "`code`, or given outright as one `symbol` per "
		                   "input symbol."))
	else:
		lines.extend(_wrap(f"This kernel names no code, and a "
		                   f"{what[:-6]} code is what selects one."))
	return lines


def _wrap(prose: str) -> list[str]:
	"""One sentence as C comment continuation lines, inside 78 columns."""
	return [f" * {line}" for line in textwrap.wrap(prose, width=74)]


def _for_kernel(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	kernel = decl.kernel
	assert kernel is not None

	if kernel.family is ast.KernelFamily.POLYNOMIAL:
		if kernel.argument("field") is not None:
			return _reed_solomon(decl, prefix)
		return _polynomial(decl, prefix)
	if kernel.family is ast.KernelFamily.TABLE:
		return _table(decl, prefix)
	if kernel.family is ast.KernelFamily.PERMUTATION:
		return _permutation(decl, prefix)
	if kernel.family is ast.KernelFamily.LINEAR:
		return _linear_block(decl, prefix)
	if kernel.family is ast.KernelFamily.SHIFT:
		return _shift_register(decl, prefix)
	if kernel.family is ast.KernelFamily.ONES_COMPLEMENT:
		return _ones_complement(decl, prefix)
	return _stuffing(decl, prefix)


# ---------------------------------------------------------------------------
# One's complement: RFC 1071, the checksum on almost every packet
# ---------------------------------------------------------------------------


def _ones_complement(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	"""RFC 1071's sum, which four of this repository's examples carry.

	Sixteen lines and no table. The data is read as big-endian 16-bit words
	and added into a wider accumulator, the carries are folded back until
	none is left, and the result is complemented where the kernel says so.

	Two details are the whole of the algorithm's reputation for being
	fiddled. An odd trailing byte is the *high* half of a final word, not
	the low one -- padding it the other way gives a number that is wrong for
	every odd-length input and right for every test somebody wrote with an
	even one. And the fold is a loop rather than a single add, because
	folding once can carry again.

	The sum is order-independent over 16-bit words, which is why a protocol
	may compute it over a pseudo-header and a payload separately and add the
	halves. That property is the reason RFC 1071 exists as a document rather
	than a line of code, and nothing here needs to do anything to preserve
	it.
	"""
	kernel = decl.kernel
	assert kernel is not None

	name       = ident(prefix, decl.name)
	complement = kernel.flag("complement")
	final      = "(uint16_t)(~sum & 0xFFFFu)" if complement \
		else "(uint16_t)(sum & 0xFFFFu)"

	return [
		"",
		f"/* {decl.name}: RFC 1071, one's-complement sum with end-around",
		" * carry" + (", complemented" if complement else "") + ". */",
		f"uint16_t {name}(const uint8_t *data, uint32_t len)",
		"{",
		"\t/* 64 bits, so the accumulator cannot overflow for any length a",
		"\t * uint32_t can express: at most 2^31 words of 0xFFFF is about",
		"\t * 1.4e14, and 2^64 is 1.8e19. A uint32_t held 65537 words and",
		"\t * wrapped on the next one -- 128 KiB, which no IP datagram",
		"\t * reaches and any file does. */",
		"\tuint64_t sum = 0;",
		"\tuint32_t i;",
		"",
		"\tfor (i = 0; i + 1u < len; i += 2u) {",
		"\t\tsum += (uint64_t)(((uint32_t)data[i] << 8) | data[i + 1u]);",
		"\t}",
		"\tif (i < len) {",
		"\t\t/* The odd byte is the high half of a final word. Padding it",
		"\t\t * low is wrong for every odd length and right for every",
		"\t\t * even-length test anybody writes. */",
		"\t\tsum += (uint64_t)((uint32_t)data[i] << 8);",
		"\t}",
		"",
		"\t/* A loop rather than one add, because a fold can carry again --",
		"\t * which a 64-bit accumulator makes reachable rather than",
		"\t * theoretical. */",
		"\twhile (sum >> 16) {",
		"\t\tsum = (sum & 0xFFFFu) + (sum >> 16);",
		"\t}",
		f"\treturn {final};",
		"}",
	]



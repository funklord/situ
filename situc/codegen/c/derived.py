"""Generate implementations from kernel descriptions (section 26.12).

Tier 2's other half. `situc/kernels.py` works out what a kernel implies; this
emits the code that does it, and the two come from the same description -- which
is the point. A tier-1 codec's properties are a promise nobody checked; a
tier-2 codec's properties and its implementation are computed from one source,
so they cannot disagree.

Two families here, in the order 26.12 recommends: polynomial, which is every
CRC variant and lands as a `checksum` rather than a codec, and table, which is
Manchester, NRZI, 4b5b and 8b10b.

The generated CRC is table-driven and the table is computed here rather than
copied, so a variant nobody has written down works the same as a famous one.
What is not computed here is the check value it must produce: those come from
the CRC catalogue, and testing against them is what makes this an
implementation of CRC-32 rather than an implementation of whatever this file
happens to do.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.c.names import ident, macro

WORD_WIDTHS = (8, 16, 32, 64)


def generate(schema: ast.Schema, basename: str, prefix: str = "situ") -> str:
	"""Emit every derived implementation the schema binds."""
	derived = {impl.codec for impl in schema.impls()
	           if impl.kind is ast.ImplKind.DERIVED}

	lines = [
		f"/* Generated by situc from {basename}.situ -- do not edit.",
		" *",
		" * Implementations derived from kernel descriptions (section 13.4).",
		" * The properties in the capability map and the code below come from",
		" * one description, so they cannot disagree.",
		" */",
		"",
		"#include <stdint.h>",
		"#include <stddef.h>",
		"",
		f'#include "{basename}.h"',
	]

	emitted = 0
	for decl in schema.codecs():
		if decl.name not in derived or decl.kernel is None:
			continue

		body = _for_kernel(decl, prefix)
		if body is None:
			lines.extend([
				"",
				f"/* No implementation for `{decl.name}`: a "
				f"{decl.kernel.family.value} kernel is described but not yet",
				" * generated. Its properties are derived and correct; bind an",
				f" * `impl {decl.name} extern \\\"...\\\"` to supply the code. */",
			])
			continue

		lines.extend(body)
		emitted += 1

	if not emitted:
		lines.extend([
			"",
			"/* Nothing derived in this schema. A translation unit with no",
			" * external definitions is not valid C, so here is one. */",
			f"extern const int {ident(prefix, basename, 'derived_none')};",
			f"const int {ident(prefix, basename, 'derived_none')} = 0;",
		])

	return "\n".join(lines) + "\n"


def declarations(schema: ast.Schema, prefix: str) -> list[str]:
	"""The prototypes the header needs for what `generate` emits."""
	derived = {impl.codec for impl in schema.impls()
	           if impl.kind is ast.ImplKind.DERIVED}
	lines: list[str] = []

	for decl in schema.codecs():
		if decl.name not in derived or decl.kernel is None:
			continue

		if decl.kernel.family is ast.KernelFamily.POLYNOMIAL:
			width = _width(decl)
			if width is None:
				continue
			lines.extend([
				"",
				f"/* `{decl.name}`: derived from a polynomial kernel. */",
				f"#define {macro(prefix, decl.name, 'WIDTH')} {width}u",
				f"uint{width}_t {ident(prefix, decl.name)}"
				"(const uint8_t *data, uint32_t len);",
			])
		elif decl.kernel.family is ast.KernelFamily.TABLE:
			lines.extend([
				"",
				f"/* `{decl.name}`: derived from a table kernel. */",
				f"uint32_t {ident(prefix, decl.name, 'encode')}"
				"(const uint8_t *in, uint32_t bits, uint8_t *out);",
				f"uint32_t {ident(prefix, decl.name, 'decode')}"
				"(const uint8_t *in, uint32_t bits, uint8_t *out);",
			])

	return lines


def _for_kernel(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	kernel = decl.kernel
	assert kernel is not None

	if kernel.family is ast.KernelFamily.POLYNOMIAL:
		return _polynomial(decl, prefix)
	if kernel.family is ast.KernelFamily.TABLE:
		return _table(decl, prefix)
	return None


# ---------------------------------------------------------------------------
# Polynomial: every CRC variant
# ---------------------------------------------------------------------------


def _width(decl: ast.CodecDecl) -> int | None:
	kernel = decl.kernel
	assert kernel is not None
	value = kernel.argument("width")
	width = value.value if isinstance(value, ast.IntLiteral) else None
	return width if width in WORD_WIDTHS else None


def _number(decl: ast.CodecDecl, name: str, default: int = 0) -> int:
	kernel = decl.kernel
	assert kernel is not None
	value = kernel.argument(name)
	return value.value if isinstance(value, ast.IntLiteral) else default


def _polynomial(decl: ast.CodecDecl, prefix: str) -> list[str] | None:
	"""A table-driven CRC, with the table computed rather than copied.

	The parameters are the CRC catalogue's: width, polynomial, initial value,
	whether input and output are reflected, and a final xor. Every named
	variant is a point in that space, so generating from it means a variant
	nobody has written down works exactly as well as a famous one.
	"""
	width = _width(decl)
	if width is None:
		return None

	poly    = _number(decl, "poly")
	init    = _number(decl, "init")
	xorout  = _number(decl, "xorout")
	kernel  = decl.kernel
	assert kernel is not None
	reflect = kernel.flag("reflect")

	if not poly:
		return None

	table = _crc_table(width, poly, reflect)
	word  = f"uint{width}_t"
	name  = ident(prefix, decl.name)
	mask  = (1 << width) - 1
	digits = width // 4

	lines = [
		"",
		f"/* {decl.name}: width={width} poly=0x{poly:0{digits}X} "
		f"init=0x{init:0{digits}X}",
		f" * xorout=0x{xorout:0{digits}X} reflect={'yes' if reflect else 'no'}",
		" *",
		" * The table is computed from the polynomial, not copied from one: a",
		" * variant nobody has written down works the same as a famous one.",
		" */",
		f"static const {word} {name}_table[256] = {{",
	]

	for row in range(0, 256, 4):
		entries = ", ".join(f"0x{table[row + column]:0{digits}X}u"
		                    for column in range(4))
		lines.append(f"\t{entries},")

	lines.append("};")
	lines.append("")
	lines.append(f"{word} {name}(const uint8_t *data, uint32_t len)")
	lines.append("{")
	lines.append(f"\t{word} crc = ({word})0x{init:0{digits}X}u;")
	lines.append("\tuint32_t i;")
	lines.append("")
	lines.append("\tfor (i = 0; i < len; i++) {")

	if reflect:
		lines.append(f"\t\tcrc = ({word})({name}_table[(crc ^ data[i]) & 0xFFu]"
		             f" ^ (crc >> 8));")
	elif width == 8:
		lines.append(f"\t\tcrc = {name}_table[crc ^ data[i]];")
	else:
		lines.append(f"\t\tcrc = ({word})({name}_table"
		             f"[((crc >> {width - 8}) ^ data[i]) & 0xFFu]"
		             f" ^ ({word})(crc << 8));")

	lines.append("\t}")
	lines.append("")
	lines.append(f"\treturn ({word})(crc ^ ({word})0x{xorout:0{digits}X}u)"
	             f"{f' & 0x{mask:X}u' if width < 64 else ''};")
	lines.append("}")
	return lines


def _crc_table(width: int, poly: int, reflect: bool) -> list[int]:
	"""One byte's worth of the polynomial division, for each possible byte.

	Reflected variants run the division the other way round, which is the same
	arithmetic over the bit-reversed polynomial. Doing it here rather than
	reversing bits at run time is what keeps the generated loop one table
	lookup wide.
	"""
	mask  = (1 << width) - 1
	table = []

	if reflect:
		reversed_poly = _reverse(poly, width)
		for byte in range(256):
			crc = byte
			for _ in range(8):
				crc = (crc >> 1) ^ (reversed_poly if crc & 1 else 0)
			table.append(crc & mask)
		return table

	top = 1 << (width - 1)
	for byte in range(256):
		crc = (byte << (width - 8)) & mask
		for _ in range(8):
			crc = ((crc << 1) ^ poly) & mask if crc & top else (crc << 1) & mask
		table.append(crc)
	return table


def _reverse(value: int, width: int) -> int:
	result = 0
	for _ in range(width):
		result = (result << 1) | (value & 1)
		value >>= 1
	return result



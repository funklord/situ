"""Generate implementations from kernel descriptions (section 26.12).

Tier 2's other half. `situc/kernels.py` works out what a kernel implies; this
emits the code that does it, and the two come from the same description -- which
is the point. A tier-1 codec's properties are a promise nobody checked; a
tier-2 codec's properties and its implementation are computed from one source,
so they cannot disagree.

Two families here, in the order 26.12 recommends: polynomial, which is every
CRC variant and lands as a `checksum` rather than a codec, and table, which is
Manchester, 4b5b and the base-N alphabets. (Not NRZI or 8b10b: see
`kernels.py`.)

The generated CRC is table-driven and the table is computed here rather than
copied, so a variant nobody has written down works the same as a famous one.
What is not computed here is the check value it must produce: those come from
the CRC catalogue, and testing against them is what makes this an
implementation of CRC-32 rather than an implementation of whatever this file
happens to do.
"""

from __future__ import annotations

import textwrap


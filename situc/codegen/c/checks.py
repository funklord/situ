"""Generate tests that hold the emitted code to what the map claims.

`situc map` is the product: it says a field sits at offset 4, occupies two
bytes, can be written without moving anything, and goes stale when a tag
covers it. Nothing checked that the generated C agreed. A capability map that
the accessors quietly contradict is worse than no map, because it is believed.

So this is the same discipline `gen-codec-tests` applies to a codec signature,
turned on the compiler's own output. The compiler cannot verify an
implementation it never sees; it *can* generate the tests that would falsify
one, and its own backend is no more trustworthy than anybody else's algorithm.

Everything here derives from the schema alone. A user runs `situc gen-checks`
and gets a suite, with no vectors to write and nothing to keep in step by hand
-- which is what makes it get run.

The conformance checks work from the outside. Rather than asserting that an
accessor was emitted a particular way, they poke bytes in the buffer and watch
which ones the accessor notices: a field claiming offset 4 and size 2 must see
every one of those bytes change and no other. That catches an offset the
backend got wrong, a mask that is too wide, and a stride that drifted, without
knowing anything about how the accessor is written.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from situc import ast
from situc.capability import Axis
from situc.codegen.c.names import c_name, ident, macro
from situc.layout import BITS_PER_BYTE, Placement
from situc.propagate import Resolved
from situc.resolve import ResolvedSchema, ResolvedStruct
from situc.traverse import own_members

WORD_WIDTHS = (8, 16, 32, 64)


@dataclass
class Suite:
	"""The checks emitted, and the ones deliberately not."""

	lines: list[str]      = field(default_factory=list)
	names: list[str]      = field(default_factory=list)
	skipped: list[str]    = field(default_factory=list)

	def add(self, name: str, body: list[str], doc: list[str]) -> None:
		self.lines.extend(["", *doc,
		                   f"static void {name}(void **state)", "{",
		                   "\t(void)state;", *body, "}"])
		self.names.append(name)

	def skip(self, subject: str, why: str) -> None:
		self.skipped.append(f"{subject}: {why}")


def generate(schema: ast.Schema, resolved: ResolvedSchema, basename: str,
		prefix: str = "situ") -> str:
	suite = Suite()

	for name in sorted(resolved.structs):
		struct = resolved.structs[name]
		if struct.layout.register is not None:
			_register_checks(suite, struct, prefix)
		else:
			_struct_checks(suite, resolved, struct, prefix)

	return _render(suite, basename)


def _render(suite: Suite, basename: str) -> str:
	lines = [
		f"/* Generated by situc from {basename}.situ -- do not edit.",
		" *",
		" * Every check here is derived from the schema, and every one of them",
		" * holds the generated accessors to what the capability map claims. A",
		" * map the accessors contradict is worse than no map, because it is",
		" * believed.",
		" */",
		"",
		"#include <setjmp.h>",
		"#include <stdarg.h>",
		"#include <stddef.h>",
		"#include <stdint.h>",
		"#include <string.h>",
		"",
		"#include <cmocka.h>",
		"",
		f'#include "{basename}.h"',
	]

	if suite.skipped:
		lines.extend(["", "/* Not checked here, and why:"])
		lines.extend(f" *   {note}" for note in suite.skipped)
		lines.append(" */")

	lines.extend(suite.lines)

	if not suite.names:
		lines.extend([
			"",
			"/* Nothing in this schema has a checkable accessor yet. cmocka",
			" * refuses an empty group, so this one asserts that it is empty on",
			" * purpose rather than by accident. */",
			"static void test_nothing_to_check(void **state)",
			"{",
			"\t(void)state;",
			"}",
		])
		suite.names.append("test_nothing_to_check")

	lines.extend(["", "int main(void)", "{", "\tconst struct CMUnitTest checks[] = {"])
	lines.extend(f"\t\tcmocka_unit_test({name})," for name in suite.names)
	lines.extend(["\t};", "",
	              "\treturn cmocka_run_group_tests(checks, NULL, NULL);", "}"])

	return "\n".join(lines) + "\n"



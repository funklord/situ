def _register_checks(suite: Suite, struct: ResolvedStruct, prefix: str) -> None:
	"""Exercise a register against memory standing in for the bus.

	A user cannot issue a bus transaction in CI, and the arithmetic is what
	goes wrong anyway: which bits a field occupies, what a builder composes,
	what a `w1c` clear writes. Pointing the accessors at an array checks all of
	that. What it cannot check is the bus itself, which is the part no test
	could reach.
	"""
	info = struct.layout.register
	assert info is not None

	if info.access_width not in WORD_WIDTHS:
		suite.skip(struct.name, "access width is not a width C can name")
		return

	block = ((info.address or 0) + info.access_width // BITS_PER_BYTE)
	word  = f"uint{info.access_width}_t"
	name  = struct.name

	fields = [entry for entry in struct.entries
	          if entry.placement.kind == "field"
	          and entry.placement.access_mode is not None]

	for entry in fields:
		placement = entry.placement
		mode      = placement.access_mode
		assert mode is not None
		if not mode.readable or not mode.writable or not mode.is_assignment:
			continue

		local = c_name(placement.path[len(name) + 1:])
		mask  = (1 << placement.size_bits) - 1
		shift = placement.offset_bits or 0

		suite.add(
			f"check_{c_name(placement.path)}_composes_and_decodes",
			[
				f"\t{word} word = 0;",
				"",
				f"\tword = {ident(prefix, name, local, 'with')}(word, "
				f"({word})0x{mask:X}u);",
				f"\tassert_int_equal(word, ({word})(0x{mask:X}u << {shift}u));",
				f"\tassert_int_equal({ident(prefix, name, local, 'get')}(word), "
				f"({word})0x{mask:X}u);",
				"",
				"\t/* And it must leave every other bit of the word alone. */",
				f"\tword = ({word})~({word})0;",
				f"\tword = {ident(prefix, name, local, 'with')}(word, ({word})0);",
				f"\tassert_int_equal(word, "
				f"({word})~(({word})0x{mask:X}u << {shift}u));",
			],
			[f"/* {placement.path}: the builder places the field and the getter",
			 " * takes it back out, and neither touches a neighbouring bit. */"])

	_register_bit_operations(suite, struct, prefix, block, word)


def _register_bit_operations(suite: Suite, struct: ResolvedStruct, prefix: str,
		block: int, word: str) -> None:
	"""`w1c` writes a one to clear; a trigger writes only its own bit."""
	info = struct.layout.register
	assert info is not None
	name = struct.name

	for entry in struct.entries:
		placement = entry.placement
		mode      = placement.access_mode
		if mode is None or placement.kind != "field":
			continue

		local = c_name(placement.path[len(name) + 1:])
		mask  = (1 << placement.size_bits) - 1
		shift = placement.offset_bits or 0
		at    = ident(prefix, name, "at")

		if mode.writable and not mode.is_assignment:
			verb = "clear" if mode in (ast.AccessMode.W1C,
			                           ast.AccessMode.W0C) else "set"
			ones = mode in (ast.AccessMode.W1C, ast.AccessMode.W1S)
			expect = (f"({word})(0x{mask:X}u << {shift}u)" if ones
			          else f"({word})~(({word})0x{mask:X}u << {shift}u)")

			suite.add(
				f"check_{c_name(placement.path)}_{verb}_writes_the_bit",
				[
					f"\tuint8_t block[{block}u];",
					"",
					"\tmemset(block, 0, sizeof block);",
					f"\t{ident(prefix, name, local, verb)}(block);",
					f"\tassert_int_equal(*{at}(block), {expect});",
				],
				[f"/* {placement.path} is `{mode.value}`: the write is not an",
				 f" * assignment, so the operation is a {verb} and what reaches the",
				 " * bus is the bit pattern the hardware acts on. */"])

		if placement.on_write is ast.SideEffect.TRIGGER and mode.writable:
			suite.add(
				f"check_{c_name(placement.path)}_trigger_writes_only_itself",
				[
					f"\tuint8_t block[{block}u];",
					"",
					"\tmemset(block, 0xFF, sizeof block);",
					f"\t{ident(prefix, name, local, 'trigger')}(block);",
					f"\tassert_int_equal(*{at}(block), "
					f"({word})(0x{mask:X}u << {shift}u));",
				],
				[f"/* {placement.path} has `on_write = trigger`. It writes a word",
				 " * with this field set and every other field zero, which is the",
				 " * only word that can be composed without reading first. */"])

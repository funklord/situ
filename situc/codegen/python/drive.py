"""Retransmission in Python (26.98).

I/O is a callable, not an interface. A protocol class would be ceremony
around one function, and `submit(bytes) -> None` is the whole obligation --
which is also what makes a transcript a lambda in a test rather than a class.

The clock is a parameter here as everywhere else on this rung. That is what
lets the same ten simulated minutes run in every backend and answer the same
thing, and it is not something Python's dynamism gets to relax.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.python.emit import py_name
from situc.relation import Read, KeyLayout, ReadBytes, Refused, Side, SubView, key_layout
from situc.resolve import ResolvedSchema
from situc import __version__

__all__ = ["generate"]


def _policy(relation: ast.Relation) -> tuple[int, int] | None:
	found = {}
	for attr in relation.attrs:
		value = getattr(attr.value, "value", None)
		if attr.name in ("timeout_ms", "retries") and isinstance(value, int):
			found[attr.name] = value
	return (found["timeout_ms"], found["retries"]) if len(found) == 2 else None


def _key(sides: Side, view: str) -> list[str]:
	lines = ["\t\tkey = 0"]
	for chain, width in sides:
		source = view
		for step in chain:
			if isinstance(step, Read):
				lines.append(f"\t\tkey = (key << {width}) | "
				             f"{source}.{py_name(step.member)}")
			elif isinstance(step, SubView):
				local = f"_{py_name(step.member)}"
				lines.append(f"\t\t{local} = {source}.{py_name(step.member)}")
				source = local
	return lines


def _key_bytes(sides: Side, view: str) -> list[str]:
	"""The exact-bytes key (0042); see the converse twin for the layout."""
	lines = ["\t\tparts = []"]
	for chain, width in sides:
		source = view
		for step in chain:
			if isinstance(step, ReadBytes):
				lines.append(f"\t\tparts.append(bytes({source}."
				             f"{py_name(step.member)}))\t# {step.path}")
			elif isinstance(step, Read):
				count = (width + 7) // 8
				lines.append(f"\t\tparts.append(int({source}."
				             f"{py_name(step.member)}).to_bytes({count}, "
				             f"\"big\"))\t# {step.path}")
			elif isinstance(step, SubView):
				local = f"_{py_name(step.member)}"
				lines.append(f"\t\t{local} = {source}.{py_name(step.member)}")
				source = local
	lines.append('\t\tkey = b"".join(parts)')
	return lines


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str) -> dict[str, str]:
	ready = []
	for relation in schema.relations():
		policy = _policy(relation)
		if policy is None:
			continue
		try:
			ready.append((relation, policy, key_layout(relation, resolved)))
		except Refused:
			continue
	if not ready:
		return {}

	lines = [
		f'"""Generated by situc {__version__} from {basename}.situ -- do not edit.',
		"",
		"Retransmission and timeout. Owns I/O through a callable you supply",
		"and never owns the clock: every entry point takes `now_ms`.",
		'"""',
		"",
		"from __future__ import annotations",
		"",
		"from typing import Callable",
		"",
		"from situ_runtime import BoundsError, ConstraintError",
		"",
		f"from {basename} import *  # noqa: F403",
		"",
	]

	from situc.codegen.c.drive import part_of, resend_of

	if any(resend_of(relation) for relation, _, _ in ready):
		lines += [
			"",
			"",
			"def _sooner(a: int, b: int, now_ms: int) -> int:",
			'	"""The sooner of two deadlines, serially from `now_ms`."""',
			"	return a if (a - now_ms) & 0xFFFFFFFF < (b - now_ms) & 0xFFFFFFFF"
			" else b",
		]

	for relation, (timeout, retries), layout in ready:
		request, response = layout.request, layout.response
		resend = resend_of(relation)
		part   = part_of(relation) if resend else None
		name = py_name(relation.name)
		first, second = relation.params
		lines += [
			"",
			f"{name.upper()}_TIMEOUT_MS = {timeout}",
			f"{name.upper()}_RETRIES = {retries}",
			*([f"{name.upper()}_RESEND_MS = {resend}",
			   "# TIMEOUT_MS is the whole exchange's wait with a resend",
			   "# interval: C's (26.1039)."] if resend else []),
			*([f"{name.upper()}_RESEND_PART_MS = {part[0]}",
			   f"{name.upper()}_RETRIES_PART = {part[1]}",
			   "# Once `part_held` says part of the reply is in: C's."]
			  if part else []),
			"",
			"",
			f"class {name}_driver:",
			f'\t"""Retransmission for `{relation.name}`.',
			"",
			"\tThe bytes you hand `send` are kept for the retransmission, so",
			"\tthey must not change until the exchange ends.",
			'\t"""',
			"",
			"\t__slots__ = (\"_cap\", \"_live\", \"_submit\", \"_timeout\", \"_retries\",",
			("\t             \"_resend\", \"_interval\", \"_part_interval\","
			 " \"_part_retries\")" if part else
			 "\t             \"_resend\", \"_interval\")" if resend else
			 "\t             \"_resend\")"),
			"",
			"\tdef __init__(self, submit: Callable[[bytes], None], cap: int,",
			f"\t             timeout_ms: int = {timeout},",
			f"\t             retries: int = {retries}, *,"
			if not resend else
			f"\t             retries: int = {retries},"
			f"\n\t             resend_ms: int = {resend}, *,"
			if not part else
			f"\t             retries: int = {retries},"
			f"\n\t             resend_ms: int = {resend},"
			f"\n\t             resend_part_ms: int = {part[0]},"
			f"\n\t             retries_part: int = {part[1]}, *,",
			"\t             resend: Callable[[int, bytes], None] | None = None"
			") -> None:",
			"\t\t# `resend` is told which exchange a retransmission is, so a",
			"\t\t# caller sealing each send can reseal it (26.1036); without",
			"\t\t# one the same bytes go to `submit` again.",
			"\t\tself._submit  = submit",
			"\t\tself._resend  = resend",
			"\t\tself._cap     = cap",
			"\t\tself._timeout = timeout_ms",
			"\t\tself._retries = retries",
			*(["\t\tself._interval = resend_ms"] if resend else []),
			*(["\t\tself._part_interval = resend_part_ms",
			   "\t\tself._part_retries  = retries_part"] if part else []),
			(f"\t\tself._live: dict[{'int' if layout.packed else 'bytes'}, "
			 "list[object]] = {}"),
			"",
			f"\tdef send(self, {first.name}: {py_name(first.type_name)},",
			"\t         data: bytes, id: int, now_ms: int) -> None:",
			*(_key(request, first.name) if layout.packed
			  else _key_bytes(request, first.name)),
			"",
			"\t\tif key not in self._live and len(self._live) >= self._cap:",
			"\t\t\traise BoundsError(",
			f"\t\t\t\t\"{relation.name}: {{}} exchanges already pending\""
			".format(self._cap), self._cap)",
			*(["\t\tend = (now_ms + self._timeout) & 0xFFFFFFFF",
			   "\t\tfirst = end if self._retries == 0 else _sooner(",
			   "\t\t\t(now_ms + self._interval) & 0xFFFFFFFF, end, now_ms)",
			   (f"\t\tself._live[key] = [data, id, first, self._retries, end,"
			    " now_ms, False]" if part else
			    "\t\tself._live[key] = [data, id, first, self._retries, end]")]
			  if resend else
			  ["\t\tself._live[key] = [data, id,",
			   "\t\t                   (now_ms + self._timeout) & 0xFFFFFFFF,",
			   "\t\t                   self._retries]"]),
			"\t\tself._submit(data)",
			"",
			f"\tdef on_message(self, {second.name}: "
			f"{py_name(second.type_name)}) -> int:",
			*(_key(response, second.name) if layout.packed
			  else _key_bytes(response, second.name)),
			"",
			"\t\tif key not in self._live:",
			"\t\t\traise ConstraintError(",
			f"\t\t\t\t\"{relation.name}: no exchange is waiting for this\")",
			"\t\treturn int(self._live.pop(key)[1])  # type: ignore[arg-type]",
			"",
			f"\tdef peek(self, {second.name}: "
			f"{py_name(second.type_name)}) -> int:",
			'\t\t"""`on_message` without ending the exchange: which request',
			"",
			'\t\ta reply answers, for a reply in pieces (26.1009)."""',
			*(_key(response, second.name) if layout.packed
			  else _key_bytes(response, second.name)),
			"",
			"\t\tif key not in self._live:",
			"\t\t\traise ConstraintError(",
			f"\t\t\t\t\"{relation.name}: no exchange is waiting for this\")",
			"\t\treturn int(self._live[key][1])  # type: ignore[arg-type]",
			"",
			*_part_held(part),
			"\tdef step(self, now_ms: int) -> tuple[int | None, int]:",
			'\t\t"""Retransmit what is due; return (next deadline, given up).',
			"",
			"\t\tThe deadline is None where nothing is outstanding, and the",
			"\t\tcount is returned either way -- an exchange that gave up on",
			"\t\tthe call that emptied the table is one the caller still has",
			"\t\tto hear about. C writes it through a pointer for the same",
			'\t\treason, alongside SITU_ERR_TRUNCATED."""',
			"\t\tsoonest: int | None = None",
			"\t\texpired = 0",
			"\t\tdue: list[tuple[int, bytes]] = []",
			"",
			"\t\tfor key in list(self._live):",
			("\t\t\tdata, _id, deadline, left, end, _sent, held = self._live[key]"
			 if part else
			 "\t\t\tdata, _id, deadline, left, end = self._live[key]" if resend
			 else "\t\t\tdata, _id, deadline, left = self._live[key]"),
			# Serially, modulo 2^32, as the other three: a 32-bit clock
			# wraps, and the four agree about when it does (26.1008).
			"\t\t\tif (now_ms - int(deadline)) & 0xFFFFFFFF < 0x80000000:"
			"  # type: ignore[call-overload]",
			("\t\t\t\tif int(left) == 0 or (now_ms - int(end)) & 0xFFFFFFFF"
			 " < 0x80000000:  # type: ignore[call-overload]" if resend else
			 "\t\t\t\tif int(left) == 0:  # type: ignore[call-overload]"),
			"\t\t\t\t\tdel self._live[key]",
			"\t\t\t\t\texpired += 1",
			"\t\t\t\t\tcontinue",
			*(["\t\t\t\tleft = int(left) - 1  # type: ignore[call-overload]",
			   "\t\t\t\tdeadline = int(end) if left == 0 else _sooner("
			   "  # type: ignore[call-overload]",
			   "\t\t\t\t\t(now_ms + (self._part_interval if held"
			   " else self._interval)) & 0xFFFFFFFF, int(end),"
			   "  # type: ignore[call-overload]",
			   "\t\t\t\t\tnow_ms)",
			   "\t\t\t\tself._live[key] = [data, _id, deadline, left, end,"
			   " now_ms, held]"]
			  if part else
			  ["\t\t\t\tleft = int(left) - 1  # type: ignore[call-overload]",
			   "\t\t\t\tdeadline = int(end) if left == 0 else _sooner("
			   "  # type: ignore[call-overload]",
			   "\t\t\t\t\t(now_ms + self._interval) & 0xFFFFFFFF, int(end),"
			   "  # type: ignore[call-overload]",
			   "\t\t\t\t\tnow_ms)",
			   "\t\t\t\tself._live[key] = [data, _id, deadline, left, end]"]
			  if resend else
			  ["\t\t\t\tdeadline = (now_ms + self._timeout) & 0xFFFFFFFF",
			   "\t\t\t\tleft = int(left) - 1  # type: ignore[call-overload]",
			   "\t\t\t\tself._live[key] = [data, _id, deadline, left]"]),
			"\t\t\t\tdue.append((int(_id), bytes(data)))"
			"  # type: ignore[arg-type, call-overload]",
			"\t\t\tat = int(deadline)  # type: ignore[call-overload]",
			"\t\t\tif soonest is None or (at - now_ms) & 0xFFFFFFFF"
			" < (soonest - now_ms) & 0xFFFFFFFF:",
			"\t\t\t\tsoonest = at",
			"",
			"\t\tfor exchange, data in due:",
			"\t\t\tif self._resend is not None:",
			"\t\t\t\tself._resend(exchange, data)",
			"\t\t\telse:",
			"\t\t\t\tself._submit(data)",
			"",
			"\t\treturn (soonest, expired)",
		]

	return {f"{basename}_drive.py": "\n".join(lines).rstrip("\n") + "\n"}


def _part_held(part: tuple[int, int] | None) -> list[str]:
	"""`part_held`: see the C driver's `_part_held`."""
	if part is None:
		return []
	return [
		"\tdef part_held(self, id: int, now_ms: int) -> None:",
		'\t\t"""Part of exchange `id`\'s reply is held: from here its next',
		"",
		"\t\tretransmission is due `resend_part_ms` after the last send, and",
		"\t\t`retries_part` bounds them all. ConstraintError where no such",
		'\t\texchange is outstanding."""',
		"\t\tfor entry in self._live.values():",
		"\t\t\tif int(entry[1]) != id:  # type: ignore[call-overload]",
		"\t\t\t\tcontinue",
		"\t\t\tif not entry[6]:",
		"\t\t\t\tdone = self._retries - int(entry[3])"
		"  # type: ignore[call-overload]",
		"\t\t\t\tdue = (int(entry[5]) + self._part_interval) & 0xFFFFFFFF"
		"  # type: ignore[call-overload]",
		"\t\t\t\tif (now_ms - due) & 0xFFFFFFFF < 0x80000000:",
		"\t\t\t\t\tdue = now_ms",
		"\t\t\t\tleft = max(self._part_retries - done, 0)",
		"\t\t\t\tentry[3] = left",
		"\t\t\t\tentry[6] = True",
		"\t\t\t\tentry[2] = int(entry[4]) if left == 0 else _sooner("
		"  # type: ignore[call-overload]",
		"\t\t\t\t\tdue, int(entry[4]), now_ms)"
		"  # type: ignore[call-overload]",
		"\t\t\treturn",
		"\t\traise ConstraintError(\"no exchange {} is outstanding\""
		".format(id))",
		"",
	]

"""`gen-fuzz --target python`: a harness driving the Python accessors.

**No dependency, and that is deliberate rather than a limitation.** This
was parked once on the reading that `atheris` is third party and section
24 forbids one -- which it does not: decision 0001 constrains what `situc`
IMPORTS, and says nothing about what a generated file expects of the
consumer's toolchain, `--target c` already emitting a `libFuzzer` entry
point `situc` does not depend on (26.846).

But the better answer turned out not to need the dependency at all. The C
harness keeps `LLVMFuzzerTestOneInput` separate from a
`SITU_FUZZ_STANDALONE` `main` that reads stdin, "so the harness can be
built and run without a fuzzing engine. This is what keeps it from rotting
between runs." The same split here gives a harness that **runs under this
repository's own gates** rather than skipping where a fuzzer is absent,
and an engine wraps `one_input` in two lines:

    import atheris, <name>_fuzz
    atheris.Setup(sys.argv, <name>_fuzz.one_input); atheris.Fuzz()

What it exercises is what the C harness exercises: acquire, validate on
arbitrary bytes -- the first thing a parser runs and the last thing an
attacker controls -- then read every field, so a getter that indexes out
of its claim is reached rather than merely compiled.
"""

from __future__ import annotations

from situc import __version__, ast
from situc.codegen import refuse_only_arguments, takes_arguments
from situc.codegen.python.emit import py_name
from situc.resolve import ResolvedSchema, ResolvedStruct
from situc.traverse import own_entries


def _readable(struct: ResolvedStruct, placement: object) -> bool:
	"""Whether a plain getter exists to read this member with no argument.

	A register is excluded with its struct; what is asked here is narrower
	-- a member whose accessor needs something the fuzzer has not got.
	"""
	kind = getattr(placement, "kind", None)
	if kind not in ("field", "indexed", "tlv"):
		return False
	if getattr(placement, "arguments", None):
		return False
	return True


def _one(basename: str, struct: ResolvedStruct) -> list[str]:
	"""One struct's harness: acquire, validate, read everything."""
	name   = py_name(struct.name)
	extent = struct.layout.size_bytes
	length = "" if struct.layout.is_fixed_size else ", len(data)"

	reads = [f"\t\tsink(view.{py_name(entry.placement.name)})"
	         for entry in own_entries(struct)
	         if _readable(struct, entry.placement)
	         and entry.placement.kind == "field"]

	return [
		f"def fuzz_{name}(data: bytes) -> None:",
		f'\t"""`{struct.name}` over arbitrary bytes."""',
		f"\tif len(data) < {extent}:",
		"\t\treturn",
		"",
		"\tmsg = situ_runtime.Message(bytearray(data))",
		"\ttry:",
		f"\t\tview = {basename}.{name}.at(msg, 0{length})",
		"\texcept situ_runtime.SituError:",
		"\t\treturn",
		"",
		"\t# Validation must be safe on arbitrary bytes: it is the first",
		"\t# thing a parser runs and the last thing an attacker controls.",
		"\ttry:",
		"\t\tview.validate()",
		"\texcept situ_runtime.SituError:",
		"\t\tpass",
		"",
		"\t# Every field READ, not merely the view taken. A getter that",
		"\t# indexes outside its own claim is reached here and nowhere",
		"\t# else in this harness.",
		"\ttry:",
		*(reads or ["\t\tpass"]),
		"\texcept situ_runtime.SituError:",
		"\t\tpass",
		"",
		"",
	]


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str, prefix: str = "situ") -> str:
	"""A dependency-free fuzz harness over the Python accessors."""
	refuse_only_arguments(schema, resolved)

	# A register is a bus transaction rather than bytes off a wire: no view,
	# no `validate`, and accessors taking a device handle. A zero-byte
	# struct would frame an unbounded number of empty messages. Both are
	# `--target c`'s exclusions and for its reasons.
	fuzzable = [struct for struct in resolved.structs.values()
	            if struct.layout.is_byte_sized
	            and not takes_arguments(struct)
	            and struct.layout.register is None
	            and not (struct.layout.is_fixed_size
	                     and struct.layout.size_bytes == 0)]

	bodies: list[str] = []
	for struct in fuzzable:
		bodies.extend(_one(basename, struct))

	names = [py_name(struct.name) for struct in fuzzable]
	lines = [
		f'"""Generated by situ {__version__} from {basename}.situ'
		' -- do not edit.',
		"",
		"A fuzz harness over the Python accessors: acquire, validate on",
		"arbitrary bytes, then read every field.",
		"",
		"    python3 -m " f"{basename}_fuzz < some-input",
		"",
		"`one_input` is the entry point and takes no dependency, which is",
		"what lets this repository's own gates run it rather than skip",
		"where a fuzzer is absent. An engine wraps it in two lines:",
		"",
		"    import atheris, " f"{basename}_fuzz",
		"    atheris.Setup(sys.argv, " f"{basename}_fuzz.one_input)",
		"    atheris.Fuzz()",
		"",
		"The split is `--target c`'s, whose `SITU_FUZZ_STANDALONE` main",
		'exists so the harness "can be built and run without a fuzzing',
		'engine. This is what keeps it from rotting between runs."',
		'"""',
		"",
		"from __future__ import annotations",
		"",
		"import sys",
		"",
		"import situ_runtime",
		"",
		f"import {basename}",
		"",
		"",
		"def sink(value: object) -> None:",
		'\t"""Where a read goes, so nothing is optimised away.',
		"",
		"\tPython optimises nothing away, so this is a name for the",
		"\tintent rather than a necessity -- and it keeps the harness the",
		'\tsame shape as `--target c`\'s, which needs one."""',
		"\tif value is None:",
		"\t\treturn",
		"",
		"",
		*bodies,
		"def one_input(data: bytes) -> int:",
		'\t"""One input, dispatched by its first byte.',
		"",
		"\tThe first byte selects a struct, so one corpus drives every",
		'\tparser in the schema rather than needing a harness each."""',
	]
	if not names:
		lines.extend([
			"\t# Nothing in this schema takes a view: every struct is a",
			"\t# register, or has no bytes to read.",
			"\tdel data",
			"\treturn 0",
		])
	else:
		lines.extend([
			"\tif not data:",
			"\t\treturn 0",
			"",
			f"\tchosen = data[0] % {len(names)}",
			"\tbody   = data[1:]",
		])
		for index, name in enumerate(names):
			lines.append(f"\t{'if' if index == 0 else 'elif'}"
			             f" chosen == {index}:")
			lines.append(f"\t\tfuzz_{name}(body)")
		lines.append("\treturn 0")

	lines.extend([
		"",
		"",
		'if __name__ == "__main__":',
		"\t# One input from stdin, so the harness runs with no engine at",
		"\t# all. This is what keeps it from rotting between runs.",
		"\tsys.exit(one_input(sys.stdin.buffer.read()))",
	])
	return "\n".join(lines) + "\n"

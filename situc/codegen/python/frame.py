"""Stream framing in Python (26.96).

`required` answers an `int` here rather than an error code, and a view is
acquired through `T.at(Message, offset)`. The reader raises where the other
backends return, which is what this runtime does everywhere else.

No capacity is imposed. C, C++ and Rust take a caller buffer because they
have to; here a `bytearray` grows, and pretending otherwise would be a limit
this language does not need -- the same reasoning 26.30 records for why
`--materialize` needs a `max` in three backends and not the fourth.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.c.frame import framed_structs
from situc.codegen.python.emit import py_name
from situc.resolve import ResolvedSchema
from situc import __version__

__all__ = ["generate"]


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str) -> dict[str, str]:
	structs = framed_structs(resolved)
	if not structs:
		return {}

	lines = [
		f'"""Generated by situc {__version__} from {basename}.situ -- do not edit.',
		"",
		"Stream framing: a byte stream in, whole messages out. A separate",
		"module -- a rung adds files rather than changing them (0032).",
		'"""',
		"",
		"from __future__ import annotations",
		"",
		"from situ_runtime import Message, TruncatedError",
		"",
		f"from {basename} import *  # noqa: F403",
		"",
	]

	for struct in structs:
		held = py_name(struct.name)
		lines += [
			"",
			f"class {held}_reader:",
			f'\t"""A stream reader for `{struct.name}`.',
			"",
			"\tPush bytes as they arrive and call `next` until it raises",
			"\tTruncatedError. Call `advance` when done with each message:",
			"\tthe view it returned reads the buffer, and dropping a message",
			"\tmoves what follows down over it.",
			'\t"""',
			"",
			"\t__slots__ = (\"_buf\", \"_ready\")",
			"",
			"\tdef __init__(self) -> None:",
			"\t\tself._buf   = bytearray()",
			"\t\tself._ready = 0",
			"",
			"\tdef push(self, data: bytes) -> None:",
			"\t\tself.advance()",
			"\t\tself._buf.extend(data)",
			"",
			"\tdef advance(self) -> None:",
			"\t\tif self._ready:",
			"\t\t\tdel self._buf[:self._ready]",
			"\t\t\tself._ready = 0",
			"",
			f"\tdef next(self) -> {held}:",
			'\t\t"""The next whole message, or TruncatedError."""',
			"\t\tself.advance()",
			f"\t\tneed = {held}.required(bytes(self._buf))",
			"\t\tif need > len(self._buf):",
			"\t\t\traise TruncatedError(",
			f"\t\t\t\t\"{struct.name}: the stream has not carried one yet\",",
			"\t\t\t\tneed)",
			f"\t\tview = {held}.at(Message(bytearray(self._buf[:need])), 0)",
			"\t\tself._ready = need",
			"\t\treturn view",
		]

	return {f"{basename}_frame.py": "\n".join(lines).rstrip("\n") + "\n"}

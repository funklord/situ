"""Owned decode in Python (26.99), and why it takes no backing.

The other three take a caller buffer because a variable member has to live
somewhere the message does not. Python's `bytes` *is* that somewhere:
copying out of a `memoryview` produces a value that owns its bytes and
outlives everything. A backing parameter here would be ceremony around
something the language already did.

That is the same reasoning 26.96 gives for the framing reader imposing no
capacity, and the opposite of 26.97's table, whose bound is about refusing an
attacker rather than about representation. The question each time is whether
the limit exists for the language's sake or the protocol's.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.c.edit import editable
from situc.codegen.python.emit import py_name
from situc.layout import Placement
from situc.resolve import ResolvedSchema, ResolvedStruct
from situc.traverse import is_own_member, local_name
from situc import __version__

__all__ = ["generate"]


def _runs(struct: ResolvedStruct) -> list[Placement]:
	from situc.codegen.c.edit import _runs as runs_of
	return runs_of(struct)


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str) -> dict[str, str]:
	structs = editable(resolved)
	if not structs:
		return {}

	lines = [
		f'"""Generated by situc {__version__} from {basename}.situ -- do not edit.',
		"",
		"Owned decode: rung 2. No backing parameter, because `bytes` is",
		"already storage that outlives the message -- the other backends take",
		"a caller buffer because they have no such thing.",
		'"""',
		"",
		"from __future__ import annotations",
		"",
		"from dataclasses import dataclass",
		"",
		f"from {basename} import *  # noqa: F403",
		"",
	]

	for struct in structs:
		held  = py_name(struct.name)
		runs  = _runs(struct)
		members = [entry.placement for entry in struct.entries
		           if is_own_member(struct, entry.placement)]

		fields, build = [], []
		for placement in members:
			local = py_name(local_name(struct, placement))
			if placement in runs:
				fields.append(f"\t{local}: bytes")
				build.append(f"\t\t\t{local}=bytes(view.{local}),")
			elif placement.scalar is not None and placement.array_count is None:
				fields.append(f"\t{local}: int")
				build.append(f"\t\t\t{local}=view.{local},")

		lines += [
			"",
			"@dataclass(frozen=True)",
			f"class {held}_owned:",
			f'\t"""`{struct.name}`, copied out of the message.',
			"",
			"\tEvery field owns its value, so the message may go afterwards.",
			'\t"""',
			"",
			*fields,
			"",
			"\t@classmethod",
			f"\tdef decode(cls, view: {held}) -> \"{held}_owned\":",
			"\t\treturn cls(",
			*build,
			"\t\t)",
		]

	return {f"{basename}_edit.py": "\n".join(lines).rstrip("\n") + "\n"}

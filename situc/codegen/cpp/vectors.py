"""Golden-vector tests over the C++ accessors (sections 1 and 22).

The last of 26.829's four. `gen-tests` reached C alone; the Rust and Python
halves came first because Rust had no suite at all and Python has no
compiler, and this one completes the row -- one of section 1's four
artifacts finally reaching all four of its languages.

**A plain `main` rather than a framework.** The C suite uses cmocka and the
C++ fuzz harness uses libFuzzer, and neither is a thing to ask a user for:
section 24 requires `situc` itself to run from a bare interpreter with no
third-party packages, and a suite handed to a consumer should ask no more
than the compiler does. So this counts its own failures, names each one, and
exits non-zero -- which is what a `make` target or a CI step actually reads.

**One vector file, one parser, one validator**, for the reason the other two
give: `parse_vectors` and `_check` are the C backend's and are imported,
because the vector file is language-independent and two answers to "is this
vector well formed" is the shape this tree keeps paying for.

Per-field expectations are read and schema-checked and not yet compared, as
in the other two, and the generated file says so with the count.
"""

from __future__ import annotations

from situc import __version__, ast
from situc.codegen import refuse_parameters
from situc.codegen.c.vectors import Case, _check, _symbol
from situc.resolve import ResolvedSchema


def generate(schema: ast.Schema, resolved: ResolvedSchema, cases: list[Case],
		basename: str, prefix: str = "situ") -> str:
	"""A standalone program for `basename.hpp`, from `basename`'s vectors.

	`prefix` is accepted and unused: C++ names its accessors by namespace and
	method, so there is nothing for a prefix to disambiguate, and one
	signature across the backends is what lets `cmd_gen_tests` dispatch
	without a special case.
	"""
	refuse_parameters(schema)

	seen: dict[str, Case] = {}
	for case in cases:
		symbol = _symbol(case)
		if symbol in seen:
			raise ValueError(
				f"vector `{case.struct} {case.name}` is declared twice")
		seen[symbol] = case

	for case in cases:
		_check(resolved, case)

	unchecked = sum(len(case.expectations) for case in cases)
	lines = _preamble(basename, unchecked)

	for case in cases:
		lines.extend(_case_body(resolved, case))

	lines.extend(_main(cases))
	return "\n".join(lines) + "\n"


def _preamble(basename: str, unchecked: int) -> list[str]:
	lines = [
		f"/* Generated by situc {__version__} from {basename}.situ and its"
		f" vectors -- do not edit.",
		" *",
		" * Golden-vector tests over the C++ accessors, read from the same",
		" * vector file every other `--target` reads. One file, so the",
		" * backends cannot be asked different questions about one schema.",
		" *",
		" * A standalone program: it names each failure and exits non-zero,",
		" * which is what a make target reads. No test framework, because",
		" * section 24's no-third-party rule is about what situ asks of the",
		" * people who use it as much as of itself.",
		" *",
		f" *     c++ -std=c++17 -I. {basename}_vectors.cpp situ.c \\",
		f" *         -o {basename}_vectors",
	]

	if unchecked:
		lines.extend([
			" *",
			f" * {unchecked} field expectation(s) in that file are not",
			" * compared here; `situc gen-tests --target c` compares them.",
			" * They are read and checked against the schema all the same,",
			" * so a vectors file naming a field this schema does not have",
			" * is refused here too.",
		])

	lines.extend([
		" */",
		"",
		"#include <cstdint>",
		"#include <cstdio>",
		"#include <vector>",
		"",
		f'#include "{basename}.hpp"',
		"",
		"static int situ_failures = 0;",
		"",
	])
	return lines


def _case_body(resolved: ResolvedSchema, case: Case) -> list[str]:
	name = _symbol(case)
	body = ", ".join(f"0x{byte:02X}" for byte in case.data)

	# A variable struct's `at` takes the message length and a fixed one's
	# does not, which is the C++ backend's own branch and not a second
	# reading of it. The Python half got this wrong for 13 of 27 schemas
	# before it was run (26.829), so it is written down here rather than
	# rediscovered.
	struct = resolved.structs[case.struct]
	extent = "" if struct.layout.is_fixed_size else ", length"

	return [
		f"static void {name}(void)",
		"{",
		f"\tstd::uint8_t bytes[] = {{{body}}};",
		"\tconst std::uint32_t length ="
		" static_cast<std::uint32_t>(sizeof bytes);",
		"\t::situ::rt::message msg(bytes, length);",
		f"\t::situ::{case.struct} view;",
		"",
		f"\tif (::situ::{case.struct}::at(msg, 0{extent}, view)"
		" != ::situ::rt::err::ok) {",
		f"\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
		" the bytes take no view\\n\");",
		"\t\tsitu_failures++;",
		"\t\treturn;",
		"\t}",
		"\tif (view.validate() != ::situ::rt::err::ok) {",
		f"\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
		" validation refuses them\\n\");",
		"\t\tsitu_failures++;",
		"\t}",
		"}",
		"",
	]


def _main(cases: list[Case]) -> list[str]:
	lines = ["int main(void)", "{"]
	for case in cases:
		lines.append(f"\t{_symbol(case)}();")

	lines.extend([
		"",
		f"\tstd::printf(\"%d of {len(cases)} vector(s) failed\\n\","
		" situ_failures);",
		"\treturn situ_failures == 0 ? 0 : 1;",
		"}",
	])
	return lines

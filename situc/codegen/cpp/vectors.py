"""Golden-vector tests over the C++ accessors (sections 1 and 22).

The last of 26.829's four. `gen-tests` reached C alone; the Rust and Python
halves came first because Rust had no suite at all and Python has no
compiler, and this one completes the row -- one of section 1's four
artifacts finally reaching all four of its languages.

**A plain `main` rather than a framework.** The C suite uses cmocka and the
C++ fuzz harness uses libFuzzer, and neither is a thing to ask a user for:
section 24 requires `situc` itself to run from a bare interpreter with no
third-party packages, and a suite handed to a consumer should ask no more
than the compiler does. So this counts its own failures, names each one, and
exits non-zero -- which is what a `make` target or a CI step actually reads.

**One vector file, one parser, one validator**, for the reason the other two
give: `parse_vectors` and `_check` are the C backend's and are imported,
because the vector file is language-independent and two answers to "is this
vector well formed" is the shape this tree keeps paying for.

Per-field expectations are read and schema-checked and not yet compared, as
in the other two, and the generated file says so with the count.
"""

from __future__ import annotations

from situc import __version__, ast
from situc.codegen import (byte_run, comparable, enum_constants,
                           refuse_only_arguments, refuse_parameters,
                           tally)
from situc.codegen.c.names import c_name
from situc.codegen.c.vectors import Case, _check, _symbol
from situc.codegen.cpp.emit import ctype
from situc.resolve import ResolvedSchema


def generate(schema: ast.Schema, resolved: ResolvedSchema, cases: list[Case],
		basename: str, prefix: str = "situ") -> str:
	"""A standalone program for `basename.hpp`, from `basename`'s vectors.

	`prefix` is accepted and unused: C++ names its accessors by namespace and
	method, so there is nothing for a prefix to disambiguate, and one
	signature across the backends is what lets `cmd_gen_tests` dispatch
	without a special case.
	"""
	refuse_parameters(schema, {case.struct for case in cases})
	refuse_only_arguments(schema, resolved)

	seen: dict[str, Case] = {}
	for case in cases:
		symbol = _symbol(case)
		if symbol in seen:
			raise ValueError(
				f"vector `{case.struct} {case.name}` is declared twice")
		seen[symbol] = case

	for case in cases:
		_check(resolved, case)

	constants = enum_constants(schema, prefix)
	# `nested=True`: C++ reaches a nested field by declaring a view and
	# passing it, its accessor taking an out-parameter rather than
	# returning one -- where Rust chains an `expect` and Python chains a
	# dot. Three languages, three shapes, one question.
	# `text=True`: a text number's getter is fallible here as in C, taking
	# an out-parameter and returning an error, so it needs a block and the
	# out-parameter's type -- which is `cpp/emit.py`'s `ctype`, extracted
	# to a function for this rather than written a second time.
	compared, declined = tally(resolved, cases, constants, nested=True,
	                          text=True)
	lines = _preamble(basename, compared, declined)

	for case in cases:
		lines.extend(_case_body(resolved, constants, case))

	lines.extend(_main(cases))
	return "\n".join(lines) + "\n"


def _preamble(basename: str, compared: int,
		declined: dict[str, int]) -> list[str]:
	lines = [
		f"/* Generated by situc {__version__} from {basename}.situ and its"
		f" vectors -- do not edit.",
		" *",
		" * Golden-vector tests over the C++ accessors, read from the same",
		" * vector file every other `--target` reads. One file, so the",
		" * backends cannot be asked different questions about one schema.",
		" *",
		" * A standalone program: it names each failure and exits non-zero,",
		" * which is what a make target reads. No test framework, because",
		" * section 24's no-third-party rule is about what situ asks of the",
		" * people who use it as much as of itself.",
		" *",
		f" *     c++ -std=c++17 -I. {basename}_vectors.cpp situ.c \\",
		f" *         -o {basename}_vectors",
	]

	if compared:
		lines.extend([
			" *",
			f" * {compared} field expectation(s) are compared -- a scalar",
			" * against an integer and a byte run against its bytes,",
			" * through their getters.",
		])

	if declined:
		lines.extend([
			" *",
			f" * {sum(declined.values())} are NOT compared, and",
			" * `situc gen-tests --target c` compares them:",
			" *",
		])
		for why, count in sorted(declined.items()):
			lines.append(f" *   {count} -- {why}")
		lines.extend([
			" *",
			" * Each is still read and checked against the schema, so a",
			" * vectors file naming a field this schema does not have is",
			" * refused here too.",
		])

	lines.extend([
		" */",
		"",
		"#include <cstdint>",
		"#include <cstdio>",
		"#include <cstring>",
		"#include <vector>",
		"",
		f'#include "{basename}.hpp"',
		"",
		"static int situ_failures = 0;",
		"",
	])
	return lines


def _case_body(resolved: ResolvedSchema, constants: dict[str, int],
		case: Case) -> list[str]:
	name = _symbol(case)
	body = ", ".join(f"0x{byte:02X}" for byte in case.data)

	# A variable struct's `at` takes the message length and a fixed one's
	# does not, which is the C++ backend's own branch and not a second
	# reading of it. The Python half got this wrong for 13 of 27 schemas
	# before it was run (26.829), so it is written down here rather than
	# rediscovered.
	struct = resolved.structs[case.struct]
	extent = "" if struct.layout.is_fixed_size else ", length"

	return [
		f"static void {name}(void)",
		"{",
		f"\tstd::uint8_t bytes[] = {{{body}}};",
		"\tconst std::uint32_t length ="
		" static_cast<std::uint32_t>(sizeof bytes);",
		"\t::situ::rt::message msg(bytes, length);",
		f"\t::situ::{case.struct} view;",
		"",
		f"\tif (::situ::{case.struct}::at(msg, 0{extent}, view)"
		" != ::situ::rt::err::ok) {",
		f"\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
		" the bytes take no view\\n\");",
		"\t\tsitu_failures++;",
		"\t\treturn;",
		"\t}",
		"\tif (view.validate() != ::situ::rt::err::ok) {",
		f"\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
		" validation refuses them\\n\");",
		"\t\tsitu_failures++;",
		"\t\treturn;",
		"\t}",
		*_expectations(resolved, constants, case),
		"}",
		"",
	]


def _reach(resolved: ResolvedSchema, case: Case,
		path: str) -> tuple[list[str], str, str]:
	"""The declarations that reach a nested field, the holder, and the leaf.

	C++'s nested accessor takes an out-parameter and returns an error, so
	each level is a declaration and a check -- where Rust chains an `expect`
	and Python chains a dot.

	An early `return` on failure, which is what the view and validate
	checks above already do: a case that cannot reach a nested view has
	nothing useful to say about the rest of its fields. And the message
	names the LEVEL rather than the case, because a vector whose bytes take
	a view can still fail to reach a nested one -- a bounds check per level
	is what section 12.3 asks for -- and "`one` failed" would not say
	which.
	"""
	parts = path.split(".")
	if len(parts) == 1:
		return ([], "view", parts[0])

	lines: list[str] = []
	holder = "view"
	struct = case.struct
	for depth, step in enumerate(parts[:-1]):
		found = resolved.find(f"{struct}.{step}")
		assert found is not None, f"{struct}.{step}"
		inner = found.placement.type_name
		sub   = f"sub{depth}"

		lines.extend([
			f"\t\t::situ::{inner} {sub};",
			f"\t\tif ({holder}.{c_name(step)}({sub})"
			" != ::situ::rt::err::ok) {",
			f"\t\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
			f" {step} is not reachable\\n\");",
			"\t\t\tsitu_failures++;",
			"\t\t\treturn;",
			"\t\t}",
		])
		holder = sub
		struct = inner

	return (lines, holder, parts[-1])


def _expectations(resolved: ResolvedSchema, constants: dict[str, int],
		case: Case) -> list[str]:
	"""What the vector says about each field, where this target can say it.

	A printed comparison rather than an `assert`: this suite has no
	framework and reports on a count, so a mismatch names the field and both
	numbers and then carries on to the next field. `assert` would abort and
	report one failure where there are several.

	Widened to `unsigned long long` for the compare and the print, because
	the getter's own type is whatever the field is -- `u8` through `u64` --
	and `-Wsign-compare` has an opinion about the narrow ones meeting a
	literal.
	"""
	lines: list[str] = []
	for path, value in case.expectations:
		raw = byte_run(resolved, case, path, value, nested=True)
		if raw is not None:
			if not lines:
				lines.append("")
			body = ", ".join(f"0x{byte:02X}" for byte in raw)
			# `::situ::rt::bytes` is a `span`, so `data()` and `size()` and
			# `memcmp`. Both halves compared, because a span of the right
			# bytes and the wrong length is not the run the vector names.
			reach, holder, leaf = _reach(resolved, case, path)
			lines.extend([
				"\t{",
				*reach,
				f"\t\tconst auto got = {holder}.{c_name(leaf)}();",
				f"\t\tstatic const std::uint8_t want[] = {{{body}}};",
				"",
				"\t\tif (got.size() != sizeof want",
				"\t\t    || std::memcmp(got.data(), want, sizeof want) != 0) {",
				f"\t\t\tstd::printf(\"FAIL {case.struct} {case.name}: {path}"
				f" is not the {len(raw)} bytes the vector names\\n\");",
				"\t\t\tsitu_failures++;",
				"\t\t}",
				"\t}",
			])
			continue

		literal = comparable(resolved, case, path, value, constants,
		                     nested=True, text=True)
		if literal is None:
			continue
		if not lines:
			lines.append("")
		reach, holder, leaf = _reach(resolved, case, path)

		# A text number's getter is fallible: an out-parameter and a code,
		# where every other getter here returns the value. So its own block,
		# and the parse failing is a finding rather than a mismatch -- a
		# vector whose digits are not digits is a vector claiming something
		# the bytes do not say.
		found = resolved.find(f"{case.struct}.{path}")
		if (found is not None and found.placement.radix is not None
		    and found.placement.scalar is not None):
			if not lines:
				lines.append("")
			kind = ctype(found.placement.scalar)
			lines.extend([
				"\t{",
				*reach,
				f"\t\t{kind} got = 0;",
				"",
				f"\t\tif ({holder}.{c_name(leaf)}(got)"
				" != ::situ::rt::err::ok) {",
				f"\t\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
				f" {path} does not parse\\n\");",
				"\t\t\tsitu_failures++;",
				f"\t\t}} else if (static_cast<unsigned long long>(got)",
				f"\t\t           != static_cast<unsigned long long>"
				f"({literal})) {{",
				f"\t\t\tstd::printf(\"FAIL {case.struct} {case.name}:"
				f" {path} is %llu, expected %llu\\n\",",
				"\t\t\t\tstatic_cast<unsigned long long>(got),",
				f"\t\t\t\tstatic_cast<unsigned long long>({literal}));",
				"\t\t\tsitu_failures++;",
				"\t\t}",
				"\t}",
			])
			continue

		got = f"static_cast<unsigned long long>({holder}.{c_name(leaf)}())"
		want = f"static_cast<unsigned long long>({literal})"
		if reach:
			# A scope, because the sub-view is a declaration and the flat
			# form has none.
			lines.extend(["\t{", *reach,
			              f"\t\tif ({got} != {want}) {{",
			              f"\t\t\tstd::printf(\"FAIL {case.struct}"
			              f" {case.name}: {path} is %llu, expected"
			              f" %llu\\n\",",
			              f"\t\t\t\t{got}, {want});",
			              "\t\t\tsitu_failures++;",
			              "\t\t}",
			              "\t}"])
			continue
		lines.extend([
			f"\tif ({got} != {want}) {{",
			f"\t\tstd::printf(\"FAIL {case.struct} {case.name}: {path}"
			f" is %llu, expected %llu\\n\",",
			f"\t\t\t{got}, {want});",
			"\t\tsitu_failures++;",
			"\t}",
		])
	return lines


def _main(cases: list[Case]) -> list[str]:
	lines = ["int main(void)", "{"]
	for case in cases:
		lines.append(f"\t{_symbol(case)}();")

	lines.extend([
		"",
		f"\tstd::printf(\"%d of {len(cases)} vector(s) failed\\n\","
		" situ_failures);",
		"\treturn situ_failures == 0 ? 0 : 1;",
		"}",
	])
	return lines

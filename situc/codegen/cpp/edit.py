"""Owned decode against caller backing, in C++ (26.99).

C's shape with the pair replaced by the type the language already has:
`rt::const_bytes` is a pointer and a length, so a variable member is one
field here rather than two, and it is the same type the ordinary accessor
returns.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.c.edit import editable
from situc.codegen.c.names import c_name
from situc.codegen.cpp.names import class_name
from situc.layout import Placement
from situc.resolve import ResolvedSchema, ResolvedStruct
from situc.traverse import is_own_member, local_name

__all__ = ["generate"]


def _runs(struct: ResolvedStruct) -> list[Placement]:
	from situc.codegen.c.edit import _runs as runs_of
	return runs_of(struct)


def _scalar(placement: Placement) -> str:
	assert placement.scalar is not None
	bits  = max(8, placement.scalar.bits)
	width = 8 if bits <= 8 else 16 if bits <= 16 else 32 if bits <= 32 else 64
	return (f"std::int{width}_t" if placement.scalar.signed
	        else f"std::uint{width}_t")


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str) -> dict[str, str]:
	structs = editable(resolved)
	if not structs:
		return {}

	guard = f"SITU_{c_name(basename).upper()}_EDIT_HPP"
	lines = [
		f"/* Generated by situc from {basename}.situ -- do not edit.",
		" *",
		" * Owned decode against backing you supply: rung 2. A variable",
		" * member is one `rt::const_bytes` rather than a pointer and a",
		" * length, which is the type the ordinary accessor already returns.",
		" *",
		" * Nothing here allocates. A separate header -- a rung adds files",
		" * rather than changing them (decision 0032).",
		" */",
		"",
		f"#ifndef {guard}",
		f"#define {guard}",
		"",
		"#include <cstdint>",
		"",
		f"#include \"{basename}.hpp\"",
		"",
		"namespace situ {",
		"",
	]

	for struct in structs:
		held = class_name(struct)
		name = f"{c_name(struct.name)}_owned"
		runs = _runs(struct)
		members = [entry.placement for entry in struct.entries
		           if is_own_member(struct, entry.placement)]

		fields = []
		for placement in members:
			local = c_name(local_name(struct, placement))
			if placement in runs:
				fields.append(f"\t::situ::rt::const_bytes {local};"
				              f"\t/* into your backing */")
			elif placement.scalar is not None and placement.array_count is None:
				fields.append(f"\t{_scalar(placement)} {local};")

		lines += [
			f"/** `{struct.name}`, decoded into storage you own.",
			" *",
			" * The message may go afterwards; the backing is yours and",
			" * outlives it, which is the whole trade.",
			" */",
			f"struct {name} {{",
			*fields,
			"",
			"\t/** How many bytes the variable members need. */",
			"\t[[nodiscard]] static ::situ::rt::err backing(",
			"\t\t\tconst std::uint8_t *data, std::uint32_t len,",
			"\t\t\tstd::uint32_t &need) noexcept",
			"\t{",
			f"\t\t::situ::rt::message owner(const_cast<std::uint8_t *>(data), len);",
			f"\t\t::situ::{held} view;",
			f"\t\tconst ::situ::rt::err err = ::situ::{held}::at(owner, 0u, len,",
			"\t\t                                                 view);",
			"\t\tif (err != ::situ::rt::err::ok) {",
			"\t\t\treturn err;",
			"\t\t}",
			"",
			"\t\tneed = 0u;",
		]
		for placement in runs:
			local = c_name(local_name(struct, placement))
			lines.append(f"\t\tneed += static_cast<std::uint32_t>("
			             f"view.{local}().size());")
		lines += [
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
			"",
			"\t/** Copy into your backing. `err::bounds` where it does not fit. */",
			"\t[[nodiscard]] ::situ::rt::err decode(",
			"\t\t\tconst std::uint8_t *data, std::uint32_t len,",
			"\t\t\tstd::uint8_t *store, std::uint32_t cap) noexcept",
			"\t{",
			"\t\tstd::uint32_t need = 0u;",
			"\t\t::situ::rt::err err = backing(data, len, need);",
			"\t\tif (err != ::situ::rt::err::ok) {",
			"\t\t\treturn err;",
			"\t\t}",
			"\t\tif (need > cap) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			f"\t\t::situ::rt::message owner(const_cast<std::uint8_t *>(data), len);",
			f"\t\t::situ::{held} view;",
			f"\t\terr = ::situ::{held}::at(owner, 0u, len, view);",
			"\t\tif (err != ::situ::rt::err::ok) {",
			"\t\t\treturn err;",
			"\t\t}",
			"",
			"\t\tstd::uint32_t at = 0u;",
		]
		for placement in members:
			local = c_name(local_name(struct, placement))
			if placement in runs:
				lines += [
					f"\t\t{{",
					f"\t\t\tconst ::situ::rt::bytes src = view.{local}();",
					"\t\t\tfor (std::size_t i = 0u; i < src.size(); i++) {",
					"\t\t\t\tstore[at + i] = src.data()[i];",
					"\t\t\t}",
					f"\t\t\t{local} = ::situ::rt::const_bytes(store + at,",
					"\t\t\t                                  src.size());",
					"\t\t\tat += static_cast<std::uint32_t>(src.size());",
					"\t\t}",
				]
			elif placement.scalar is not None and placement.array_count is None:
				lines.append(f"\t\t{local} = view.{local}();")

		lines += ["\t\t(void)at;", "\t\treturn ::situ::rt::err::ok;", "\t}",
		          "};", ""]

	lines += ["}  /* namespace situ */", "", f"#endif /* {guard} */"]
	return {f"{basename}_edit.hpp": "\n".join(lines) + "\n"}

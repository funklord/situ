@dataclass
class Generated:
	"""What a schema compiles to. One file: C++ needs no second one here."""

	header: str
	basename: str
	warnings: list[Diagnostic] = field(default_factory=list)

	def files(self) -> dict[str, str]:
		return {f"{self.basename}.hpp": self.header}


def generate(schema: ast.Schema, resolved: ResolvedSchema, basename: str,
		namespace: str = "situ", materialize: bool = False) -> Generated:
	# Before anything is emitted: a class a member has taken the name of is
	# renamed and aliased, and the one case where that rename has nowhere to go
	# is a diagnostic rather than a header no compiler accepts.
	check_collisions(schema, resolved)

	return Generated(
		header   = Emitter(schema, resolved, basename, namespace,
		                   materialize).header(),
		basename = basename,
	)


class Emitter:
	def __init__(self, schema: ast.Schema, resolved: ResolvedSchema,
			basename: str, namespace: str, materialize: bool = False) -> None:
		self.schema    = schema
		self.resolved  = resolved
		self.basename  = basename
		self.namespace = namespace
		self.enums     = {decl.name: decl for decl in schema.enums()}
		self.codecs    = {decl.name: decl for decl in schema.codecs()}
		self.markers   = {decl.name: decl for decl in schema.markers()}
		self.structs   = set(resolved.structs)
		#: Emit the second accessor family (decision 0022): the consumer's
		#: choice rather than the schema's, and off unless asked for.
		self.materialize = materialize

	# -- the file ------------------------------------------------------

	def header(self) -> str:
		guard = f"SITU_{c_name(self.basename).upper()}_HPP"
		lines = [
			f"/* Generated by situc from {self.basename}.situ -- do not edit.",
			" *",
			" * The operations below are exactly the ones this schema's capability",
			" * vectors support. Where one is missing, a comment says why.",
			" */",
			"",
			f"#ifndef {guard}",
			f"#define {guard}",
			"",
			'#include "situ.hpp"',
			"",
			*self._codec_prototypes(),
			f"namespace {self.namespace} {{",
		]

		for decl in self.schema.enums():
			lines.extend(self._enum(decl))

		for name in self._struct_order():
			lines.extend(self._struct(self.resolved.structs[name]))

		lines.extend(["", f"}}  /* namespace {self.namespace} */", "",
		              f"#endif /* {guard} */"])
		# Twice, because this backend documents two levels. A member sits at
		# one tab and a class at none, and running it for members alone left
		# every class undocumented -- which Doxygen said out loud the first
		# time anybody ran it: "Compound situ::flags is not documented".
		return "\n".join(
			extractable(extractable(lines, indent="\t"))) + "\n"

	def _struct_order(self) -> list[str]:
		"""Structs before the structs that contain them.

		A class has to be complete before another names it by value, which C
		sidesteps by handing out offsets rather than types. Declaration order in
		the schema is not required to respect containment, so it is sorted here
		rather than demanded of the author.
		"""
		return containment_order(self.resolved.structs, sorted(self.structs))

	# -- enums ---------------------------------------------------------

	def _enum(self, decl: ast.EnumDecl) -> list[str]:
		backing = decl.backing.scalar
		assert backing is not None
		values = self.resolved.layout.env.enums[decl.name]

		lines = [
			"",
			f"/* enum {decl.name} : {decl.backing.name}"
			f" -- unknown values are {decl.effective_default.value} */",
			f"enum class {c_name(decl.name)} : {self._ctype(backing)} {{",
		]
		lines.extend(f"\t{c_name(member.name)} = {values[member.name]},"
		             for member in decl.members)
		lines.append("};")

		# Section 8.7 makes `default = error` the default and says unknown
		# values are rejected on parse. Every backend emitted that as a comment
		# and validated nothing until now.
		name = c_name(decl.name)
		lines.extend([
			"",
			f"/* Whether a value names a member of {decl.name} (section 8.7). */",
			f"constexpr bool is_known({name} value) noexcept",
			"{",
			"\tswitch (value) {",
			*[f"\tcase {name}::{c_name(member.name)}:" for member in decl.members],
			"\t\treturn true;",
			"\tdefault:",
			"\t\treturn false;",
			"\t}",
			"}",
		])
		return lines

	# -- structs -------------------------------------------------------

	def _struct(self, struct: ResolvedStruct) -> list[str]:
		layout = struct.layout
		name   = class_name(struct)

		if layout.register is not None:
			return [*self._register(struct), *self._alias(struct)]

		lines = ["", *self._struct_comment(struct),
		         f"class {name} : public ::situ::rt::view {{", "public:"]
		lines.extend(self._acquire(struct))
		lines.extend([
			"",
			f"\tconstexpr {name}() noexcept = default;",
			f"\texplicit constexpr {name}(situ_view_t raw) noexcept"
			f" : ::situ::rt::view(raw) {{}}",
		])
		lines.extend(self._dirty_constants(struct))

		for entry in own_entries(struct):
			lines.extend(self._explained(struct, entry))

		lines.extend(self._region_runs(struct))
		lines.extend(self._nested_text_values(struct))

		lines.extend(self._covered_nested_setters(struct))
		lines.extend(self._arm_accessors(struct))
		lines.extend(self._offsets(struct))
		lines.extend(self._extent_method(struct))
		lines.extend(self._required(struct))
		lines.extend(self._invariants(struct))
		lines.extend(self._validate(struct))
		lines.extend(self._gates(struct))
		lines.append("};")
		lines.extend(self._alias(struct))
		return lines

	def _alias(self, struct: ResolvedStruct) -> list[str]:
		"""The schema's name for a class that could not be called that.

		Emitted only where a member has taken the name (`cpp/names.py`). It is
		a namespace-scope alias rather than a base class or a subclass because
		it has to be the same type: a caller writes `situ::framed` and a
		containing class returns one, and neither is aware that anything was
		renamed.
		"""
		if not renamed(struct):
			return []

		name = c_name(struct.name)
		return [
			"",
			f"/* `{name}` is what the schema calls this, and what to write.",
			" *",
			f" * The class is `{class_name(struct)}` because a member of it is"
			f" called `{name}` --",
			" * an accessor this schema asked for, or one every view has. C++"
			" declares a",
			" * class's own name inside the class, so no member may take it."
			" These two",
			" * names are one type. */",
			f"using {name} = {class_name(struct)};",
		]

	def _register(self, struct: ResolvedStruct) -> list[str]:
		"""A memory-mapped register (section 15).

		The whole-word read and the field composition are separate types,
		because they are separate things: a `word` is a copy of the bits and a
		register is a place on a bus. That split is what section 15's headline
		asks for -- where a field cannot be written alone, the remedy is to
		compose the whole word and write it once, and here that remedy is the
		only shape the API has.

		`with_x()` returns a new word rather than mutating, so composing reads
		as one expression and the write is visibly one transaction:

		    r.write(r.read().with_enable(1).with_mode(3));
		"""
		info = struct.layout.register
		assert info is not None

		name  = class_name(struct)
		word  = self._ctype_for_bits(info.width)
		lines = [
			"",
			f"/* register {struct.name}"
			+ (f" at {info.address:#x}" if info.address is not None else "")
			+ f": {info.width} bits, {info.access_width}-bit bus access"
			+ (", volatile" if info.volatile else "")
			+ (", no read-modify-write" if info.no_rmw else "") + ". */",
			f"class {name} {{",
			"public:",
		]
		if info.address is not None:
			lines.append(f"\tstatic constexpr std::uint32_t address = {info.address:#x};")
		lines.extend([
			f"\tstatic constexpr std::uint32_t width = {info.width};",
			"",
			"\t/* A word: a copy of the bits, not the register. Composing one",
			"\t * costs no bus transaction; writing it costs exactly one. */",
			"\tclass word {",
			"\tpublic:",
			f"\t\tconstexpr explicit word({word} raw) noexcept : raw_(raw) {{}}",
			f"\t\tconstexpr {word} raw() const noexcept {{ return raw_; }}",
		])

		for entry in own_entries(struct):
			lines.extend(self._register_field(entry, word))

		lines.extend([
			"",
			"\tprivate:",
			f"\t\t{word} raw_;",
			"\t};",
			"",
			f"\texplicit constexpr {name}(volatile std::uint8_t *block) noexcept",
			"\t\t: block_(block) {}",
			"",
		])
		lines.extend(self._register_access(struct, info, word))
		lines.extend([
			"",
			"private:",
			f"\tvolatile {word} *at() const noexcept",
			"\t{",
			f"\t\treturn reinterpret_cast<volatile {word} *>(block_ + "
			f"{info.address or 0:#x});",
			"\t}",
			"",
			"\tvolatile std::uint8_t *block_;",
			"};",
		])
		return lines

	def _register_access(self, struct: ResolvedStruct, info: object,
			word: str) -> list[str]:
		"""Read, write, and the operations that are neither."""
		lines = [
			"\t[[nodiscard]] word read() const noexcept",
			"\t{",
			"\t\treturn word(*at());",
			"\t}",
			"",
			"\tvoid write(word value) const noexcept",
			"\t{",
			"\t\t*at() = value.raw();",
			"\t}",
		]

		for entry in own_entries(struct):
			placement = entry.placement
			mode      = placement.access_mode
			if placement.kind == "reserved" or placement.scalar is None:
				continue

			name  = c_name(local_name(struct, placement))
			shift = placement.offset_bits or 0
			mask  = (1 << placement.scalar.bits) - 1

			if placement.on_write is not ast.SideEffect.NONE:
				lines.extend([
					"",
					f"\t/* {placement.path} has on_write ="
					f" {placement.on_write.value}: the write is the event, and",
					"\t * the value written is not a value the field then holds. */",
					f"\tvoid trigger_{name}() const noexcept",
					"\t{",
					f"\t\t*at() = static_cast<{word}>({mask:#x}u << {shift}u);",
					"\t}",
				])
			elif mode is ast.AccessMode.W1C:
				lines.extend([
					"",
					f"\t/* {placement.path} is w1c: writing a one clears it, so",
					"\t * this is a clear rather than an assignment. Every other",
					"\t * bit is left zero, which leaves neighbouring w1c fields",
					"\t * alone. */",
					f"\tvoid clear_{name}() const noexcept",
					"\t{",
					f"\t\t*at() = static_cast<{word}>({mask:#x}u << {shift}u);",
					"\t}",
				])
		return lines

	def _register_field(self, entry: Resolved, word: str) -> list[str]:
		"""A field's getter and composer, if its access mode admits them."""
		placement = entry.placement
		scalar    = placement.scalar

		if placement.kind == "reserved":
			return ["",
			        f"\t\t/* {placement.path} is reserved: no accessor, and its",
			        "\t\t * bits are carried through a compose untouched. */"]
		if scalar is None:
			return []

		name  = c_name(placement.path.rsplit(".", 1)[-1])
		mode  = placement.access_mode or ast.AccessMode.RW
		shift = placement.offset_bits or 0
		mask  = (1 << scalar.bits) - 1
		ctype = self._field_ctype(placement)
		lines = ["", f"\t\t/* {placement.path}: {mode.value},"
		         f" bits {shift}..{shift + scalar.bits - 1} */"]

		if mode.readable:
			raw = f"(raw_ >> {shift}u) & {mask:#x}u"
			cast = (f"static_cast<{ctype}>({raw})" if placement.type_name in self.enums
			        else f"static_cast<{ctype}>({raw})")
			lines.extend([
				f"\t\t[[nodiscard]] constexpr {ctype} {name}() const noexcept",
				"\t\t{",
				f"\t\t\treturn {cast};",
				"\t\t}",
			])
		else:
			lines.append(f"\t\t/* No {name}(): the mode is"
			             f" {mode.value}, so a read returns nothing the field holds. */")

		if mode.writable and mode.is_assignment:
			value = ("static_cast<std::uint32_t>(value)"
			         if placement.type_name in self.enums else "value")
			lines.extend([
				f"\t\t[[nodiscard]] constexpr word with_{name}({ctype} value)"
				f" const noexcept",
				"\t\t{",
				f"\t\t\treturn word(static_cast<{word}>(",
				f"\t\t\t\t(raw_ & ~static_cast<{word}>({mask:#x}u << {shift}u))",
				f"\t\t\t\t| ((static_cast<{word}>({value}) & {mask:#x}u)"
				f" << {shift}u)));",
				"\t\t}",
			])
		elif mode.writable:
			lines.append(f"\t\t/* No with_{name}(): `{mode.value}` is not an"
			             f" assignment. See the register's own method. */")
		else:
			lines.append(f"\t\t/* No with_{name}(): the mode is {mode.value}. */")
		return lines

	def _ctype_for_bits(self, bits: int) -> str:
		return f"std::uint{_storage_width(bits)}_t"

	# -- obligations (sections 14.2 and 16.1) ---------------------------

	def _dirty_constants(self, struct: ResolvedStruct) -> list[str]:
		"""One bit per obligation over this struct's bytes.

		Scoped constants rather than the C backend's macros: the numbering is
		shared with C (`traverse.obligations`) but the spelling need not be,
		and a macro named after a member is exactly the sort of thing that
		collides with a member somewhere else in a translation unit.
		"""
		held = obligations(self.schema, struct)
		if not held:
			return []

		lines = ["",
		         "\t/* Dirty bits. A covered write sets one; the message refuses",
		         "\t * to be transmittable until it is cleared -- a tag by being",
		         "\t * recomputed and finalized, a derived field by its recompute. */"]
		lines.extend(
			f"\tstatic constexpr std::uint32_t dirty_{c_name(one.name)}"
			f" = {hex(1 << one.bit)}u;"
			for one in held)
		lines.append(
			f"\tstatic constexpr std::uint32_t dirty_mask = {hex((1 << len(held)) - 1)}u;")
		return lines

	def _invariants(self, struct: ResolvedStruct) -> list[str]:
		"""A derived field, and the one thing allowed to write it.

		The lattice has already refused the plain setter -- `mutate` is
		Immutable -- so without this the schema could state a relationship and
		never satisfy it.

		`recompute_x()` takes the message, as every covered write here does:
		it clears a dirty bit, and the bit lives on the message rather than on
		the view.
		"""
		lines: list[str] = []

		for decl in derived_by(self.schema, struct):
			field = decl.derived.partition(".")[2]
			entry = next((e for e in struct.entries
			              if e.placement.path == f"{struct.name}.{field}"), None)
			if entry is None or entry.placement.scalar is None:
				continue

			name  = c_name(field)
			value = invariant_expression(struct, decl.expr, self)
			if value is None:
				lines.extend([
					"",
					f"\t/* No recompute_{name}(): this backend cannot evaluate",
					f"\t * `{unparse_expr(decl.expr)}` at run time. The refusal to",
					"\t * write the field directly still stands, so the invariant",
					"\t * cannot be broken -- only left unsatisfiable here. */",
				])
				continue

			scalar = entry.placement.scalar
			stored = f"static_cast<{self._ctype(scalar)}>({value})"

			lines.extend([
				"",
				f"\t/* {decl.derived} == {unparse_expr(decl.expr)}",
				"\t *",
				f"\t * Writing anything the right side reads sets dirty_{name},",
				"\t * and the message refuses to be transmittable until this",
				"\t * recomputes (section 16.1). */",
				f"\tvoid recompute_{name}(::situ::rt::message &owner) noexcept",
				"\t{",
				f"\t\t{self._store(scalar, entry.placement, stored)}",
				f"\t\towner.clear_dirty(dirty_{name});",
				"\t}",
				"",
				f"\t[[nodiscard]] bool {name}_is_stale("
				"const ::situ::rt::message &owner) const noexcept",
				"\t{",
				f"\t\treturn owner.is_stale(dirty_{name});",
				"\t}",
			])

		return lines

	# -- invariant.Terms, in C++ ----------------------------------------

	def literal(self, value: int) -> str:
		return f"{value}u"

	def binary(self, op: str, left: str, right: str) -> str:
		return f"({left} {op} {right})"

	def offset(self, struct: ResolvedStruct, placement: Placement) -> str | None:
		return (f"{placement.offset_bytes}u" if placement.offset_bits is not None
		        else None)

	def size(self, struct: ResolvedStruct, placement: Placement) -> str | None:
		if placement.is_fixed_size:
			return f"{placement.size_bits // BITS_PER_BYTE}u"
		return self._length_expression(struct, placement)

	def count(self, struct: ResolvedStruct, placement: Placement) -> str | None:
		return self._count_expression(struct, placement)

	def _struct_comment(self, struct: ResolvedStruct) -> list[str]:
		layout = struct.layout
		if layout.is_fixed_size:
			return [f"/* struct {struct.name}: {layout.size_bytes} bytes, fixed. */"]

		return [
			f"/* struct {struct.name}: {layout.size_bytes} bytes and up, so its",
			" * extent is the caller's to establish -- a length it knows from the",
			" * frame this arrived in. That is the one bounds check, and",
			" * everything below trusts it. */",
		]

	def _acquire(self, struct: ResolvedStruct) -> list[str]:
		"""The factory. Fixed-size structs know their own extent; the rest are
		told it, because nothing in the bytes says where the frame ends."""
		layout = struct.layout
		name   = class_name(struct)

		if layout.is_fixed_size:
			return [
				f"\tstatic constexpr std::uint32_t size_bytes = {layout.size_bytes};",
				"",
				"\t[[nodiscard]] static ::situ::rt::err at(::situ::rt::message &owner,",
				f"\t\t\tstd::uint32_t offset, {name} &out) noexcept",
				"\t{",
				"\t\tsitu_view_t raw;",
				"\t\tconst situ_err_t e = situ_view_at(owner.raw(), offset,"
				" size_bytes, &raw);",
				"",
				"\t\tif (e == SITU_OK) {",
				f"\t\t\tout = ::{self.namespace}::{name}(raw);",
				"\t\t}",
				"\t\treturn static_cast<::situ::rt::err>(e);",
				"\t}",
			]

		return [
			f"\tstatic constexpr std::uint32_t size_min = {layout.size_bytes};",
			"",
			"\t/* The one bounds check, and the minimum is part of it: every",
			"\t * constant-offset accessor below trusts that the fixed members",
			"\t * are here (20.2), which a shorter frame does not carry. C and",
			"\t * Rust refused one from the start and this did not, so a"
			" 55-byte",
			"\t * `packet` was a view here and an error there -- found by"
			" handing",
			"\t * random bytes to all four and diffing what they said. */",
			"\t[[nodiscard]] static ::situ::rt::err at(::situ::rt::message &owner,",
			f"\t\t\tstd::uint32_t offset, std::uint32_t length,"
			f" {name} &out) noexcept",
			"\t{",
			"\t\tif (length < size_min) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			"\t\tsitu_view_t raw;",
			"\t\tconst situ_err_t e = situ_view_at(owner.raw(), offset,"
			" length, &raw);",
			"",
			"\t\tif (e == SITU_OK) {",
			f"\t\t\tout = ::{self.namespace}::{name}(raw);",
			"\t\t}",
			"\t\treturn static_cast<::situ::rt::err>(e);",
			"\t}",
		]

	def _gates(self, struct: ResolvedStruct) -> list[str]:
		"""Sealed regions, as a type that cannot be made without verifying.

		Section 14.3 asks that a sealed interior be unreachable before its tag
		verifies. C gets close: the accessors take a struct nobody but `_open`
		is supposed to fill in, and anybody determined enough can fill it in
		anyway. C++ can close it.

		The gate has no public constructor and no public factory. The only way
		to obtain one is to be handed it, inside a callback that runs only on
		the verified branch -- so there is no expression a caller can write
		that names a gate object outside that branch. Not discouraged: absent.
		"""
		regions = [entry.placement for entry in struct.entries
		           if entry.placement.kind == "sealed"]
		if not regions:
			return []

		lines: list[str] = []
		for region in regions:
			lines.extend(self._gate(struct, region))
		return lines

	def _gate(self, struct: ResolvedStruct, region: Placement) -> list[str]:
		name    = c_name(local_name(struct, region))
		holder  = f"{name}_gate"
		# Scalars only for now. A variable-length member inside a sealed region
		# needs its length read through the gate's own view, which is the next
		# piece rather than this one.
		inside  = [entry for entry in struct.entries
		           if entry.placement.sealed_by == region.name
		           and entry.placement.kind == "field"
		           # Not a field of an element of a run: the element type has
		           # its own accessors and the walk is how a caller reaches
		           # one. Emitted here it read element zero at the region's
		           # base, under a name that reads as the run's field.
		           and "[]" not in entry.placement.path
		           and entry.placement.scalar is not None
		           and entry.placement.array_count is None
		           and entry.placement.sized_by is None]

		rest    = [entry.placement for entry in struct.entries
		           if entry.placement.sealed_by == region.name
		           and entry.placement.kind == "field"
		           and (entry.placement.array_count is not None
		                or entry.placement.sized_by is not None)]
		secret  = [placement.path for placement in rest
		           if any(attr.name == "secret" for attr in placement.attrs)]
		skipped = [placement.path for placement in rest
		           if placement.path not in secret]

		lines = [
			"",
			f"\t/* {region.path}, sealed by {region.codec or 'a codec'}"
			f" and covered by {', '.join(region.covered_by) or 'a tag'}.",
			"\t *",
			"\t * This type has no public constructor and no public factory. A",
			f"\t * caller reaches the interior through with_{name}() below, which",
			"\t * runs the callback only once the tag has verified -- so there is",
			"\t * no expression that names one of these outside that branch.",
			"\t * Parsing attacker-controlled plaintext before authenticating it",
			"\t * is not discouraged here; it cannot be written. */",
			f"\tclass {holder} {{",
			"\tpublic:",
		]

		for entry in inside:
			lines.extend(self._gated_accessor(struct, entry))

		if not inside:
			lines.append("\t\t/* Nothing in this region has a scalar accessor. */")
		for path in secret:
			lines.extend(["",
			              f"\t\t/* {path} is [secret]: no debug accessor is",
			              "\t\t * generated for it at all (section 14.6). */"])
		for placement in rest:
			if placement.path in secret:
				continue
			lines.extend(self._gated_span(struct, placement))

		lines.extend([
			"",
			"\tprivate:",
			f"\t\tfriend class {class_name(struct)};",
			f"\t\texplicit constexpr {holder}(situ_view_t raw) noexcept"
			f" : raw_(raw) {{}}",
			"",
			"\t\tsitu_view_t raw_;",
			"\t};",
			"",
			f"\t/* Runs `fn` over the sealed interior, and only if `verified`.",
			"\t *",
			"\t * The result is whatever the callback needs it to be: it may",
			"\t * capture. What it may not do is outlive the check, because the",
			"\t * gate it is handed cannot be copied out of the namespace it has",
			"\t * no constructor in. */",
			"\ttemplate <typename F>",
			f"\t[[nodiscard]] ::situ::rt::err with_{name}(bool verified,"
			f" F &&fn) const",
			"\t{",
			"\t\tif (!verified) {",
			"\t\t\treturn ::situ::rt::err::tag;",
			"\t\t}",
			"",
			f"\t\tfn({holder}(raw()));",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		])
		return lines

	def _in_gate(self, struct: ResolvedStruct, text: str) -> str:
		"""One expression, moved from the struct's vocabulary into the gate's.

		Everything the expression machinery renders is written for the
		enclosing class: `base()` and `limit()` from the view it derives from,
		and a member call for every field an expression names. None of those
		resolve inside the gate, which is a nested class and has no enclosing
		object -- so the header did not compile the moment an interior member's
		offset depended on anything but a constant.

		Three sites each patched the two spellings they had met -- `base()`
		everywhere, `limit()` in two of the three -- and the rest went through
		untouched: `label_span()`, `n_len()`, `n_value()`, and `limit()` in the
		site that had not been told. Four symptoms, one cause, and a fifth was
		one schema away.

		So the rewrite happens once, from a list the struct itself supplies.
		The gate's `raw_` *is* the enclosing view -- `with_` hands it `raw()` --
		so an outer object built from it answers exactly what the enclosing
		object would, and the accessors keep their meaning rather than being
		re-derived here.
		"""
		owner = f"{class_name(struct)}(raw_)"

		# The accessor names this struct emits, from its members rather than
		# from a list somebody keeps current: a stem per member, and the
		# suffixes an expression can name it through. Anything outside this set
		# is a runtime helper (`situ_advance_u32`, `static_cast`) and is left
		# alone, which is why the set is derived rather than guessed at.
		# The *outer* members only. A name an interior expression could also
		# mean -- one of the gate's own accessors -- must not be prefixed:
		# `n()` inside the gate is the gate's `n()` where the region declares
		# one, and reaching for the enclosing object would be reaching for a
		# member that is not there.
		stems = {c_name(local_name(struct, held))
		         for held in own_members(struct)}
		if not stems:
			return text.replace("base()", "raw_.base") \
			           .replace("limit()", "raw_.limit")

		pattern = "|".join(re.escape(stem)
		                   for stem in sorted(stems, key=len, reverse=True))
		# The view's own two first, or the alternation below would leave them
		# for a member that happens to be called `base`.
		text = text.replace("base()", "raw_.base").replace("limit()", "raw_.limit")
		return re.sub(
			rf"\b(?:{pattern})(?:_span|_value|_len|_offset|_count|_extent)?\(\)",
			lambda hit: f"{owner}.{hit.group(0)}", text)

	def _gated_span(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""A byte run inside a sealed region.

		Its length is read through the gate's own view: the field that sizes it
		is plaintext at the same offsets, so the arithmetic is the struct's and
		only the view it is read through differs.
		"""
		scalar = placement.scalar
		if scalar is not None and indexed_elements(placement):
			return self._gated_elements(struct, placement, scalar)
		if scalar is None or scalar.bits != BITS_PER_BYTE:
			return ["", f"\t\t/* {placement.path}: element type"
			        f" {placement.type_name} is not reachable through the gate. */"]

		name  = self._gate_name(struct, placement)
		start = self._offset_expression(struct, placement)
		count = (str(placement.array_count) if placement.array_count is not None
		         else self._count_expression(struct, placement))

		if start is None or count is None:
			return ["", f"\t\t/* {placement.path}: this backend cannot resolve"
			        f" its extent. */"]

		# Rendered for the enclosing class, then moved into the gate's
		# vocabulary in one pass. This patched `base()` and left `limit()`
		# alone, so a run whose offset is clamped to the frame named a member
		# function of the view with no object to call it on.
		start = self._in_gate(struct, start)
		count = self._in_gate(struct, count)

		return [
			"",
			f"\t\t/* {placement.path}: {placement.array_count or placement.sized_by}"
			f" bytes, reached through the gate. */",
			f"\t\t[[nodiscard]] ::situ::rt::bytes {name}() const noexcept",
			"\t\t{",
			f"\t\t\treturn ::situ::rt::bytes(raw_.base + ({start}), {count});",
			"\t\t}",
		]

	def _gated_elements(self, struct: ResolvedStruct, placement: Placement,
			scalar: ScalarType) -> list[str]:
		"""A run of values wider than a byte inside a sealed region.

		The span above is not available to it -- the element is
		ValueConverted -- so it is the count and the indexed getter, read
		through the gate's own view. This backend declined it with a note,
		which was honest and left the interior unreadable; C emitted an
		indexed getter taking a plain view, which is the stage gate of 14.3
		with a hole in it.
		"""
		name  = self._gate_name(struct, placement)
		width = scalar.bits // BITS_PER_BYTE
		start = self._offset_expression(struct, placement)
		length = (str(placement.array_count * width)
		          if placement.array_count is not None
		          else self._length_expression(struct, placement))
		if start is None or length is None:
			return ["", f"\t\t/* {placement.path}: this backend cannot resolve"
			        f" its extent. */"]

		# Built in the enclosing class's vocabulary and moved into the gate's
		# once, at the end. Transforming the pieces first and then embedding
		# them is what produced `raw_.base.base` here and needed a third
		# `replace` to undo -- a rewriter reading its own output (invariant
		# 53).
		load   = self._in_gate(struct, self._load(
			scalar, placement, f"({start}) + index * {width}"))
		start  = self._in_gate(struct, start)
		length = self._in_gate(struct, length)

		return [
			"",
			f"\t\t/* {placement.path}: {scalar.name} elements, reached through",
			"\t\t * the gate and by index -- the bytes are not the values. */",
			"\t\t[[nodiscard]] std::uint32_t "
			f"{name}_count() const noexcept",
			"\t\t{",
			f"\t\t\treturn situ_min_u32({length},",
			f"\t\t\t\tsitu_remaining_u32(raw_.limit, {start})) / {width}u;",
			"\t\t}",
			f"\t\t[[nodiscard]] {self._ctype(scalar)} {name}"
			"(std::uint32_t index) const noexcept",
			"\t\t{",
			f"\t\t\treturn index < {name}_count() ? {load}"
			f" : static_cast<{self._ctype(scalar)}>(0);",
			"\t\t}",
		]

	def _gate_name(self, struct: ResolvedStruct, placement: Placement) -> str:
		"""What an interior member is called on the gate class.

		The member's local name with the region's stripped, which is the same
		derivation C spells out in full -- `situ_s_body_run_a_get` -- and the
		same one the differential drivers ask for. This took the *last* path
		component, which is the same answer for a member of the region and a
		different one for anything deeper: a field of an element of a run
		inside the region came out as `a()`, with nothing left to say which
		run it belongs to, and two runs in one region would have collided on
		it. The driver asked for `run_a()` and the header had no such member.
		"""
		local  = c_name(local_name(struct, placement))
		region = c_name(placement.sealed_by or "")
		if region and local.startswith(f"{region}_"):
			return local[len(region) + 1:]
		return local

	def _gated_accessor(self, struct: ResolvedStruct,
			entry: Resolved) -> list[str]:
		placement = entry.placement
		scalar    = placement.scalar
		assert scalar is not None

		name  = self._gate_name(struct, placement)
		ctype = self._field_ctype(placement)

		if any(attr.name == "secret" for attr in placement.attrs):
			return ["",
			        f"\t\t/* {name} is [secret]: no debug accessor is generated"
			        f" for it",
			        "\t\t * at all (section 14.6). */"]

		# Not `offset_bytes`: a scalar behind a variable-length member *inside*
		# the region has an offset the message decides, and asking for a
		# constant one crashed the compiler. Dropping such members instead
		# left them unreachable in three backends while C read them through
		# the gate -- and read them at the wrong place, which is how the
		# offset itself turned out to be wrong.
		where = (str(placement.offset_bytes) if placement.offset_bits is not None
		         else self._offset_expression(struct, placement))
		if where is None:
			return ["", f"\t\t/* {placement.path}: this backend cannot resolve",
			        "\t\t * where it starts. */"]
		# The offset is written for the enclosing class -- `label_span()` for a
		# member behind a delimited one, `n_value()` for a text driver -- and
		# none of those resolve in a nested class. One pass moves the whole
		# expression into the gate's vocabulary, at the end: transforming
		# `where` and then embedding it in the load rewrote what the first
		# pass had written, and produced `s(raw_).s(raw_).label_span()`.
		load  = self._in_gate(
			struct, self._raw_load(scalar, placement, f"base() + ({where})"))
		where = self._in_gate(struct, where)
		if placement.type_name in self.enums:
			load = f"static_cast<{ctype}>({load})"

		# Bounded where the offset is the message's, as every other dynamic
		# read is. The gate says the bytes have been authenticated; it does
		# not say the frame is long enough for what a length field claims.
		width = max(1, (scalar.bits + BITS_PER_BYTE - 1) // BITS_PER_BYTE)
		body  = ([f"\t\t\treturn {load};"] if placement.offset_bits is not None
		         else [
			f"\t\t\treturn situ_in_bounds(raw_, {where}, {width})",
			f"\t\t\t\t? {load}",
			f"\t\t\t\t: static_cast<{ctype}>(0);",
		])
		return [
			"",
			f"\t\t[[nodiscard]] {ctype} {name}() const noexcept",
			"\t\t{",
			*body,
			"\t\t}",
		]

	def _offset_expression(self, struct: ResolvedStruct,
			placement: Placement) -> str | None:
		"""Where a member starts, as a C++ expression.

		The same walk the C backend does: everything before the first
		variable-length member contributes a constant, and each variable one
		contributes its own length, read from the field that drives it. That
		field always has a static offset, because a size expression may only
		name a field declared before it.
		"""
		if placement.offset_bits is not None:
			return str(placement.offset_bits // BITS_PER_BYTE)

		parts = preceding_parts(struct, placement)
		if parts is None:
			return None

		constant = sum(part for part in parts if isinstance(part, int))
		terms: list[str] = []

		for other in parts:
			if isinstance(other, int):
				continue
			length = self._length_expression(struct, other)
			if length is None:
				return None
			terms.append(length)

		if not terms:
			return str(constant)

		# Saturating, term by term, for the reason `situ_advance_u32` exists:
		# one of these is a length the message chose, and `at + by` in
		# `std::uint32_t` wraps to an offset inside the frame pointing at the
		# wrong bytes. C's runtime is this backend's too, so it is the same
		# function rather than a second one that agrees today.
		folded = str(constant)
		for term in terms:
			folded = f"situ_advance_u32({folded}, {term}, limit())"
		return folded

	def _offset_body(self, struct: ResolvedStruct,
			placement: Placement) -> list[str] | None:
		"""The offset accessor's body, accumulating rather than summing.

		`_offset_expression` builds `0 + a_span() + b_span()`, and each of
		those re-derives its own base by rescanning everything before it, so
		the expression costs far more than the terms in it. An expression
		cannot hold a running total; this is the same sum written as
		statements, with each span given the offset already reached.
		"""
		if placement.offset_bits is not None:
			return None		# a constant; nothing to accumulate

		parts = preceding_parts(struct, placement)
		if parts is None:
			return None

		lines = ["\t\tstd::uint32_t at = 0;"]
		for other in parts:
			if isinstance(other, int):
				if other:
					lines.append(f"\t\tat += {other};")
				continue
			length = self._length_expression(struct, other, running="at")
			if length is None:
				return None
			# Saturating: a term is a length the message chose, and `at + by`
			# in `std::uint32_t` wraps to an offset that is inside the frame
			# and points at the wrong bytes. C's runtime is this one's too, so
			# the arithmetic is the same function (26.27).
			lines.append(f"\t\tat = situ_advance_u32(at, {length}, limit());")
		return [*lines, "\t\treturn at;"]

	# -- delimited members (section 8.6) --------------------------------

	def _delimiter_array(self, placement: Placement) -> str:
		"""The delimiter as a C++ initialiser list, inline at the call site.

		A `static constexpr` member would need an out-of-line definition
		before C++17 and is a stored object either way; this is two bytes in
		an argument, which the optimiser folds into the compare.
		"""
		delim = placement.delimiter
		assert delim is not None
		return ("(const std::uint8_t[]){"
		        + ", ".join(f"0x{byte:02X}" for byte in delim) + "}")

	def _scan_expression(self, placement: Placement, data: str,
			limit: str) -> str:
		delim = placement.delimiter
		assert delim is not None
		array = self._delimiter_array(placement)

		if placement.delimiter_quote is None and placement.delimiter_escape is None:
			return f"situ_scan({data}, {limit}, {array}, {len(delim)}u)"

		quote  = (f"{placement.delimiter_quote}u"
		          if placement.delimiter_quote is not None else "SITU_NO_BYTE")
		escape = (f"{placement.delimiter_escape}u"
		          if placement.delimiter_escape is not None else "SITU_NO_BYTE")
		return (f"situ_scan_relaxed({data}, {limit}, {array}, {len(delim)}u, "
		        f"{quote}, {escape})")

	def _delimited(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""The same three questions the C backend answers, as methods.

		`len()` is the content, `span()` is content plus delimiter -- what the
		next member's offset is computed from -- and `terminated()` is neither.
		Named identically to the C accessors on purpose: a reader moving
		between the two headers for one schema should not have to learn a
		second vocabulary for the same three numbers.
		"""
		assert placement.delimiter is not None
		name  = c_name(local_name(struct, placement))
		delim = placement.delimiter
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the scan starts. */"]

		# Saturating. `start` is a sum of length fields the message chooses,
		# so it can exceed the frame -- `u16 n` claiming 65535 in a ten-byte
		# view puts the scan base past the end, and an unsaturating
		# subtraction then hands `scan` about four billion bytes to search.
		# Measured as an AddressSanitizer SEGV before this line changed; the
		# C backend has been saturating here since the `[remaining]` fix and
		# these three were not.
		room  = f"situ_remaining_u32(limit(), {start})"
		limit = (room if placement.delimiter_cap is None
		         else f"situ_min_u32({placement.delimiter_cap}u, {room})")

		# The same two, over a base the caller hands in. Every loop that sums
		# offsets has the running total and called the plain form, which
		# re-derives the base by rescanning everything before this member --
		# so a sum over M members cost far more than the M scans it added up.
		# Measured on an eight-member record: 620ms, against 45ms in C once C
		# had this.
		room_at  = "situ_remaining_u32(limit(), at)"
		limit_at = (room_at if placement.delimiter_cap is None
		            else f"situ_min_u32({placement.delimiter_cap}u, {room_at})")

		# With `[trim]` the framing and the value are different numbers: the
		# scan says where the next member starts, and the value is what is
		# left after the whitespace at either end. Without it they are one.
		scan = f"{name}_raw_len" if placement.trimmed else f"{name}_len"

		lines = [
			"",
			f"\t/* {placement.path} runs to the first"
			f" {render_delimiter(delim)}. */",
			f"\t[[nodiscard]] std::uint32_t {name}_offset() const noexcept",
			"\t{",
			*(self._offset_body(struct, placement) or [f"\t\treturn {start};"]),
			"\t}",
			f"\t[[nodiscard]] std::uint32_t {scan}_from(std::uint32_t at)"
			" const noexcept",
			"\t{",
			f"\t\treturn {self._scan_expression(placement, 'base() + at', limit_at)};",
			"\t}",
			f"\t[[nodiscard]] std::uint32_t {scan}() const noexcept",
			"\t{",
			f"\t\treturn {scan}_from({name}_offset());",
			"\t}",
			f"\t[[nodiscard]] bool {name}_terminated_from(std::uint32_t at)"
			" const noexcept",
			"\t{",
			f"\t\treturn {scan}_from(at) < ({limit_at});",
			"\t}",
			f"\t[[nodiscard]] bool {name}_terminated() const noexcept",
			"\t{",
			f"\t\treturn {name}_terminated_from({name}_offset());",
			"\t}",
			f"\t[[nodiscard]] std::uint32_t {name}_span_from(std::uint32_t at)"
			" const noexcept",
			"\t{",
			f"\t\treturn {scan}_from(at) + "
			f"({name}_terminated_from(at) ? {len(delim)}u : 0u);",
			"\t}",
			f"\t[[nodiscard]] std::uint32_t {name}_span() const noexcept",
			"\t{",
			f"\t\treturn {name}_span_from({name}_offset());",
			"\t}",
		]

		if placement.trimmed:
			lines.extend([
				"\t/* `[trim]`: the whitespace at either end is framing rather",
				"\t * than value, so the span above is unchanged. */",
				f"\t[[nodiscard]] std::uint32_t {name}_len() const noexcept",
				"\t{",
				f"\t\treturn situ_trim_len(base() + {name}_offset(), {scan}());",
				"\t}",
			])

		value_at = (f"base() + {name}_offset()" if not placement.trimmed else
		            f"base() + {name}_offset() + situ_trim_start("
		            f"base() + {name}_offset(), {scan}())")

		if placement.radix is None:
			lines.extend([
				f"\t[[nodiscard]] ::situ::rt::const_bytes {name}() const noexcept",
				"\t{",
				f"\t\treturn ::situ::rt::const_bytes({value_at}, {name}_len());",
				"\t}",
				"",
				f"\t/* Whether {placement.path} is a given token, compared "
				+ ("folding ASCII case." if placement.case_insensitive
				   else "byte for byte."),
				"\t *",
				"\t * The length is checked first, so a prefix is not a match --",
				"\t * which is what a `strncmp` against a literal makes it. */",
				f"\t[[nodiscard]] bool {name}_eq(::situ::rt::const_bytes other)"
				" const noexcept",
				"\t{",
				f"\t\treturn {'situ_ascii_ci_eq' if placement.case_insensitive else 'situ_bytes_eq'}"
				f"({value_at}, {name}_len(),",
				"\t\t\tother.data(), static_cast<std::uint32_t>(other.size()))"
				" != 0;",
				"\t}",
			])
			return lines

		return lines + self._text_number(struct, placement, value_at)

	def _text_number(self, struct: ResolvedStruct, placement: Placement,
			value_at: str) -> list[str]:
		"""A number written as digits, read through something that can fail.

		`err` and an out-parameter rather than the value, alone among the
		getters here: every other conversion is total, and a decimal parse is
		not. `[[nodiscard]]` is what stops the error being dropped, which is
		one of the three things this backend enforces that C can only
		document.
		"""
		assert placement.radix is not None
		scalar = placement.scalar
		assert scalar is not None

		name  = c_name(local_name(struct, placement))
		ctype = self._ctype(scalar)
		limit = (1 << scalar.bits) - 1

		return [
			f"\t/* Digits, in the range of {scalar.name}. The only getter here",
			"\t * that can fail, which is what `repr = TextConverted` means. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}({ctype} &out) const noexcept",
			"\t{",
			"\t\tstd::uint64_t value;",
			"",
			f"\t\tif (situ_parse_uint({value_at}, {name}_len(),"
			f" {placement.radix}u, {limit}u, &value) != 0) {{",
			"\t\t\treturn ::situ::rt::err::constraint;",
			"\t\t}",
			f"\t\tout = static_cast<{ctype}>(value);",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
			f"\t/* The same digits where an error cannot be returned: the offset",
			"\t * arithmetic after this field is not fallible. `validate`",
			"\t * refuses a frame whose digits are not digits, so a validated",
			"\t * one always parses here. */",
			f"\t[[nodiscard]] {ctype} {name}_value() const noexcept",
			"\t{",
			"\t\tstd::uint64_t value = 0u;",
			"",
			f"\t\t(void)situ_parse_uint({value_at}, {name}_len(),"
			f" {placement.radix}u, {limit}u, &value);",
			f"\t\treturn static_cast<{ctype}>(value);",
			"\t}",
		]


	def _run_index(self, struct: ResolvedStruct, placement: Placement,
			walk: list[str], cond: str | None, inner: str) -> list[str]:
		"""The second family for a run: element offsets, resolved once (0022).

		The C backend's shape, because this one shares its constraint: a view
		is a value, nothing allocates, and the storage has to be the
		caller's. `max N` bounds the array, so a run without one gets a note
		saying what to add. Python needs no cap for the same feature, its
		list being the language's -- one decision, a different construct in
		each.
		"""
		if not self.materialize:
			return []

		cap = placement.repeat_cap or placement.delimiter_cap
		name = c_name(local_name(struct, placement))
		if cap is None:
			return [
				"",
				f"\t/* No index for {placement.path}: the run has no `max`, so",
				"\t * how many offsets to hold is not a number this knows and",
				"\t * the array would have to be allocated. Add `max N`. */",
			]

		return [
			"",
			f"\t/* Where each element of {placement.path} starts.",
			"\t *",
			"\t * The map calls this run `access = Sequential`: reaching",
			"\t * element N means reading the N-1 before it, so the indexed",
			"\t * accessor above walks from the base on every call. Building",
			"\t * this is one pass; every lookup after it is arithmetic. */",
			f"\tstruct {name}_index {{",
			"\t\tstd::uint32_t count;",
			"\t\t/* One more than `count`: the last is where the run ends, so",
			"\t\t * an element's size is the gap to its neighbour. */",
			f"\t\tstd::uint32_t start[{cap}u + 1u];",
			"\t};",
			"",
			f"\t[[nodiscard]] {name}_index {name}_indexed() const noexcept",
			"\t{",
			f"\t\t{name}_index out{{}};",
			"",
			*walk,
			"\t\t\tout.start[n] = at;",
			"\t\t\tat += size;",
			"\t\t\tn  += 1;",
			*([] if cond is None else [
				f"\t\t\tif (!({cond})) {{",
				"\t\t\t\tbreak;",
				"\t\t\t}",
			]),
			f"\t\t\tif (n == {cap}u) {{",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			"\t\t}",
			"",
			"\t\tout.count = n;",
			"\t\tout.start[n] = at;",
			"\t\treturn out;",
			"\t}",
			"",
			"\t/* Element `index`, in constant time. Arithmetic rather than a",
			"\t * walk -- calling the walking accessor here would build an",
			"\t * index and then ignore it. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_at("
			f"const {name}_index &idx,",
			f"\t\t\tstd::uint32_t index, ::{self.namespace}::{inner} &out)"
			" const noexcept",
			"\t{",
			"\t\tif (index >= idx.count) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"\t\tsitu_view_t raw;",
			"\t\tconst auto e = situ_view_sub(this->raw(), idx.start[index],",
			"\t\t\tidx.start[index + 1u] - idx.start[index], &raw);",
			"\t\tif (e != SITU_OK) {",
			"\t\t\treturn static_cast<::situ::rt::err>(e);",
			"\t\t}",
			f"\t\tout = ::{self.namespace}::{inner}(raw);",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]

	def _repeat_while(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""A run ending after the element that fails a condition (8.6.6)."""
		element = self.resolved.structs.get(placement.type_name or "")
		if element is None or self._extent_terms(element) is None:
			return ["", f"\t/* No accessors for {placement.path}: one"
			        f" `{placement.type_name}` has no",
			        "\t * extent this backend can compute. */"]

		name  = c_name(local_name(struct, placement))
		inner = c_name(placement.type_name or "")
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the run starts. */"]

		cap  = ("" if placement.repeat_cap is None
		        else f" && n < {placement.repeat_cap}u")

		def walk_from(base: str) -> list[str]:
			return [
			f"\t\tstd::uint32_t at = {base};",
			"\t\tstd::uint32_t n  = 0;",
			"",
			f"\t\twhile (at < limit(){cap}) {{",
			"\t\t\tsitu_view_t raw;",
			"\t\t\tif (situ_view_sub(this->raw(), at, limit() - at, &raw)"
			" != SITU_OK) {",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			f"\t\t\tconst ::{self.namespace}::{inner} element(raw);",
			"\t\t\tconst std::uint32_t size = element.extent();",
			"\t\t\tif (size == 0u || at + size > limit()) {",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			]

		walk  = walk_from(start)
		from_ = walk_from("start")
		tail = [
			"\t\t\tat += size;",
			"\t\t\tn  += 1;",
			f"\t\t\tif (!({self._element_cond(element, placement)})) {{",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			"\t\t}",
		]

		return [
			"",
			f"\t/* {placement.path} is a run of `{placement.type_name}` ending",
			f"\t * after the element for which `{placement.repeat_while}` is",
			"\t * false. That element is part of the run: the condition is",
			"\t * asked about it once it has been read. */",
			f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
			"\t{",
			*walk, *tail,
			"\t\treturn n;",
			"\t}",
			"",
			f"\t[[nodiscard]] ::situ::rt::err {name}(std::uint32_t index,"
			f" {inner} &out) const noexcept",
			"\t{",
			*walk,
			"\t\t\tif (n == index) {",
			"\t\t\t\tsitu_view_t found;",
			"\t\t\t\tconst situ_err_t e = situ_view_sub(this->raw(), at,"
			" size, &found);",
			"",
			"\t\t\t\tif (e == SITU_OK) {",
			f"\t\t\t\t\tout = ::{self.namespace}::{inner}(found);",
			"\t\t\t\t}",
			"\t\t\t\treturn static_cast<::situ::rt::err>(e);",
			"\t\t\t}",
			*tail,
			"\t\treturn ::situ::rt::err::bounds;",
			"\t}",
			"",
			"\t/* The walk, from a base the caller already knows: the same",
			"\t * helper every delimited member has, for the same reason. */",
			f"\t[[nodiscard]] std::uint32_t {name}_span_from(std::uint32_t start)"
			" const noexcept",
			"\t{",
			*from_, *tail,
			"\t\t(void)n;",
			"\t\treturn at - start;",
			"\t}",
			"",
			f"\t[[nodiscard]] std::uint32_t {name}_span() const noexcept",
			"\t{",
			f"\t\treturn {name}_span_from({start});",
			"\t}",
			*self._run_index(struct, placement, walk,
			                 self._element_cond(element, placement), inner),
		]

	def _element_cond(self, element: ResolvedStruct,
			placement: Placement) -> str:
		"""The condition over `element`, whose accessors are methods."""
		names = [entry.placement.name for entry in element.entries
		         if entry.placement.scalar is not None
		         and "." not in entry.placement.path[len(element.name) + 1:]]

		# The same enum problem `_over_fields` has, in the other rewriter:
		# `next_header == 43` over an `enum class` does not compile, and
		# `examples/ipv6ext` is exactly that. Two rewriters, one rule.
		by_name = {entry.placement.name: entry.placement
		           for entry in element.entries}

		def read(name: str) -> str:
			held = by_name.get(name)
			if held is not None and held.type_name in self.enums \
					and held.scalar is not None:
				return f"({self._load(held.scalar, held, None, on='element')})"
			return f"element.{c_name(name)}()"

		return over_fields(names, placement.repeat_while or "", read)

	def _record_run(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""A run of records, ending where the terminator would be an element.

		Walked, not indexed, exactly as in C and for the same reason: a view
		is a value and nothing here allocates. What C++ adds is that `at()`
		returns `[[nodiscard]] err`, so an out-of-range index cannot be
		ignored into a use of an uninitialised view.
		"""
		assert placement.delimiter is not None
		element = self.resolved.structs.get(placement.type_name or "")
		if element is None or not self._extent_terms(element):
			return ["", f"\t/* No accessors for {placement.path}: one"
			        f" `{placement.type_name}` has no",
			        "\t * extent this backend can compute, so the run cannot be"
			        " walked. */"]

		name  = c_name(local_name(struct, placement))
		delim = placement.delimiter
		inner = c_name(placement.type_name or "")
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the run starts. */"]

		array = self._delimiter_array(placement)

		def walk_from(base: str) -> list[str]:
			return [
			f"\t\tstd::uint32_t at = {base};",
			"\t\tstd::uint32_t n  = 0;",
			"",
			f"\t\twhile (at + {len(delim)}u <= limit()) {{",
			f"\t\t\tif (situ_scan(base() + at, {len(delim)}u, {array},"
			f" {len(delim)}u) == 0u) {{",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			"",
			"\t\t\tsitu_view_t raw;",
			"\t\t\tif (situ_view_sub(this->raw(), at, limit() - at, &raw)"
			" != SITU_OK) {",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			f"\t\t\tconst std::uint32_t size = "
			f"::{self.namespace}::{inner}(raw).extent();",
			"\t\t\tif (size == 0u || at + size > limit()) {",
			"\t\t\t\t/* A zero-extent element would walk here forever, and",
			"\t\t\t\t * one running past the limit was never in this frame. */",
			"\t\t\t\tbreak;",
			"\t\t\t}",
			]

		walk  = walk_from(start)
		from_ = walk_from("start")

		return [
			"",
			f"\t/* {placement.path} is a run of `{placement.type_name}`, ending",
			f"\t * where {render_delimiter(delim)} stands in for one. Walked, not",
			"\t * indexed: there is nowhere to keep a table of offsets. */",
			f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
			"\t{",
			*walk,
			"\t\t\tat += size;",
			"\t\t\tn  += 1;",
			"\t\t}",
			"\t\treturn n;",
			"\t}",
			"",
			f"\t[[nodiscard]] ::situ::rt::err {name}(std::uint32_t index,"
			f" {inner} &out) const noexcept",
			"\t{",
			*walk,
			"\t\t\tif (n == index) {",
			"\t\t\t\tsitu_view_t found;",
			"\t\t\t\tconst situ_err_t e = situ_view_sub(this->raw(), at, size,"
			" &found);",
			"",
			"\t\t\t\tif (e == SITU_OK) {",
			f"\t\t\t\t\tout = ::{self.namespace}::{inner}(found);",
			"\t\t\t\t}",
			"\t\t\t\treturn static_cast<::situ::rt::err>(e);",
			"\t\t\t}",
			"\t\t\tat += size;",
			"\t\t\tn  += 1;",
			"\t\t}",
			"\t\treturn ::situ::rt::err::bounds;",
			"\t}",
			"",
			"\t/* The walk, from a base the caller already knows -- the same",
			"\t * helper every delimited member has. Everything that",
			"\t * accumulates offsets holds `at` already, and the plain",
			"\t * `_span` re-resolves it by rescanning every member before",
			"\t * the run. */",
			f"\t[[nodiscard]] std::uint32_t {name}_span_from(std::uint32_t start)"
			" const noexcept",
			"\t{",
			*from_,
			"\t\t\tat += size;",
			"\t\t\tn  += 1;",
			"\t\t}",
			"\t\t(void)n;",
			"",
			"\t\t/* The terminator belongs to this member. Where the run ran",
			"\t\t * out of buffer instead there is none to count. */",
			f"\t\tif (at + {len(delim)}u <= limit()) {{",
			f"\t\t\tat += {len(delim)}u;",
			"\t\t}",
			"\t\treturn at - start;",
			"\t}",
			"",
			f"\t[[nodiscard]] std::uint32_t {name}_span() const noexcept",
			"\t{",
			f"\t\treturn {name}_span_from({start});",
			"\t}",
		]

	def _required(self, struct: ResolvedStruct) -> list[str]:
		"""Framing: is a whole message here, and if not how many bytes? (20.3)

		Static, because it is asked of bytes rather than of a message that has
		already been acquired -- there is nothing to be a member of yet. The
		length expressions are member functions, so it builds a temporary over
		the prefix and reads through that: the class is a view and a view is
		two words, so the temporary is free.
		"""
		if struct.layout.register is not None:
			return []

		name = class_name(struct)

		# Two functions rather than one. The length expressions below are
		# member calls -- `base()` is `this->base()` -- so the work has to
		# happen on an object, and framing is asked of bytes that are not one
		# yet. So: an instance method over a view, and a static that makes the
		# view. `framed` is worth having on its own, being "is what I already
		# hold a complete message?".
		head = [
			"",
			"\t/* How many bytes a whole one needs, given the ones this view",
			"\t * holds.",
			"\t *",
			"\t * ok        a complete one is present; `need` is its length",
			"\t * truncated not yet; `need` is a lower bound on the total */",
			"\t[[nodiscard]] ::situ::rt::err framed(std::uint32_t &need)"
			" const noexcept",
			"\t{",
			"\t\tconst std::uint32_t have = limit();",
		]
		tail = [
			"",
			"\t/* The same question asked of bytes that are not a view yet,"
			" which is",
			"\t * the shape a stream reader wants. */",
			"\t[[nodiscard]] static ::situ::rt::err required("
			"const std::uint8_t *data,",
			"\t\t\tstd::uint32_t have, std::uint32_t &need) noexcept",
			"\t{",
			f"\t\treturn {name}{{ situ_view_t{{",
			"\t\t\tconst_cast<std::uint8_t *>(data), have, 0u } }"
			".framed(need);",
			"\t}",
		]

		if struct.layout.is_fixed_size and struct.layout.is_byte_sized:
			return [*head,
			        "\t\tneed = size_bytes;",
			        "\t\treturn have >= size_bytes ? ::situ::rt::err::ok",
			        "\t\t                          : ::situ::rt::err::truncated;",
			        "\t}", *tail]

		parts = extent_parts(self.resolved.structs, struct)
		if parts is None:
			return self._unframeable(struct)

		constant, variable = parts
		if constant == 0 and not variable:
			return self._unframeable(struct,
			        "a complete one can be zero bytes, so every buffer already"
			        " holds one")

		steps: list[str] = []
		for placement in variable:
			if placement.kind == "indexed":
				return self._unframeable(struct, "an `indexed` region reaches"
				        " wherever its furthest element ends, which its offset"
				        " table does not say")
			if is_run(placement, self.structs):
				walk = self._framing_walk(struct, placement)
				if walk is None:
					return self._unframeable(struct, "a run whose element"
					        " cannot be framed cannot be framed either")
				steps.extend(walk)
				continue

			length = self._length_expression(struct, placement)
			if length is None:
				return self._unframeable(struct)

			name_of = c_name(local_name(struct, placement))
			steps.extend([
				"",
				f"\t\t/* {placement.path}: reading its length means reading",
				"\t\t * bytes that have to be here first. */",
				"\t\tif (have < at) {",
				"\t\t\tneed = at;",
				"\t\t\treturn ::situ::rt::err::truncated;",
				"\t\t}",
			])
			if placement.delimiter is not None:
				steps.extend([
					f"\t\tif (!{name_of}_terminated()) {{",
					"\t\t\t/* The delimiter is not in what we have, and how"
					" much more",
					"\t\t\t * is the sender's to know. One byte is the honest"
					" bound. */",
					"\t\t\tneed = have + 1u;",
					"\t\t\treturn ::situ::rt::err::truncated;",
					"\t\t}",
				])
			steps.append(f"\t\tat = at + ({length});")

		return [
			*head,
			f"\t\tstd::uint32_t at = {constant}u;",
			"",
			"\t\tif (have < size_min) {",
			"\t\t\tneed = size_min;",
			"\t\t\treturn ::situ::rt::err::truncated;",
			"\t\t}",
			*steps,
			"",
			"\t\tneed = at;",
			"\t\treturn have >= at ? ::situ::rt::err::ok",
			"\t\t                  : ::situ::rt::err::truncated;",
			"\t}",
			*tail,
		]

	def _framing_walk(self, struct: ResolvedStruct,
			placement: Placement) -> list[str] | None:
		"""Framing a run: one element at a time, through the element's own
		`required`.

		The walk the accessors use cannot answer this. It stops when the
		terminator stands where an element would, when an element runs past
		the view, and when the bytes run out -- and it cannot tell the first
		from the last, which are opposite answers to "is a whole one here?".
		So a record run was declined and, worse, a `while` run was *accepted*:
		two bytes of a nine-byte reply came back complete (26.31).

		The element's own `required` is what separates them, being the same
		question one level down.
		"""
		element = self.resolved.structs.get(placement.type_name or "")
		if element is None or not frameable(self.resolved.structs, element):
			return None

		inner = class_name(element)
		call  = (f"\t\t\tconst ::situ::rt::err e = ::{self.namespace}::{inner}"
		         "::required(")
		read  = [
			call + "base() + at,",
			"\t\t\t\thave - at, part);",
			"\t\t\tif (e != ::situ::rt::err::ok) {",
			"\t\t\t\tneed = at + part;",
			"\t\t\t\treturn ::situ::rt::err::truncated;",
			"\t\t\t}",
		]
		cap  = placement.repeat_cap if placement.repeat_while else None
		body = ["\t\t\tstd::uint32_t part = 0;"]

		if placement.repeat_while is not None:
			body.extend([
				"\t\t\tsitu_view_t raw;",
				"",
				*read,
				"\t\t\tif (situ_view_sub(this->raw(), at, part, &raw)"
				" != SITU_OK) {",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				f"\t\t\tconst ::{self.namespace}::{inner} element(raw);",
				"\t\t\tat += part;",
				"",
				"\t\t\t/* The condition is asked about the element just"
				" read, which",
				"\t\t\t * is the whole difference from a delimiter -- and"
				" only once",
				"\t\t\t * that element is known to be entirely here. */",
				f"\t\t\tif (!({self._element_cond(element, placement)})) {{",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				*([] if cap is None else [
					"\t\t\tn += 1;",
					f"\t\t\tif (n == {cap}u) {{",
					"\t\t\t\tbreak;",
					"\t\t\t}",
				]),
			])
		else:
			delim = placement.delimiter
			assert delim is not None
			array = self._delimiter_array(placement)
			body.extend([
				"",
				f"\t\t\tif (have < at + {len(delim)}u) {{",
				f"\t\t\t\tneed = at + {len(delim)}u;",
				"\t\t\t\treturn ::situ::rt::err::truncated;",
				"\t\t\t}",
				"",
				"\t\t\t/* The terminator only terminates where an element"
				" would start.",
				"\t\t\t * It belongs to this member, as a delimiter does. */",
				f"\t\t\tif (situ_scan(base() + at, {len(delim)}u, {array},"
				f" {len(delim)}u) == 0u) {{",
				f"\t\t\t\tat += {len(delim)}u;",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"",
				*read,
				"\t\t\tat += part;",
			])

		loop = ["\t\tfor (;;) {", *body, "\t\t}"]
		if cap is not None:
			loop = ["\t\t{", "\t\t\tstd::uint32_t n = 0;",
			        *[f"\t{line}" if line else line for line in loop],
			        "\t\t}"]

		return [
			"",
			f"\t\t/* {placement.path}: a run of `{element.name}`, framed one",
			"\t\t * element at a time. The walk the accessors use stops at"
			" the end",
			"\t\t * of the bytes as readily as at the end of the run; this"
			" asks each",
			"\t\t * element whether it is whole. */",
			*loop,
		]

	def _unframeable(self, struct: ResolvedStruct,
			why: str | None = None) -> list[str]:
		if struct.layout.register is not None:
			return []
		reason = why or (
			"it ends where the view ends, so how long one is is the"
			" transport's answer rather than the message's"
			if any(held.sized_by == "remaining" for held in own_members(struct))
			else "one of its members has no length this can compute")
		return [
			"",
			f"\t/* No `required`: {reason}.",
			"\t * Framing such a message is the layer below's job. */",
		]

	def _extent_terms(self, struct: ResolvedStruct) -> list[str] | None:
		"""The lengths one instance of a variable struct sums to, or None.

		The arithmetic and the refusals are shared (traverse.extent_parts);
		what is left here is rendering one length in C++.
		"""
		# A fixed-size element still has an extent: it is the size. Only
		# variable structs reach `extent_parts`, which says so by returning
		# None for a fixed one -- so a `while` run over `struct e { u8 k; u8
		# pad; }` got no walk at all, and every member after the run went on
		# calling the span function nobody emitted. C computes this from the
		# size directly and was the only backend that built such a schema.
		if struct.layout.is_fixed_size and struct.layout.is_byte_sized:
			return [str(int(struct.layout.size_bytes))]

		parts = extent_parts(self.resolved.structs, struct)
		if parts is None:
			return None
		constant, variable = parts

		terms = [str(constant)]
		for placement in variable:
			length = self._length_expression(struct, placement)
			if length is None:
				return None
			terms.append(length)
		return terms

	def _extent_method(self, struct: ResolvedStruct) -> list[str]:
		"""How many bytes one instance occupies, for a run that walks them."""
		# A run walks them and a nested member sizes its view from one. Gated
		# on the run alone, the nested case reached for `size_bytes` instead.
		# A run walks them, a `while` run walks them, a nested member sizes its
		# view from one, and an `indexed` region narrows an offset to one. All
		# four read the same method -- and the fourth was missing, so an
		# indexed region reported an extent it could not compute when the
		# extent was simply not emitted.
		# A *count*-driven run of these walks them too, and this did not name
		# it: `adv_report reports[num]`, where each report carries its own
		# `data[data_length]`, got no `extent()` -- and the accessor that
		# walks such a run then called a method nothing emits (26.36). It
		# classifies as VARIABLE, because a count of elements and a byte
		# length look alike until you ask what the element is.
		def walks(holder: ResolvedStruct, entry: Resolved) -> bool:
			placement = entry.placement
			if placement.type_name != struct.name:
				return False
			if classify(holder, placement, self.structs) in (
					Member.RECORD_RUN, Member.REPEAT_WHILE, Member.NESTED,
					Member.INDEXED):
				return True
			# `data_sized`, not `sized_by`: the arithmetic spelling of a
			# count is a count, and reading only the bare one left
			# `vrec run[n + 1]` without an `extent()` while the walk that
			# indexes it called one. The same missing spelling this file
			# has now met in four places.
			return (data_sized(placement)
			        and not struct.layout.is_fixed_size)

		if not any(walks(other, entry)
		           for other in self.resolved.structs.values()
		           for entry in other.entries):
			return []

		terms = self._extent_terms(struct)
		if terms is None:
			return []

		return [
			"",
			f"\t/* How many bytes one `{struct.name}` occupies. A run of these is",
			"\t * walked, and the walk needs to know where each one ends. */",
			"\t[[nodiscard]] std::uint32_t extent() const noexcept",
			"\t{",
			f"\t\treturn {' + '.join(terms)};",
			"\t}",
		]

	def _over_fields(self, struct: ResolvedStruct, source: str) -> str:
		# An enum-typed field's getter hands back an `enum class`, which has
		# no implicit conversion -- `k() != 1u` does not compile. So an
		# expression over one reads the backing bytes, which is what the
		# expression means anyway: a discriminant is compared against
		# numbers, and section 8.7 admits values no member names.
		#
		# Every use of this was wrong for an enum discriminant -- the extent
		# chain, the `default: error` check, the arm guards -- so a schema
		# with `case K.a:` did not compile at all. No C++ test had one, and
		# neither did Rust, which had the same bug in its own spelling.
		#
		# Keyed by the *local path* rather than the name, and including the
		# scalars of nested structs. Keyed by name over every entry, a nested
		# member of the same name won -- entries are in layout order and the
		# deeper one comes last -- and the dotted paths themselves were left
		# unrewritten, which in C++ is a member function call
		# (`at file.pixel_offset`, in `examples/bmp`).
		by_name = {local_name(struct, placement): placement
		           for placement in readable_names(struct)}
		# Constants too. A `const` is a compile-time value and the renderer
		# only rewrote *fields*, so `align_up(HEADER_BYTES + n, 4)` reached
		# the target as `HEADER_BYTES` -- an identifier that exists in the
		# schema and in no generated file. Folding it here keeps the emitted
		# arithmetic the arithmetic the schema wrote.
		consts = self.resolved.layout.env.consts

		def read(name: str) -> str:
			if name in consts:
				return str(consts[name])
			held = by_name[name]
			if "." in name:
			# A text number is digits, not bytes of an integer: reading it
			# where it sits parses eight ASCII characters as a binary
			# integer, which is a plausible number nobody wrote.
				if held.radix is not None:
					return f"{c_name(name)}_value()"
				assert held.scalar is not None
				return f"({self._load(held.scalar, held, None)})"
			if held.type_name in self.enums and held.scalar is not None:
				# The backing bytes, because the getter hands back an `enum
				# class` and nothing compares that to a number. At a dynamic
				# offset there is no constant to read them at -- a
				# discriminant behind a delimited member is exactly that --
				# and asking the placement for one asserted out of the
				# compiler.
				at = (None if held.offset_bits is not None
				      else self._offset_expression(struct, held))
				if held.offset_bits is None and at is None:
					raise UnknownName(name)
				return f"({self._load(held.scalar, held, at)})"
			# A varint's own getter reports a truncated encoding; `_value` is
			# the read that cannot fail, which is what the count form uses --
			# and a text number's getter reports one too, which only the
			# nested branch above knew about.
			if held.varint is not None or held.radix is not None:
				return f"{c_name(name)}_value()"
			return f"{c_name(name)}()"

		return expand_calls(over_fields([*by_name, *consts], source, read),
		                    c_spelling)

	def _nested_text_values(self, struct: ResolvedStruct) -> list[str]:
		"""The non-failing read of a *nested* text number.

		A member of a nested struct can drive a length -- `u8
		name[header.namesize]` in a cpio entry -- and an expression over it
		names a helper on *this* class. Nothing emitted it.
		"""
		lines: list[str] = []
		for entry in struct.entries:
			placement = entry.placement
			scalar    = placement.scalar
			if placement.radix is None or placement.offset_bits is None:
				continue
			# Nested *or* the struct's own. Restricting this to nested
			# members assumed the fixed-width form beside it emitted its own
			# `_value`, and it does not: `decimal u32 n[4]; u16 d[n]` named a
			# helper nothing defined. Every text driver in `examples/` is
			# either delimited or nested, which are the two forms that had it.
			if scalar is None or placement.array_count is None:
				continue

			name  = c_name(local_name(struct, placement))
			ctype = self._field_ctype(placement)
			limit = (1 << scalar.bits) - 1
			at    = placement.offset_bits // BITS_PER_BYTE
			lines.extend([
				"",
				f"\t/* {placement.path}, where an error cannot be returned:",
				"\t * the offset arithmetic after it is not fallible, and",
				"\t * `validate` refuses a frame whose digits are not"
				" digits. */",
				f"\t[[nodiscard]] {ctype} {name}_value() const noexcept",
				"\t{",
				"\t\tstd::uint64_t value = 0;",
				"",
				f"\t\t(void)situ_parse_uint(base() + {at},"
				f" {placement.array_count}, {placement.radix}, {limit},"
				" &value);",
				f"\t\treturn static_cast<{ctype}>(value);",
				"\t}",
			])
		return lines

	def _fits(self, struct: ResolvedStruct, placement: Placement,
			bytes_: int) -> str | None:
		"""Whether a fixed-size member at a *dynamic* offset is in the view.

		None where the question does not arise: a statically placed member is
		inside the frame by the bounds check that acquired the view (20.2). A
		member placed after a variable-length region is not, and
		`examples/packet` put its tag 65 kilobytes past a 62-byte one.
		"""
		if placement.offset_bits is not None:
			return None
		start = self._offset_expression(struct, placement)
		if start is None:
			return None
		return f"situ_in_bounds(raw(), {start}, {bytes_}u)"

	def _fits_check(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""A length the message declares must fit the frame it is in.

		Nothing checked this in any backend: `u8 opts[hdr.length]` with a
		`u16` length in a 32-byte frame parsed clean. The accessor clamps,
		which is what keeps a caller who skips validation safe; this is what
		tells a caller who does not that the message is malformed rather than
		short. Clamping alone silently turns a lie into a truncation.
		"""
		if "." in placement.path[len(struct.name) + 1:]:
			return []

		# The other half of the same sentence: a member *placed* after a
		# variable-length region has an offset the message chose, so whether
		# the frame contains it is not something the acquiring check settled.
		if not declares_its_own_length(placement):
			extent = (placement.size_bits // BITS_PER_BYTE
			          if placement.is_fixed_size
			          and placement.size_bits % BITS_PER_BYTE == 0 else None)
			fits = (None if not extent
			        else self._fits(struct, placement, extent))
			if fits is None:
				return []
			return [
				f"\t\t/* {placement.path}: its offset is a sum of lengths the",
				"\t\t * message chose, so the frame is not known to contain"
				" it. */",
				f"\t\tif (!{fits}) {{",
				"\t\t\treturn ::situ::rt::err::bounds;",
				"\t\t}",
			]

		declared = self._length_expression(struct, placement)
		start    = self._offset_expression(struct, placement)
		if declared is None or start is None:
			return []
		return [
			f"\t\t/* {placement.path}: the length the message declares has to",
			"\t\t * fit the frame it is in. */",
			f"\t\tif (situ_remaining_u32(limit(), {start}) < ({declared})) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
		]

	def _discriminant_check(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""`default: error` -- the discriminant must select an arm.

		Section 14.5 says an unrecognised discriminant is rejected on parse,
		and no backend rejected it. It stayed invisible while a variant had no
		computable extent, because nothing walked one.
		"""
		values = matched_values(placement)
		if not values or placement.discriminant is None:
			return []

		held = self._over_fields(struct, placement.discriminant)
		test = " && ".join(f"{held} != {arm.value}u" for arm in values)
		named = ", ".join(arm.source or str(arm.value) for arm in values)
		return [
			f"\t\t/* {placement.path}: an arm for {named}, and"
			f" `default: error` for the rest. */",
			f"\t\tif ({test}) {{",
			"\t\t\treturn ::situ::rt::err::version;",
			"\t\t}",
		]

	def _variant_length(self, struct: ResolvedStruct,
			placement: Placement) -> str | None:
		"""How many bytes the selected arm occupies, as one expression.

		A conditional chain rather than a statement `switch`, because callers
		want this inside a sum -- the extent of the struct around it, or the
		offset of whatever follows.

		An unmatched discriminant yields zero, which is not a claim that such
		a message is empty: `default: error` says there is no such message,
		and `validate` is where that is said. Zero is the value the run walk
		already refuses to advance by.
		"""
		if not placement.arm_cases or placement.discriminant is None:
			return None

		held  = self._over_fields(struct, placement.discriminant)
		chain = "0u"
		for arm, member in reversed(arm_members(struct, placement)):
			if member is None:
				continue		# `default: error`; falls to the zero above
			if member.is_fixed_size:
				length = f"{member.size_bits // BITS_PER_BYTE}u"
			else:
				rendered = self._length_expression(struct, member)
				if rendered is None:
					return None
				length = f"({rendered})"

			chain = (length if arm.value is None
			         else f"({held} == {arm.value}u ? {length} : {chain})")
		return chain

	def _region_length(self, struct: ResolvedStruct,
			region: Placement) -> str | None:
		"""How many bytes a coded or sealed region occupies, at runtime.

		Its interior extent put through the codec's expansion -- the same rule
		the solver applies and the only one available, the region's bytes
		being the transform's output.

		Only C had this, so the other three could place nothing after such a
		region: `examples/packet`'s tag sits after the sealed region and
		reported that its offset could not be resolved.
		"""
		rule = region_extent(struct, region,
		                     self.codecs.get(region.type_name), self.resolved.structs)
		if rule is None:
			return None

		terms = [str(rule.constant)]
		for member in rule.variable:
			length = self._length_expression(struct, member)
			if length is None:
				return None
			terms.append(f"({length})")
		inner = " + ".join(terms)

		if rule.kind == "preserving":
			return inner
		if rule.kind == "add":
			return f"({inner}) + {rule.add}"
		if rule.kind == "ratio":
			return f"(({inner}) * {rule.out}) / {rule.into}"
		# Whole groups only, so a partial one still costs a full group.
		return (f"((({inner}) + {rule.group_in - 1})"
		        f" / {rule.group_in}) * {rule.group_out}")

	def _length_expression(self, struct: ResolvedStruct,
			placement: Placement, running: str | None = None) -> str | None:
		"""How many bytes a variable-length member occupies, at run time."""
		if placement.kind == "variant":
			return self._variant_length(struct, placement)

		# A run inside a variant arm has no length here, because the arm
		# emitter has no walk: an arm is emitted by a family of its own, and
		# that family reaches a scalar, a byte run, a run of wide values and
		# one fixed-size struct -- never a run of records. Answering anyway
		# named `<arm>_span()`, which nothing defines, so `framed()` did not
		# compile for `vrec run[n + 1]` in an arm. C declines the same member
		# for the same reason; the gap is one gap in four backends rather
		# than four answers to one schema.
		if arm_of(struct, placement) is not None \
				and (placement.repeat_while is not None
				     or placement.delimiter is not None
				     or is_counted_run(self.resolved.structs, placement)):
			return None

		# A size that is arithmetic over a field rather than a reference to
		# one. `sized_by` holds a path and holds nothing for this, so the
		# member fell through to the scalar case and this backend handed back
		# one byte and called it the field.
		if is_counted_run(self.resolved.structs, placement):
			name = c_name(local_name(struct, placement))
			return (f"{name}_span_from({running})" if running is not None
			        else f"{name}_span()")

		if placement.size_expr is not None:
			rendered = (f"static_cast<std::uint32_t>("
			            f"{self._over_fields(struct, placement.size_expr)})")
			each     = element_bytes(placement)
			return rendered if each == 1 else f"({rendered}) * {each}u"
		# A delimited member's extent is not a closed form: it is wherever the
		# delimiter turns out to be, and `_span()` is the member's own answer.
		# The same call serves a byte array and a run of records -- one name
		# for "how far this member reaches", whichever it is.
		if placement.delimiter is not None or placement.repeat_while is not None:
			name = c_name(local_name(struct, placement))
			# Every kind that reaches here has the `_from` form now: a byte
			# array's scan, a record run's walk and a `while` run's. The runs
			# were the exception, and it cost a rescan of everything before
			# the run on every accumulating pass over it.
			if running is not None:
				return f"{name}_span_from({running})"
			return f"{name}_span()"

		# A nested struct with no single size. Without this the sum treated
		# it as zero bytes wide and placed whatever follows on top of it.
		inner = self.resolved.structs.get(placement.type_name or "")
		if (inner is not None and not inner.layout.is_fixed_size
				and placement.kind == "field"
				and placement.array_count is None
				and placement.sized_by is None):
			if not has_computable_extent(self.resolved.structs, inner):
				return None		# and so nothing after it can be placed
			return f"{c_name(local_name(struct, placement))}_extent()"

		if placement.kind in ("coded", "sealed"):
			return self._region_length(struct, placement)

		if placement.varint is not None:
			if not self._reads_varint(placement):
				return None
			return f"{c_name(local_name(struct, placement))}_len()"

		# An opaque region's size expression is already a byte count: there are
		# no elements to multiply by, and asking for an element width finds no
		# scalar and gives up. C has had this branch all along.
		if placement.kind == "opaque":
			count = self._count_expression(struct, placement)
			return None if count is None else f"({count})"

		if placement.sized_by == "remaining":
			start = self._offset_expression(struct, placement)
			return None if start is None else f"(limit() - ({start}))"
		if placement.sized_by is None:
			return None

		# An `indexed` region's count counts entries, and an entry is an
		# `offset_type` wide (`traverse.index_entry_bytes`). Asking the
		# *element* for a width finds a struct with no fixed one and gives up,
		# so the region had no length here and `validate` had no check.
		entry = index_entry_bytes(placement)
		if entry is not None:
			table = self._count_expression(struct, placement)
			return None if table is None else f"({table}) * {entry}"

		count = self._count_expression(struct, placement)
		if count is None:
			return None

		element = self._element_bytes(placement)
		if element is None:
			return None
		return f"({count})" if element == 1 else f"({count}) * {element}"

	def _count_expression(self, struct: ResolvedStruct,
			placement: Placement) -> str | None:
		"""The value of the field that sizes a member, read at run time."""
		# A count written as arithmetic. `sized_by` holds a path and holds
		# nothing for `x[n + 1]`, so this looked up a driver named "None",
		# found none, and handed its caller a Python `None` -- which C++
		# formatted straight into `return None;`. The expression *is* the
		# count; it is only the bare-reference form that needs a driver
		# looked up (invariant 69, in the fourth place that spells this
		# question two ways).
		if placement.sized_by is None and placement.size_expr is not None:
			return self._over_fields(struct, placement.size_expr)

		driver = self.resolved.find(f"{struct.name}.{placement.sized_by}")
		if driver is None:
			return None

		# A varint driver has no scalar and no constant offset, so neither the
		# guard above nor the load below applies to it. It was refused by the
		# `scalar is None` check, which is why a length-prefixed field -- the
		# thing a varint is usually for -- could not be sized by one.
		if driver.placement.varint is not None:
			if not self._reads_varint(driver.placement):
				return None
			name = c_name(local_name(struct, driver.placement))
			return f"static_cast<std::uint32_t>({name}_value())"

		if driver.placement.scalar is None:
			return None

		# A text driver's value is digits, not bits, and it has no fixed
		# offset either -- it is behind the scans of everything before it.
		# Both of the checks below would have refused it for the wrong reason.
		if driver.placement.radix is not None:
			name = c_name(local_name(struct, driver.placement))
			return f"static_cast<std::uint32_t>({name}_value())"

		if driver.placement.offset_bits is None:
			# The driver is itself behind a variable-length member, so there
			# is no constant to read it at -- but its own accessor knows where
			# it is, and this backend has always emitted one. Reading at a
			# static offset was the only thing tried, so the member it sizes
			# was dropped from the class with a note, which is the whole of
			# what "cannot resolve yet" meant.
			#
			# Calling the accessor rather than inlining the load, which is
			# what the text-number branch above already does, and what C++
			# allows and C does not: a member function may call one declared
			# after it.
			name = c_name(local_name(struct, driver.placement))
			return f"static_cast<std::uint32_t>({name}())"

		# The address as a separate name rather than a nested f-string: an
		# expression split across lines inside `{...}` is PEP 701, which is
		# Python 3.12, and this project's floor is 3.11 (section 22).
		address = f"base() + {driver.placement.offset_bytes}"
		load    = self._raw_load(driver.placement.scalar, driver.placement,
		                         address)
		return f"static_cast<std::uint32_t>({load})"

	def _element_bytes(self, placement: Placement) -> int | None:
		nested = self.resolved.structs.get(placement.type_name or "")
		if nested is not None:
			return (int(nested.layout.size_bytes)
			        if nested.layout.is_fixed_size else None)
		if placement.scalar is not None and placement.scalar.bits % BITS_PER_BYTE == 0:
			return max(placement.scalar.bits // BITS_PER_BYTE, 1)
		return None

	def _variable(self, struct: ResolvedStruct, placement: Placement) -> list[str]:
		"""A member whose extent the data decides: a counted array, or the rest."""
		name   = c_name(local_name(struct, placement))
		start  = self._offset_expression(struct, placement)
		length = self._length_expression(struct, placement)

		nested = self.resolved.structs.get(placement.type_name or "")

		# The length is the *member's* total extent, which a walk does not
		# need: it steps element by element. Asking for it first refused a
		# run of variable-size records before the branch that walks them ever
		# ran -- and `_element_bytes` has no answer for an element with no
		# single size, which is the whole shape (26.36).
		wanted = length is None and (nested is None
		                             or nested.layout.is_fixed_size)
		if start is None or wanted:
			return ["", f"\t/* {placement.path}: sized by"
			        f" `{placement.sized_by}`, which this backend cannot resolve"
			        f" yet. */"]
		lines  = ["",
		          f"\t/* {placement.path}: offset and extent both from the data. */",
		          f"\t[[nodiscard]] std::uint32_t {name}_offset() const noexcept",
		          "\t{",
		          *(self._offset_body(struct, placement)
		            or [f"\t\treturn {start};"]),
		          "\t}"]

		if nested is None:
			# An element wider than a byte is the same array `x[4]` is, with
			# its count in the message rather than in the schema -- and the
			# constant-count emitter three functions down refuses to hand back
			# bytes for exactly the reason this did: they are not the values.
			if indexed_elements(placement):
				# Not None here: the refusal above only lets a missing length
				# through for a variable-size struct element, which this is not.
				assert length is not None
				lines.extend(self._variable_elements(struct, placement, length))
				return lines

			# Clamped to what the view holds. The length is a field, so it is
			# whatever the message says: `u8 opts[hdr.length]` with a `u16`
			# length claims up to 65535 bytes, and this handed out a raw
			# pointer and that number. `validate` reports the message as
			# malformed; this is what keeps a caller who skipped it safe.
			lines.extend([
				f"\t[[nodiscard]] ::situ::rt::bytes {name}() const noexcept",
				"\t{",
				f"\t\treturn ::situ::rt::bytes(base() + {name}_offset(),",
				f"\t\t\tsitu_min_u32({length},",
				f"\t\t\t\tsitu_remaining_u32(limit(), {name}_offset())));",
				"\t}",
			])
			return lines

		count = self._count_expression(struct, placement)
		inner = f"::{self.namespace}::{c_name(placement.type_name or '')}"

		# `[remaining]` says how many *bytes* are left, not how many elements
		# are in them, and an element with no single size has no stride to
		# divide the one by to get the other -- so there is no count here that
		# is not the walk itself. This pasted the Python `None` it came back
		# as straight into the header, where `return None;` is not an
		# identifier in any language.
		#
		# The walk is the answer rather than a refusal: every accessor below
		# reads `_count()`, and so does the offset of every member after the
		# run, so declining it would take the rest of the struct with it.
		walked = (count is None and not nested.layout.is_fixed_size
		          and has_computable_extent(self.resolved.structs, nested))
		if count is None and not walked:
			return lines + [
				"",
				f"\t/* No {name}_count(): one `{placement.type_name}` cannot be",
				"\t * measured from its own bytes, so a run of them can neither",
				"\t * be counted nor walked. */",
			]

		# ...and where the count *is* the walk, the walks below stop at the
		# frame rather than calling it. A stopping rule that walks would make
		# every step of a walk a walk of its own.
		bound = "" if count is None else f"n < {name}_count() && "

		lines.extend(
			[
				f"\t/* How many elements are here: `{placement.sized_by}` gives",
				"\t * the bytes that are left, and only the walk says how many",
				"\t * elements fit in them. */",
				f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
				"\t{",
				f"\t\tstd::uint32_t at = {name}_offset();",
				"\t\tstd::uint32_t n  = 0;",
				"",
				"\t\twhile (at < limit()) {",
				"\t\t\tsitu_view_t raw;",
				"",
				"\t\t\tif (situ_view_sub(this->raw(), at, limit() - at, &raw)",
				"\t\t\t\t\t!= SITU_OK) {",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"",
				f"\t\t\tconst {inner} element(raw);",
				"\t\t\tconst std::uint32_t size = element.extent();",
				"",
				"\t\t\tif (size == 0 || at + size > limit()) {",
				"\t\t\t\t/* A zero-extent element would walk here forever,",
				"\t\t\t\t * and one past the limit was never in this frame. */",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"\t\t\tat += size;",
				"\t\t\tn  += 1;",
				"\t\t}",
				"\t\treturn n;",
				"\t}",
			] if count is None else [
				f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
				"\t{",
				f"\t\treturn {count};",
				"\t}",
			])

		# An element with no single size is walked rather than indexed: there
		# is no stride to multiply. Same walk a terminated run uses, with the
		# count as the stopping rule -- which is what an HCI advertising
		# report is, `num` reports each carrying its own data (26.36).
		if not nested.layout.is_fixed_size:
			if not has_computable_extent(self.resolved.structs, nested):
				return lines + [
					"",
					f"\t/* No {name}_at(): one `{placement.type_name}` cannot"
					" be measured",
					"\t * from its own bytes, so a run of them cannot be"
					" walked. */",
				]
			return lines + [
				"",
				f"\t/* Element `index` of a run whose elements have no single",
				"\t * size: walked, because there is no stride to index by. */",
				f"\t[[nodiscard]] ::situ::rt::err {name}_at(std::uint32_t index,",
				f"\t\t\t{inner} &out) const noexcept",
				"\t{",
				f"\t\tstd::uint32_t at = {name}_offset();",
				"\t\tstd::uint32_t n  = 0;",
				"",
				*([] if count is None else [
					f"\t\tif (index >= {name}_count()) {{",
					"\t\t\treturn ::situ::rt::err::bounds;",
					"\t\t}",
					"",
				]),
				"\t\twhile (at < limit()) {",
				"\t\t\tsitu_view_t raw;",
				"",
				"\t\t\tif (situ_view_sub(this->raw(), at, limit() - at, &raw)",
				"\t\t\t\t\t!= SITU_OK) {",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"",
				f"\t\t\tconst {inner} element(raw);",
				"\t\t\tconst std::uint32_t size = element.extent();",
				"",
				"\t\t\tif (size == 0 || at + size > limit()) {",
				"\t\t\t\t/* A zero-extent element would walk here forever,",
				"\t\t\t\t * and one past the limit was never in this frame. */",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"\t\t\tif (n == index) {",
				"\t\t\t\tsitu_view_t narrowed;",
				"\t\t\t\tconst situ_err_t e =",
				"\t\t\t\t\tsitu_view_sub(this->raw(), at, size, &narrowed);",
				"",
				"\t\t\t\tif (e == SITU_OK) {",
				f"\t\t\t\t\tout = {inner}(narrowed);",
				"\t\t\t\t}",
				"\t\t\t\treturn static_cast<::situ::rt::err>(e);",
				"\t\t\t}",
				"\t\t\tat += size;",
				"\t\t\tn  += 1;",
				"\t\t}",
				"\t\treturn ::situ::rt::err::bounds;",
				"\t}",
				"",
				"\t/* How far the whole run reaches: the walk above with no",
				"\t * index to stop at. It is what places every member after",
				"\t * the run, and nothing emitted it -- so those members were",
				"\t * declined as having an offset this could not resolve,",
				"\t * which was true only because this was missing. */",
				f"\t[[nodiscard]] std::uint32_t {name}_span_from"
				"(std::uint32_t start) const noexcept",
				"\t{",
				"\t\tstd::uint32_t at = start;",
				"\t\tstd::uint32_t n  = 0;",
				"",
				f"\t\twhile ({bound}at < limit()) {{",
				"\t\t\tsitu_view_t raw;",
				"",
				"\t\t\tif (situ_view_sub(this->raw(), at, limit() - at, &raw)",
				"\t\t\t\t\t!= SITU_OK) {",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"",
				f"\t\t\tconst {inner} element(raw);",
				"\t\t\tconst std::uint32_t size = element.extent();",
				"",
				"\t\t\tif (size == 0 || at + size > limit()) {",
				"\t\t\t\tbreak;",
				"\t\t\t}",
				"\t\t\tat += size;",
				"\t\t\tn  += 1;",
				"\t\t}",
				"\t\treturn at - start;",
				"\t}",
				"",
				f"\t[[nodiscard]] std::uint32_t {name}_span() const noexcept",
				"\t{",
				f"\t\treturn {name}_span_from({name}_offset());",
				"\t}",
			]

		lines.extend([
			"",
			f"\t/* Element `index`, or an error past the end. The count is",
			"\t * checked as well as the extent: bytes after the array are",
			"\t * inside the view and are not elements. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_at(std::uint32_t index,",
			f"\t\t\t{inner} &out) const noexcept",
			"\t{",
			f"\t\tif (index >= {name}_count()) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			"\t\tsitu_view_t raw;",
			f"\t\tconst situ_err_t e = situ_view_sub(this->raw(),",
			f"\t\t\t{name}_offset() + index * {inner}::size_bytes,",
			f"\t\t\t{inner}::size_bytes, &raw);",
			"",
			"\t\tif (e == SITU_OK) {",
			f"\t\t\tout = {inner}(raw);",
			"\t\t}",
			"\t\treturn static_cast<::situ::rt::err>(e);",
			"\t}",
		])
		return lines

	def _codec_prototypes(self) -> list[str]:
		"""Decoders this header calls, at file scope with C linkage.

		The implementation is C whichever tier it came from (decision 0017),
		so the declaration has to say so -- and it cannot go inside the class
		that calls it, because a linkage specification is not allowed in a
		block.
		"""
		# Every coded member, not only the undelimited ones: a region found by
		# scanning has a decode too, and this list decided which prototypes
		# existed for it to call.
		wanted = sorted({
			held.codec for struct in self.resolved.structs.values()
			for held in own_members(struct)
			if held.codec and self._decodes(held)})

		# The tier-1 ones too, under the symbol their `impl` binds and with
		# the ABI of 13.2a. Same reason as the derived: a linkage
		# specification is not allowed in a block, so it cannot go inside the
		# class that calls it.
		tier_one = sorted({
			symbol for struct in self.resolved.structs.values()
			for held in own_members(struct)
			if held.codec and held.kind == "coded"
			and (symbol := extern_symbol(self.schema, held.codec)) is not None})

		if not wanted and not tier_one:
			return []

		# `bits` or `len` after the kernel's own unit: a `table` decoder counts
		# bits, COBS counts bytes, and the parameter name is what a reader of
		# this header has to go on.
		def counted(name: str) -> str:
			codec = self.codecs.get(name)
			return "bits" if codec is not None and decode_counts_bits(codec) \
				else "len"

		return ['extern "C" {', *[
			f"uint32_t situ_{c_name(name)}_decode(const std::uint8_t *in,"
			f" std::uint32_t {counted(name)}, std::uint8_t *out);"
			for name in wanted], *[
			f"situ_err_t {symbol}_decode(const std::uint8_t *in,"
			" std::uint32_t in_len,"
			f" std::uint8_t *out, std::uint32_t out_cap,"
			" std::uint32_t *out_len);"
			for symbol in tier_one], "}", ""]

	def _decodes(self, placement: Placement) -> bool:
		"""Whether a decode accessor is emitted for this region."""
		codec = self.codecs.get(placement.codec or "")
		return codec is not None and decodes_here(codec)

	def _indexed_region(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""An offset table, then the elements it reaches (section 9.3).

		The region answered `REGION` in the shared classifier and this backend
		emitted "not in the static subset yet" -- the fallthrough note, for the
		last construct no backend reached into.

		Insertion is still not an operation, for the reason it never was: every
		offset after the insertion point would have to move.
		"""
		table = placement.index_table
		if table is None:
			return []

		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the region starts. */"]

		name    = c_name(local_name(struct, placement))
		count   = self._count_expression(struct, placement)
		width   = table.entry_bits // BITS_PER_BYTE
		element = self.resolved.structs.get(table.element or "")

		# The same hazard the run count above carries, in the other place a
		# count reaches the output: `_count_expression` answers None where it
		# cannot read the driving field, and every accessor below reads
		# `_count()`. No schema here has an index table whose count it cannot
		# read, which is why this had never pasted a `None` -- and is not a
		# reason to leave the paste there.
		if count is None:
			return ["", f"\t/* {placement.path}: this backend cannot read the",
			        "\t * field that says how many entries the table has. */"]

		lines = [
			"",
			f"\t/* {placement.path} is an offset table of {width}-byte entries,",
			"\t * then the elements it reaches. Element N is one read of entry"
			" N plus",
			"\t * a base, whatever the elements weigh -- which is why `access`"
			" stays",
			"\t * Random through a region whose elements need not be the same"
			" size.",
			"\t *",
			"\t * Insertion is not an operation here: every offset after the",
			"\t * insertion point would have to move. */",
			f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
			"\t{",
			f"\t\treturn {count};",
			"\t}",
			"",
			"\t/* The offset held in entry `index`, as written -- measured from",
			f"\t * {self._index_base_noun(table)}. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_offset(std::uint32_t index,",
			"\t\t\tstd::uint32_t &out) const noexcept",
			"\t{",
			f"\t\tconst std::uint32_t at = {start} + index * {width}u;",
			"",
			f"\t\tif (index >= {name}_count()) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			f"\t\tif (!situ_in_bounds(this->raw(), at, {width}u)) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			f"\t\tout = {self._index_entry_read(placement, width)};",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]
		lines.extend(self._index_element(struct, placement, table, name,
		                                 element, start))
		return lines

	def _index_entry_read(self, placement: Placement, width: int) -> str:
		"""One table entry, in the region's byte order."""
		if width == 1:
			return "static_cast<std::uint32_t>(base()[at])"
		order = _order_suffix(placement.endian)
		return (f"static_cast<std::uint32_t>"
		        f"(situ_get_{order}{width * 8}(base() + at))")

	def _index_base_noun(self, table: IndexTable) -> str:
		if table.base == "message":
			return "the start of the *message*"
		if table.base == "member":
			return f"the start of `{table.base_member}`"
		return "the start of this region"

	def _index_element(self, struct: ResolvedStruct, placement: Placement,
			table: IndexTable, name: str, element: ResolvedStruct | None,
			start: str) -> list[str]:
		"""`at`: a view over the element an entry reaches.

		Emitted only where the element's extent is computable. An offset with
		no length is a position and not a frame.
		"""
		if element is None or (not element.layout.is_fixed_size
		                       and self._extent_terms(element) is None):
			held = table.element or placement.type_name
			return ["", f"\t/* No `{name}_at`: one `{held}` has no extent this"
			        " backend can",
			        "\t * compute, so an entry gives a position and not a view."
			        " The offsets",
			        "\t * are still readable above. */"]

		if table.base == "message" and not element.layout.is_fixed_size:
			return ["", f"\t/* No `{name}_at`: `{element.name}` has no fixed"
			        " size and these",
			        "\t * offsets are measured from the message, so narrowing"
			        " to one element",
			        "\t * would mean measuring it through a view this frame"
			        " cannot bound. */"]

		inner  = c_name(element.name)
		origin = (self._index_member_base(struct, table)
		          if table.base == "member" else start)

		if table.base == "message":
			return [
				"",
				"\t/* A view over element `index`. Its offset is measured from"
				" the",
				"\t * start of the *message*, so the message is taken as well:"
				" only it",
				"\t * knows where offset zero is. */",
				f"\t[[nodiscard]] ::situ::rt::err {name}_at("
				f"::situ::rt::message &owner,",
				f"\t\t\tstd::uint32_t index, {inner} &out) const noexcept",
				"\t{",
				"\t\tstd::uint32_t found = 0;",
				f"\t\tconst ::situ::rt::err e = {name}_offset(index, found);",
				"",
				"\t\tif (e != ::situ::rt::err::ok) {",
				"\t\t\treturn e;",
				"\t\t}",
				f"\t\treturn ::situ::{inner}::at(owner, found,",
				f"\t\t\t{inner}::size_bytes, out);",
				"\t}",
			]

		return [
			"",
			"\t/* A view over element `index`, whose offset is measured from",
			f"\t * {self._index_base_noun(table)}. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_at(std::uint32_t index,",
			f"\t\t\t{inner} &out) const noexcept",
			"\t{",
			"\t\tstd::uint32_t found = 0;",
			f"\t\tconst ::situ::rt::err e = {name}_offset(index, found);",
			"\t\tsitu_view_t raw;",
			"",
			"\t\tif (e != ::situ::rt::err::ok) {",
			"\t\t\treturn e;",
			"\t\t}",
			f"\t\tconst std::uint32_t start = {origin} + found;",
			*self._index_element_extent(element),
			"\t}",
		]

	def _index_member_base(self, struct: ResolvedStruct,
			table: IndexTable) -> str:
		found = self.resolved.find(f"{struct.name}.{table.base_member}")
		if found is None:
			return "0"
		return self._offset_expression(struct, found.placement) or "0"

	def _index_element_extent(self, element: ResolvedStruct) -> list[str]:
		"""Narrow to one element, measuring it first where it varies."""
		inner = c_name(element.name)

		if element.layout.is_fixed_size:
			return [
				f"\t\tif (situ_view_sub(this->raw(), start,"
				f" {inner}::size_bytes, &raw)",
				"\t\t\t\t!= SITU_OK) {",
				"\t\t\treturn ::situ::rt::err::bounds;",
				"\t\t}",
				f"\t\tout = ::situ::{inner}(raw);",
				"\t\treturn ::situ::rt::err::ok;",
			]

		return [
			"",
			"\t\t/* The extent is in the element's own bytes, so it takes a"
			" view to",
			"\t\t * read and a view is what it decides. Measure over the rest"
			" of the",
			"\t\t * region, then narrow. */",
			"\t\tif (start > limit()) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"\t\tif (situ_view_sub(this->raw(), start, limit() - start, &raw)",
			"\t\t\t\t!= SITU_OK) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			f"\t\tif (situ_view_sub(this->raw(), start,",
			f"\t\t\t\t::situ::{inner}(raw).extent(), &raw) != SITU_OK) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			f"\t\tout = ::situ::{inner}(raw);",
			"\t\treturn ::situ::rt::err::ok;",
		]

	def _tlv_region(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""A run of tag-length-value items, walked as the schema describes them.

		The region answered `REGION` in the shared classifier and this backend
		emitted "not in the static subset yet" -- the fallthrough note, for the
		one construct section 9.7 makes the conformance gate.

		The item is a nested struct rather than a class: it is a cursor into
		bytes somebody else owns, and giving it the view's interface would
		suggest it were a frame of its own.
		"""
		grammar = placement.tlv_grammar
		if grammar is None or not grammar.walkable:
			return ["", f"\t/* No accessors for {placement.path}: the region"
			        " says how its items are",
			        "\t * tagged and not how long their values are, so a walk"
			        " has nowhere to",
			        "\t * put the second item. */"]

		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the region starts. */"]

		name  = c_name(local_name(struct, placement))
		item  = f"{name}_item"

		lines = self._tlv_item_type(placement, grammar, item)
		lines.extend(self._tlv_read(placement, grammar, item, name))
		lines.extend(self._tlv_cursor(item, name, start))
		lines.extend(self._tlv_by_name(grammar, item, name))
		return lines

	def _tlv_tag_bytes(self, placement: Placement) -> int:
		declared = next((decl for decl in self.schema.varints()
		                 if decl.name == placement.tlv_tag_varint), None)
		bits = declared.max_bits if declared is not None else 64
		return (bits + 6) // 7

	def _tlv_item_type(self, placement: Placement, grammar: TlvGrammar,
			item: str) -> list[str]:
		"""One item's extent and what its tag decoded to."""
		parts = [f"\t\tstd::uint32_t {c_name(part.name)};"
		         f"\t/* {part.source} */" for part in grammar.tag_decode]

		return [
			"",
			f"\t/* One item of {placement.path}, and where the next one starts.",
			"\t *",
			"\t * The decoded parts are named by the schema; a backend"
			" inventing its own",
			"\t * would be describing protobuf rather than this region. */",
			f"\tstruct {item} {{",
			"\t\tsitu_view_t   view;",
			"\t\tstd::uint32_t at;",
			"\t\tstd::uint32_t next;",
			"\t\tstd::uint64_t tag;\t/* the raw tag, as read */",
			*parts,
			"\t\tstd::uint32_t value_at;",
			"\t\tstd::uint32_t value_len;",
			"\t};",
		]

	def _tlv_read(self, placement: Placement, grammar: TlvGrammar,
			item: str, name: str) -> list[str]:
		"""Read the item at `at`: its tag, its parts, and where its value ends."""
		max_tag  = self._tlv_tag_bytes(placement)
		assigned = ["view", "at", "tag"] + [c_name(part.name)
		                                    for part in grammar.tag_decode]
		width    = max(len(each) for each in assigned)
		stored   = [f"\t\tout.{each.ljust(width)} = {value};" for each, value in
		            (("view", "this->raw()"), ("at", "at"), ("tag", "tag"))]
		stored  += [f"\t\tout.{c_name(part.name).ljust(width)}"
		            f" = static_cast<std::uint32_t>({part.source});"
		            for part in grammar.tag_decode]

		lines = [
			"",
			f"\t/* Read the item at `at`. `bounds` where the region ends or an",
			"\t * item runs past it; `constraint` for a wire type this schema",
			"\t * does not describe. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_read(std::uint32_t at,"
			f" {item} &out) const noexcept",
			"\t{",
			"\t\tstd::uint64_t tag  = 0;",
			"\t\tstd::uint32_t used = 0;",
			"\t\tstd::uint32_t size = 0;",
			"",
			"\t\tif (at >= limit()) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			f"\t\tused = situ_varint_get(base() + at, limit() - at,"
			f" {max_tag}u, &tag);",
			"\t\tif (used == 0u) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			*stored,
			"\t\tat += used;",
			"",
		]

		lines.extend(self._tlv_value_extent(grammar, max_tag, placement.endian))
		lines.extend([
			"",
			"\t\tif (size > limit() - at) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			"\t\tout.value_at  = at;",
			"\t\tout.value_len = size;",
			"\t\tout.next      = at + size;",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		])
		return lines

	def _tlv_value_extent(self, grammar: TlvGrammar, max_tag: int,
			endian: ast.Endian | None) -> list[str]:
		"""Where the value ends, dispatched as the schema dispatches it."""
		if grammar.selector is None:
			return self._tlv_prefixed_size(grammar.length_type or "u8",
			                               "\t\t", endian)

		lines = [f"\t\tswitch (out.{c_name(grammar.selector)}) {{"]
		for rule in grammar.rules:
			if rule.label is None:
				continue
			lines.append(f"\t\tcase {rule.label}u:")
			lines.extend(self._tlv_one_rule(rule, max_tag, endian))

		default = next((rule for rule in grammar.rules if rule.label is None),
		               None)
		lines.append("\t\tdefault:")
		if default is None or default.kind == "error":
			lines.extend([
				"\t\t\t/* `default: error`: a wire type this schema does not",
				"\t\t\t * describe, so where the value ends is not knowable. */",
				"\t\t\treturn ::situ::rt::err::constraint;",
			])
		else:
			lines.extend(self._tlv_one_rule(default, max_tag, endian))
		lines.append("\t\t}")
		return lines

	def _tlv_one_rule(self, rule: ValueRule, max_tag: int,
			endian: ast.Endian | None) -> list[str]:
		if rule.kind == "fixed":
			return [f"\t\t\tsize = {rule.size}u;", "\t\t\tbreak;"]
		if rule.kind == "error":
			return ["\t\t\treturn ::situ::rt::err::constraint;"]
		if rule.kind == "self_delimiting":
			return [
				"\t\t\t{",
				"\t\t\t\tstd::uint64_t carried = 0;",
				f"\t\t\t\tused = situ_varint_get(base() + at, limit() - at,"
				f" {max_tag}u, &carried);",
				"\t\t\t\tif (used == 0u) {",
				"\t\t\t\t\treturn ::situ::rt::err::bounds;",
				"\t\t\t\t}",
				"\t\t\t\tsize = used;",
				"\t\t\t}",
				"\t\t\tbreak;",
			]
		return [*self._tlv_prefixed_size(rule.length_type or "u8", "\t\t\t",
		                                 endian),
		        "\t\t\tbreak;"]

	def _tlv_prefixed_size(self, length_type: str, indent: str,
			endian: ast.Endian | None) -> list[str]:
		"""`prefixed(T)`: a length in T, then that many bytes."""
		declared = next((decl for decl in self.schema.varints()
		                 if decl.name == length_type), None)

		if declared is not None:
			width = (declared.max_bits + 6) // 7
			return [
				f"{indent}{{",
				f"{indent}\tstd::uint64_t length = 0;",
				f"{indent}\tused = situ_varint_get(base() + at, limit() - at,"
				f" {width}u, &length);",
				f"{indent}\tif (used == 0u) {{",
				f"{indent}\t\treturn ::situ::rt::err::bounds;",
				f"{indent}\t}}",
				f"{indent}\tat += used;",
				f"{indent}\tif (length > static_cast<std::uint64_t>"
				f"(limit() - at)) {{",
				f"{indent}\t\treturn ::situ::rt::err::bounds;",
				f"{indent}\t}}",
				f"{indent}\tsize = static_cast<std::uint32_t>(length);",
				f"{indent}}}",
			]

		scalar = lookup(length_type)
		width  = (scalar.bits + 7) // 8 if scalar is not None else 1
		suffix = {2: "16", 4: "32", 8: "64"}.get(width)
		order  = _order_suffix(endian)
		read   = ("static_cast<std::uint32_t>(base()[at])" if suffix is None
		          else f"static_cast<std::uint32_t>"
		               f"(situ_get_{order}{suffix}(base() + at))")
		return [
			f"{indent}{{",
			f"{indent}\tif (limit() - at < {width}u) {{",
			f"{indent}\t\treturn ::situ::rt::err::bounds;",
			f"{indent}\t}}",
			f"{indent}\tsize = {read};",
			f"{indent}\tat += {width}u;",
			f"{indent}}}",
		]

	def _tlv_cursor(self, item: str, name: str, start: str) -> list[str]:
		"""`first`, `next` and `count`: the region walked from its own start."""
		return [
			"",
			"\t/* The first item, or `bounds` if the region is empty. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_first({item} &out)"
			" const noexcept",
			"\t{",
			f"\t\treturn {name}_read({start}, out);",
			"\t}",
			"",
			"\t/* The item after this one. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_next({item} &item)"
			" const noexcept",
			"\t{",
			f"\t\treturn {name}_read(item.next, item);",
			"\t}",
			"",
			"\t/* How many items are present. A walk: nothing in the region",
			"\t * records a count. */",
			f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
			"\t{",
			f"\t\t{item} item{{}};",
			"\t\tstd::uint32_t n = 0;",
			f"\t\t::situ::rt::err e = {name}_first(item);",
			"",
			"\t\twhile (e == ::situ::rt::err::ok) {",
			"\t\t\tn += 1;",
			f"\t\t\te = {name}_next(item);",
			"\t\t}",
			"\t\treturn n;",
			"\t}",
		]

	def _tlv_by_name(self, grammar: TlvGrammar, item: str,
			name: str) -> list[str]:
		"""`find`, and one accessor per tag the schema names."""
		if not grammar.known:
			return []

		keyed = (f"item.{c_name(grammar.identity)}" if grammar.identity
		         else "static_cast<std::uint32_t>(item.tag)")
		named = (f"the part `{grammar.identity}` decodes to" if grammar.identity
		         else "the raw tag")

		lines = [
			"",
			f"\t/* The first item whose tag is `tag`, matched against {named}",
			"\t * (decision 0023). O(n): the region is walked from the start,",
			"\t * which is what `access = Sequential` costs. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}_find(std::uint32_t tag,"
			f" {item} &item) const noexcept",
			"\t{",
			f"\t\t::situ::rt::err e = {name}_first(item);",
			"",
			"\t\twhile (e == ::situ::rt::err::ok) {",
			f"\t\t\tif ({keyed} == tag) {{",
			"\t\t\t\treturn ::situ::rt::err::ok;",
			"\t\t\t}",
			f"\t\t\te = {name}_next(item);",
			"\t\t}",
			"\t\treturn e;",
			"\t}",
		]

		for known in grammar.known:
			described = f"tag {known.tag}"
			if known.wire is not None:
				described += f", wire type {known.wire}"
			if known.type_name is not None:
				described += f", carrying {known.type_name}"
				described += "[]" if known.repeated else ""
			lines.extend([
				"",
				f"\t/* `{known.name}`: {described}. */",
				f"\t[[nodiscard]] ::situ::rt::err {c_name(known.name)}"
				f"({item} &item) const noexcept",
				"\t{",
				f"\t\treturn {name}_find({known.tag}u, item);",
				"\t}",
			])

		return lines

	def _coded_region(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""The encoded bytes of a coded region, and the decode beside them.

		A region with no delimiter answered `REGION` in the shared classifier
		and this backend emitted nothing, so the bytes on the wire were
		unreachable -- odd for a treat-as-bytes region, and true only of that
		case: the scan path emits a pointer for the delimited one.
		"""
		name  = c_name(local_name(struct, placement))
		start = self._offset_expression(struct, placement)
		if start is None or placement.size_max_bits is None \
				or placement.size_bits % BITS_PER_BYTE:
			return ["", f"\t/* No accessor for {placement.path}: its encoded",
			        f"\t * extent is {placement.codec}'s to report. */"]

		# The interior's extent through the codec's expansion
		# (`traverse.region_extent`), not the region's minimum: a region whose
		# interior the data sizes reported zero bytes, in all four backends
		# and with no refusal (26.35). A fixed interior is unaffected -- its
		# minimum is its extent.
		size = self._region_length(struct, placement)
		if size is None:
			return ["", f"\t/* No accessor for {placement.path}: its encoded",
			        f"\t * extent is {placement.codec}'s to report. */"]

		lines = [
			"",
			f"\t/* {placement.path} is `{placement.codec}` output: the bytes on",
			"\t * the wire rather than the value. What they mean is behind the",
			"\t * transform (13.5), which is what `stage = TransformTime`"
			" says. */",
			f"\t[[nodiscard]] ::situ::rt::bytes {name}() const noexcept",
			"\t{",
			# Clamped like every other length the message decides: the
			# interior is sized by fields an attacker fills in, and a span is
			# a pointer that carries one.
			f"\t\treturn ::situ::rt::bytes(base() + ({start}),",
			f"\t\t\tsitu_min_u32({size},"
			f" situ_remaining_u32(limit(), {start})));",
			"\t}",
		]

		return lines + self._decode_accessor(struct, placement, f"({size})")

	def _coded_delimited(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""A region found by scanning and then decoded (section 13.6).

		Scan first, decode second, and the order is the protocol's: a stuffing
		code protects its own terminator, so the sequence is unambiguous in the
		encoded bytes and would not be in the decoded ones. This backend
		emitted the bytes and said nothing at all about the transform, so a
		reader had no way to know they were not the value.
		"""
		name    = c_name(local_name(struct, placement))
		decoded = self._decode_accessor(struct, placement, f"{name}_len()")

		about = ([("\t * The decoded bytes are below: the transform is derived"
		           " from the"),
		          f"\t * kernel, so the length is {placement.codec}'s to report"
		          " and not this",
		          "\t * header's to guess."] if decoded else
		         [("\t * There is no accessor for the decoded bytes: the"
		           " transform is the"),
		          f"\t * caller's to run, and its length is {placement.codec}'s"
		          " to report",
		          "\t * rather than this header's to guess."])

		return [
			"",
			f"\t/* {placement.path} is `{placement.codec}` output, and the"
			" bytes above",
			"\t * are the encoded form.",
			"\t *",
			*about,
			"\t *",
			"\t * The scan runs on the encoded bytes, which is the order the",
			"\t * format specifies -- a stuffing code protects its own",
			"\t * terminator, so the sequence is unambiguous here and would",
			"\t * not be after decoding. */",
			*decoded,
		]

	def _decode_accessor(self, struct: ResolvedStruct, placement: Placement,
			encoded: str) -> list[str]:
		"""The decoded bytes, into a buffer the caller owns.

		`encoded` is how many bytes the wire form occupies -- a constant for a
		sized region, the scan's own length for a delimited one. Not the span:
		the span includes the delimiter, and the delimiter is not the codec's
		to transform.
		"""
		codec = self.codecs.get(placement.codec or "")
		if codec is None:
			return []

		# A tier-1 codec is bound to an implementation and to the ABI of
		# 13.2a, which is a settled shape whatever the algorithm -- so a
		# region with an `extern` impl decodes here too, where before it
		# handed back its bytes and nothing else (26.35).
		symbol = extern_symbol(self.schema, placement.codec or "")
		if symbol is not None:
			return self._extern_decode(struct, placement, codec, symbol,
			                           encoded)

		if not decodes_here(codec):
			return []

		ratio = codec.ratio
		if ratio is None or ratio[0] == 0:
			return []

		name    = c_name(local_name(struct, placement))
		bound   = decode_bound(codec, placement)
		bitwise = decode_counts_bits(codec)
		scale   = " * 8u" if bitwise else ""
		unscale = " / 8u" if bitwise else ""

		return [
			"",
			"\t/* The decoded bytes, into a buffer the caller owns. Nothing",
			"\t * here allocates, so the capacity is a parameter.",
			"\t *",
			f"\t * `{placement.codec}` is {ratio[0]}:{ratio[1]}, so the value"
			" is that much",
			"\t * smaller than the wire form. A short buffer is refused rather",
			"\t * than half-filled. */",
			*([f"\tstatic constexpr std::uint32_t {name}_decoded_max ="
			   f" {bound}u;"] if bound is not None else []),
			f"\t[[nodiscard]] ::situ::rt::err {name}_decode(std::uint8_t *out,",
			"\t\t\tstd::uint32_t cap, std::uint32_t &len) const noexcept",
			"\t{",
			f"\t\tconst std::uint32_t encoded = {encoded};",
			f"\t\tconst std::uint32_t need = encoded * {ratio[1]}u"
			f" / {ratio[0]}u;",
			"",
			"\t\tif (cap < need) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			f"\t\tlen = situ_{c_name(placement.codec or '')}_decode("
			f"{name}().data(),",
			f"\t\t\tencoded{scale}, out){unscale};",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]

	def _extern_decode(self, struct: ResolvedStruct, placement: Placement,
			codec: ast.CodecDecl, symbol: str, encoded: str) -> list[str]:
		"""The decode of a tier-1 region, through the ABI its `impl` binds.

		Declared at file scope with C linkage by `_extern_declarations`: a
		linkage specification is not allowed in a block, so it cannot go
		inside the class that calls it -- the same reason the derived decoder
		is declared there.
		"""
		name  = c_name(local_name(struct, placement))
		bound = decode_bound(codec, placement)

		return [
			"",
			f"\t/* The decoded bytes of {placement.path}, into a buffer the",
			"\t * caller owns. Nothing here allocates, so the capacity is a",
			"\t * parameter.",
			"\t *",
			f"\t * `{placement.codec}` is a tier-1 codec: `{symbol}_decode` is"
			" the",
			"\t * implementation this schema binds, and its error is its own"
			" to",
			"\t * report (13.1, 13.2a). */",
			*([f"\tstatic constexpr std::uint32_t {name}_decoded_max ="
			   f" {bound}u;"] if bound is not None else []),
			f"\t[[nodiscard]] ::situ::rt::err {name}_decode(std::uint8_t *out,",
			"\t\t\tstd::uint32_t cap, std::uint32_t &len) const noexcept",
			"\t{",
			f"\t\treturn static_cast<::situ::rt::err>({symbol}_decode(",
			f"\t\t\t{name}().data(), {encoded}, out, cap, &len));",
			"\t}",
		]

	def _region_runs(self, struct: ResolvedStruct) -> list[str]:
		"""A run of records inside a region, walked from out here.

		Everything else in a sealed region is reached through the gate, and a
		run is too -- but how far it *reaches* is not a question about the
		plaintext: it is what places the members after the region and what the
		tag covering it has to span. `own_entries` drops a dotted path, so
		this class had no walk at all while its own `mac()` named one, and the
		header did not compile. C emits the same family on the view for the
		same reason.
		"""
		lines: list[str] = []
		for entry in struct.entries:
			placement = entry.placement
			if placement.kind != "field":
				continue
			# A `coded` region's interior as well as a `sealed` one's: the
			# region names its own length through its members, and a run
			# is measured by a walk whichever kind of region it is in.
			# Keyed on `sealed_by` alone, a run inside a `coded` region
			# named a span nothing emitted -- the same defect one
			# container over, found the day that container joined the
			# composed space.
			inside = (placement.sealed_by is not None
			          or (placement.codec is not None
			              and "." in placement.path[len(struct.name) + 1:]))
			if not inside:
				continue
			if placement.type_name not in self.structs:
				continue
			if not is_counted_run(self.resolved.structs, placement) \
					and placement.repeat_while is None:
				continue
			lines.extend(self._variable(struct, placement))
		return lines

	def _covered_nested_setters(self, struct: ResolvedStruct) -> list[str]:
		"""A covered write for a field of a *nested* struct, on the parent.

		`own_entries` drops a dotted path, and a nested struct's fields have
		one -- so a covered field inside one never reached the branch above,
		and the only way to write it was the nested type's own setter, which
		marks nothing. The map says `auth = Covered(t)` about that field and
		14.2 says a covered write leaves `t` stale, so a backend with no
		marking path does not have the operation the map describes.

		C has flattened these onto the parent since the machinery landed;
		this backend, Rust and Python did not, and nothing compared writes
		until now (26.35). The nested type keeps its own plain setter, which
		is right: `inner` may be used where no tag covers it, and the type
		cannot know.
		"""
		covered = [entry for entry in struct.entries
		           if "." in local_name(struct, entry.placement)
		           and entry.placement.covered_by
		           and entry.placement.scalar is not None
		           and entry.placement.kind == "field"
		           and entry.placement.array_count is None
		           and entry.placement.sized_by is None
		           and entry.vector.get(Axis.MUTATE).base in ("InPlaceFixed",
		                                                      "InPlaceSlack")]
		lines: list[str] = []

		for entry in covered:
			placement = entry.placement
			scalar    = placement.scalar
			assert scalar is not None

			# A sealed member is not written from out here: the interior is
			# behind the gate of 14.3, and this wrote it at its plaintext
			# offset from the outer view. C has demanded the gate since the
			# machinery landed. The gated setter goes with the interior.
			if placement.sealed_by is not None:
				continue

			name  = c_name(local_name(struct, placement))
			ctype = self._field_ctype(placement)
			what  = ", ".join(placement.covered_by)
			bits  = self._dirty_bits(struct, placement)

			# The offset may be the message's, and a field of a nested struct
			# behind a variable-length member has a *frame-relative* one --
			# measured from the nested struct rather than from this view.
			owner = dynamic_frame_owner(struct, placement)
			start = self._offset_expression(struct, owner or placement)
			if placement.offset_bits is None or owner is not None:
				if start is None:
					lines.extend([
						"",
						f"\t/* No set_{name}(): this backend cannot resolve",
						f"\t * where {placement.path} starts. */",
					])
					continue
				at: str | None = (f"({start}) + {placement.offset_bytes}"
				                  if owner is not None else f"({start})")
			else:
				at = None

			# ...and the offset is the message's, so the frame is not known
			# to hold it. Every other dynamic setter says this; the covered
			# one wrote whatever the sum came to.
			width = max(1, scalar.bits // BITS_PER_BYTE)
			guard = ([] if at is None else [
				f"\t\tif (!situ_in_bounds(raw(), {at}, {width})) {{",
				"\t\t\treturn;",
				"\t\t}",
			])
			lines.extend([
				"",
				f"\t/* {placement.path} is under {what}, so writing it here",
				"\t * marks the bit. Its own type's setter cannot: `"
				f"{placement.type_name}` may sit",
				"\t * where nothing covers it. */",
				f"\tvoid set_{name}(::situ::rt::message &owner, {ctype} value)"
				" noexcept",
				"\t{",
				*guard,
				f"\t\t{self._store(scalar, placement, 'value', at)}",
				f"\t\towner.mark_dirty({bits});",
				"\t}",
			])

		return lines

	def _arm_accessors(self, struct: ResolvedStruct) -> list[str]:
		"""Each variant arm's members, guarded by the discriminant (9.6).

		Walked explicitly because an arm's member is nested by path and
		`own_entries` rightly leaves it out -- but an arm is not a type, so
		there is no other section it could be emitted in.
		"""
		lines: list[str] = []
		for variant in own_members(struct):
			if variant.kind != "variant":
				continue
			for arm, member in arm_members(struct, variant):
				if member is None:
					continue
				lines.extend(self._arm_member(struct, variant, arm, member))
		return lines

	def _arm_member(self, struct: ResolvedStruct, variant: Placement,
			arm: Arm, placement: Placement) -> list[str]:
		"""One arm member, behind the test that its arm is the one present.

		Reading another arm's bytes stays inside the view -- the extent
		bounds it -- and means nothing, which is a wrong answer rather than a
		fault. `err::version` is what `default: error` returns, being the
		same mistake from the other end.
		"""
		held = self._over_fields(struct, variant.discriminant or "")
		if arm.value is None:
			matched = matched_values(variant)
			if not matched:
				return []
			test = "(" + " || ".join(f"{held} == {one.value}u"
			                         for one in matched) + ")"
		else:
			test = f"{held} != {arm.value}u"

		name   = c_name(local_name(struct, placement))
		scalar = placement.scalar
		start  = self._offset_expression(struct, placement)
		if start is None:
			return []

		head = [
			"",
			f"\t/* {placement.path}, present when the discriminant selects"
			f" `{arm.source or arm.value}`. */",
		]
		refuse = [f"\t\tif ({test}) {{",
		          "\t\t\treturn ::situ::rt::err::version;",
		          "\t\t}"]

		# `data_sized` in the guard, not just the two spellings that name a
		# count: `i32 run[n + 1]` sets neither `array_count` nor `sized_by`,
		# so an arm that is a run of values looked exactly like a scalar arm
		# and got a getter for the first element. The same sentence 26.47
		# wrote about the ordinary member dispatch, in the parallel one an
		# arm has.
		if scalar is not None and placement.array_count is None \
				and placement.sized_by is None \
				and not data_sized(placement):
			ctype = self._field_ctype(placement)
			return [
				*head,
				f"\t[[nodiscard]] ::situ::rt::err {name}({ctype} &out)"
				" const noexcept",
				"\t{",
				*refuse,
				f"\t\tout = {self._load(scalar, placement, None)};",
				"\t\treturn ::situ::rt::err::ok;",
				"\t}",
			]

		if scalar is not None and scalar.bits == BITS_PER_BYTE:
			# A constant count is a length too, and `_length_expression`
			# answers only for the ones the data decides -- so `u8
			# gateway[4]`, an ICMP redirect's whole payload, was declined
			# with a note saying its length could not be computed. Four.
			length = (self._length_expression(struct, placement)
			          if placement.array_count is None
			          else f"{placement.array_count}u")
			if length is None:
				return [*head, "\t/* ...and its length is not one this can"
				        " compute. */"]
			return [
				*head,
				f"\t[[nodiscard]] ::situ::rt::err {name}"
				"(::situ::rt::bytes &out) const noexcept",
				"\t{",
				*refuse,
				# Clamped the way an ordinary run is: the length is the
				# message's, and a span is a pointer that carries one. A DNS
				# label declaring 55 bytes in a five-byte frame handed the
				# caller a 55-byte span.
				f"\t\tout = ::situ::rt::bytes(base() + ({start}),",
				f"\t\t\tsitu_min_u32({length},"
				f" situ_remaining_u32(limit(), {start})));",
				"\t\treturn ::situ::rt::err::ok;",
				"\t}",
			]

		if scalar is not None and indexed_elements(placement):
			# A run of values wider than a byte. The span above is not
			# available to it -- the element is ValueConverted, so the bytes
			# are not the values -- so it is the count and the indexed getter
			# an ordinary run gets, each behind the discriminant test.
			width  = scalar.bits // BITS_PER_BYTE
			length = (self._length_expression(struct, placement)
			          if placement.array_count is None
			          else f"{placement.array_count * width}u")
			if length is not None:
				ctype = self._field_ctype(placement)
				return [
					*head,
					f"\t[[nodiscard]] ::situ::rt::err {name}_count"
					"(std::uint32_t &out) const noexcept",
					"\t{",
					*refuse,
					f"\t\tout = situ_min_u32({length},",
					f"\t\t\tsitu_remaining_u32(limit(), {start})) / {width}u;",
					"\t\treturn ::situ::rt::err::ok;",
					"\t}",
					f"\t[[nodiscard]] ::situ::rt::err {name}"
					f"(std::uint32_t index, {ctype} &out) const noexcept",
					"\t{",
					"\t\tstd::uint32_t held = 0;",
					f"\t\tconst ::situ::rt::err e = {name}_count(held);",
					"",
					"\t\tif (e != ::situ::rt::err::ok) {",
					"\t\t\treturn e;",
					"\t\t}",
					"\t\tif (index >= held) {",
					"\t\t\treturn ::situ::rt::err::bounds;",
					"\t\t}",
					f"\t\tout = {self._load(scalar, placement, f'({start}) + index * {width}')};",
					"\t\treturn ::situ::rt::err::ok;",
					"\t}",
				]

		nested = self.resolved.structs.get(placement.type_name or "")

		# A *variable-size* struct arm, measured from its own bytes. C has
		# emitted one since variants landed and the other three demanded a
		# single size -- while `validate` called the accessor regardless, so
		# the header did not compile for a schema with such an arm. MQTT is
		# four of them: CONNECT, PUBLISH, SUBSCRIBE and UNSUBSCRIBE all end
		# in something the data sizes (26.55).
		if nested is not None and not nested.layout.is_fixed_size \
				and has_computable_extent(self.resolved.structs, nested):
			inner = c_name(nested.name)
			return [
				*head,
				f"\t[[nodiscard]] ::situ::rt::err {name}"
				f"(::{self.namespace}::{inner} &out) const noexcept",
				"\t{",
				*refuse,
				"\t\tsitu_view_t whole;",
				f"\t\tsitu_err_t e = situ_view_sub(this->raw(), {start},",
				f"\t\t\tsitu_remaining_u32(limit(), {start}), &whole);",
				"",
				"\t\tif (e != SITU_OK) {",
				"\t\t\treturn static_cast<::situ::rt::err>(e);",
				"\t\t}",
				"",
				"\t\t/* Twice: once over what is left, to give the extent",
				"\t\t * something to measure, and once at the size it says. */",
				f"\t\te = situ_view_sub(this->raw(), {start},",
				f"\t\t\t::{self.namespace}::{inner}(whole).extent(), &whole);",
				"\t\tif (e == SITU_OK) {",
				f"\t\t\tout = ::{self.namespace}::{inner}(whole);",
				"\t\t}",
				"\t\treturn static_cast<::situ::rt::err>(e);",
				"\t}",
			]

		if nested is not None and nested.layout.is_fixed_size:
			return [
				*head,
				f"\t[[nodiscard]] ::situ::rt::err {name}"
				f"(::{self.namespace}::{c_name(nested.name)} &out)"
				" const noexcept",
				"\t{",
				*refuse,
				# Through `situ_view_sub`, which is the bounds check a nested
				# member has had since 26.31 and an arm had not: an arm sits at
				# an offset the discriminant chose, and a view built by hand
				# claimed the struct's size whatever the frame held.
				"\t\tsitu_view_t raw;",
				f"\t\tconst situ_err_t e = situ_view_sub(this->raw(), {start},"
				f" {c_name(nested.name)}::size_bytes, &raw);",
				"",
				"\t\tif (e == SITU_OK) {",
				f"\t\t\tout = ::{self.namespace}::{c_name(nested.name)}(raw);",
				"\t\t}",
				"\t\treturn static_cast<::situ::rt::err>(e);",
				"\t}",
			]

		return [*head, f"\t/* ...and `{placement.name}` is not a shape this"
		        " backend reaches into yet. */"]

	def _explained(self, struct: ResolvedStruct, entry: Resolved) -> list[str]:
		"""One member, and where it has no setter, why.

		Section 1: the absence of an operation is "deliberate, explained, and
		assertable". The explanation lived in the scalar branch, which a
		delimited or variable member never reaches -- so
		`http.request_line.method` had a span, a length, no setter and nothing
		saying so (26.35).
		"""
		lines  = self._member(struct, entry)
		mutate = entry.vector.get(Axis.MUTATE)

		if not lines or mutate.base in ("InPlaceFixed", "InPlaceSlack"):
			return lines
		if any("mutate is" in line or "No setter" in line for line in lines):
			return lines
		if not any("::situ::rt::bytes" in line or "const_bytes" in line
		           for line in lines):
			return lines

		return lines + [
			"",
			f"\t/* No setter: mutate is {mutate.render()}. The span above is",
			"\t * where the bytes are; making room for more of them is a"
			" rewrite",
			"\t * of the frame rather than a store. */",
		]

	def _member(self, struct: ResolvedStruct, entry: Resolved) -> list[str]:
		placement = entry.placement

		# The order is `traverse.classify`'s rather than this file's: three
		# backends shipped the same two mistakes when each kept its own.
		kind = classify(struct, placement, self.structs)

		if kind is Member.OPAQUE:
			return self._opaque(struct, placement)
		if kind is Member.TAG:
			return self._tag(struct, placement)
		if kind is Member.MARKER:
			return self._marker(struct, placement)
		if kind is Member.RESERVED:
			return ["",
			        f"\t/* {placement.path} is reserved: no accessor, and"
			        f" `validate` holds it to",
			        "\t * the pattern the schema declares. */"]
		if kind is Member.CODED:
			return self._coded_region(struct, placement)
		if kind is Member.TLV:
			return self._tlv_region(struct, placement)
		if kind is Member.INDEXED:
			return self._indexed_region(struct, placement)
		if kind is Member.LOCATED:
			return self._located(struct, placement)
		if kind is Member.REPEAT_WHILE:
			return self._repeat_while(struct, placement)
		if kind is Member.DELIMITED:
			lines = self._delimited(struct, placement)
			if placement.codec is not None:
				lines.extend(self._coded_delimited(struct, placement))
			return lines
		if kind is Member.RECORD_RUN:
			return self._record_run(struct, placement)
		if kind is Member.VARIABLE:
			return self._variable(struct, placement)
		if kind is Member.NESTED:
			return self._nested(struct, placement)
		if kind is Member.TEXT_NUMBER:
			return self._fixed_text_number(struct, placement)
		if kind is Member.ARRAY:
			return self._array(struct, placement)
		if kind is Member.VARINT:
			return self._varint_field(struct, placement)
		if kind is Member.SCALAR:
			return self._scalar(struct, entry)
		if kind is Member.NOTHING:
			return []

		# A sealed region has no accessor of its own: its interior is behind
		# the gate, which is emitted below. The fallthrough note read as a
		# missing feature while sitting directly above the thing that supports
		# it -- the same contradiction the coded-region note had.
		if placement.kind == "sealed":
			return ["",
			        f"\t/* {placement.path} is sealed by {placement.codec}:"
			        " it has no",
			        "\t * accessor of its own, and its interior is reached"
			        " through the",
			        "\t * gate below, which opens only once the tag has"
			        " verified (14.3). */"]

		if placement.kind == "variant":
			# Not a gap: a variant has no accessor of its own because there
			# is no one thing to hand back, and its arms are emitted above.
			# The fallthrough note said "not in the static subset yet", which
			# is what a reader would take for a missing feature.
			return ["",
			        f"\t/* {placement.path} is a variant: exactly one arm is",
			        "\t * present, and each is above behind the discriminant"
			        " that",
			        "\t * selects it. There is no accessor for the variant"
			        " itself. */"]
		return ["", f"\t/* {placement.path}: not in the static subset yet. */"]

	def _versioned(self, placement: Placement, name: str, ctype: str,
			load: str) -> list[str]:
		"""A member present only from a given version (section 19.4).

		Out-parameter and `err`, because there is no value to return when the
		field is not there. `[[nodiscard]]` is what makes this stronger than
		the C version: ignoring the error is a diagnostic rather than a habit.
		"""
		version = c_name(placement.version_field or "")
		return [
			f"\t/// Present from version {placement.since}. Reading it from an",
			"\t/// earlier message would return the bytes of whatever follows,",
			"\t/// so this reports rather than guesses.",
			f"\t[[nodiscard]] ::situ::rt::err {name}({ctype} &out) const noexcept",
			"\t{",
			f"\t\tif ({version}() < {placement.since}u) {{",
			"\t\t\treturn ::situ::rt::err::version;",
			"\t\t}",
			*self._versioned_bounds(placement),
			f"\t\tout = {load};",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]

	def _versioned_bounds(self, placement: Placement) -> list[str]:
		"""And the frame has to hold it, which the acquiring check did not say.

		The one place 20.2's argument does not reach: a versioned struct's
		minimum is its *first* version's, so a message declaring version 2 in
		three bytes is a well-formed question about a member that is not
		there. All four backends asked the version and stopped -- C read past
		the view, this handed back the bytes after it, Rust panicked.
		"""
		scalar = placement.scalar
		if scalar is None or placement.offset_bits is None:
			return []
		width = max(1, (scalar.bits + BITS_PER_BYTE - 1) // BITS_PER_BYTE)
		return [
			f"\t\tif (!situ_in_bounds(raw(), {placement.offset_bytes},"
			f" {width})) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
		]

	def _reads_varint(self, placement: Placement) -> bool:
		"""Whether this backend can read the varint this member is.

		A member sized by one it cannot has no length either, so the refusal
		reaches the offset chain rather than naming an accessor nobody wrote.
		Both encodings are read now; the check stays because the next one to
		arrive should reach the same place rather than find it removed.
		"""
		return any(decl.name == placement.varint
		           for decl in self.schema.varints())

	def _varint_field(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""Decode a varint field, and say how wide it turned out to be.

		It classified as `NOTHING` and this backend emitted nothing at all --
		not an accessor and not a note, so the member simply was not there. The
		member *after* it fared better: its offset could not be resolved and
		said so, which is the safe half of the same gap. (C, which does not ask
		the shared classifier, placed it at zero instead and read the varint's
		own bytes.)
		"""
		declared = next((decl for decl in self.schema.varints()
		                 if decl.name == placement.varint), None)
		if declared is None:
			return []

		name   = c_name(local_name(struct, placement))
		start  = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where it starts. */"]

		width  = declared.max_bytes
		signed = declared.transform is ast.VarintTransform.ZIGZAG
		ctype  = "std::int64_t" if signed else "std::uint64_t"
		decoded = ("static_cast<std::int64_t>(situ_zigzag_decode(raw))"
		           if signed else "raw")
		big    = declared.encoding is ast.VarintEncoding.BE128

		# The two encodings differ in which end the groups come from, and the
		# big-endian one in what its last permitted byte carries.
		read = (f"situ_varint_be_get(base() + at, limit() - at, {width}u,"
		        f" {declared.terminal_bits}u, &raw)" if big else
		        f"situ_varint_get(base() + at, limit() - at, {width}u, &raw)")
		encoded = (f"situ_varint_be_len(raw, {width}u,"
		           f" {declared.terminal_bits}u)" if big else
		           "situ_varint_len(raw)")

		minimal = ([
			"",
			"\t\t/* `minimal` is declared, so a padded encoding is a second",
			"\t\t * encoding of one value and this schema does not admit it.",
			"\t\t * A canonicality claim nothing enforced would be a"
			" comment. */",
			"\t\tif (used != situ_varint_len(raw)) {",
			"\t\t\treturn ::situ::rt::err::constraint;",
			"\t\t}",
		] if declared.minimal else [])

		return [
			"",
			f"\t/* {placement.path}: a `{placement.varint}`, 1 to {width} bytes,",
			"\t * and how many is in the bytes themselves.",
			"\t *",
			"\t * `bounds` where the frame ends mid-value; `constraint` where",
			"\t * a padded encoding is refused. Everything after it in this",
			"\t * frame is measured through `_len`, which is what",
			"\t * `offset = Dynamic` costs here -- a read, not a scan. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}({ctype} &out)"
			" const noexcept",
			"\t{",
			f"\t\tconst std::uint32_t at = {start};",
			"\t\tstd::uint64_t raw = 0;",
			*(["\t\tstd::uint32_t used = 0;"] if declared.minimal else []),
			"",
			"\t\tif (at >= limit()) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			f"\t\t{'used = ' if declared.minimal else 'const std::uint32_t used = '}"
			f"{read};",
			"\t\tif (used == 0u) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			*minimal,
			"",
			f"\t\tout = {decoded};",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
			"",
			f"\t/* How many bytes {placement.path} occupies. Zero where it",
			"\t * cannot be read at all, which keeps every offset derived from",
			"\t * it inside the frame -- a width guessed at the maximum would",
			"\t * push them past the end. */",
			f"\t[[nodiscard]] std::uint32_t {name}_len() const noexcept",
			"\t{",
			f"\t\tconst std::uint32_t at = {start};",
			"\t\tstd::uint64_t raw = 0;",
			"",
			"\t\tif (at >= limit()) {",
			"\t\t\treturn 0u;",
			"\t\t}",
			f"\t\treturn {read};",
			"\t}",
			"",
			"\t/* The same value where an error cannot be returned: the length",
			"\t * arithmetic downstream is not fallible, and making it so would",
			"\t * put an error path in every accessor after this one. */",
			f"\t[[nodiscard]] {ctype} {name}_value() const noexcept",
			"\t{",
			f"\t\t{ctype} value = 0;",
			"",
			f"\t\t(void){name}(value);",
			"\t\treturn value;",
			"\t}",
		]

	def _scalar(self, struct: ResolvedStruct, entry: Resolved) -> list[str]:
		placement = entry.placement
		scalar    = placement.scalar
		assert scalar is not None

		# A member after a variable-length one is placed at run time. Its own
		# arithmetic is the struct's -- the same walk `_offset_expression`
		# does -- so the only difference from a static field is where `base()`
		# is measured from.
		offset = (None if placement.offset_bits is not None
		          else self._offset_expression(struct, placement))

		# A bit-packed field cannot land at a dynamic offset: the layout
		# solver refuses the construct outright, because a bit phase across a
		# dynamic boundary is not something it computes (`layout.py`,
		# check_alignment). This is an assertion of that rule rather than a gap
		# in this backend -- if the rule is ever relaxed, it fires here instead
		# of emitting a wrong bit offset, which is undetectable at run time.
		assert not (placement.offset_bits is None and scalar.is_bit_packed), \
			f"{placement.path}: bit-packed at a dynamic offset"

		if placement.offset_bits is None and offset is None:
			return ["", f"\t/* {placement.path}: its offset cannot be"
			        f" resolved. */"]

		name  = c_name(local_name(struct, placement))
		ctype = self._field_ctype(placement)
		lines = ["", *self._axes_comment(entry)]

		load = self._load(scalar, placement, offset)
		if placement.type_name in self.enums:
			load = f"static_cast<{ctype}>({load})"

		# A scalar whose offset the message decides answers zero where it does
		# not fit, rather than reading whatever is at that address (26.27).
		fits = self._fits(struct, placement,
		                  max(1, (scalar.bits + BITS_PER_BYTE - 1)
		                      // BITS_PER_BYTE))

		if placement.since is not None and placement.version_field is not None:
			lines.extend(self._versioned(placement, name, ctype, load))
		elif fits is not None:
			lines.extend([
				"\t/* Zero where the member does not fit the view: its offset"
				" is a sum",
				"\t * of lengths the message chose, and `validate` reports"
				" such a",
				"\t * message as malformed. */",
				f"\t[[nodiscard]] {ctype} {name}() const noexcept",
				"\t{",
				f"\t\treturn {fits} ? {load} : {ctype}{{}};",
				"\t}",
			])
		else:
			lines.extend([
				f"\t[[nodiscard]] {ctype} {name}() const noexcept",
				"\t{",
				f"\t\treturn {load};",
				"\t}",
			])

		if entry.vector.get(Axis.MUTATE).base != "InPlaceFixed":
			lines.extend([
				f"\t/* No setter: mutate is"
				f" {entry.vector.get(Axis.MUTATE).render()}. */",
			])
			return lines

		stored = "value"
		if placement.type_name in self.enums:
			backing = self._ctype(scalar)
			stored  = f"static_cast<{backing}>(value)"

		if placement.since is not None and placement.version_field is not None:
			version = c_name(placement.version_field)
			return lines + [
				f"\t/// Writing it to an earlier message would put these bytes",
				"\t/// past that message's end, so this refuses.",
				f"\t[[nodiscard]] ::situ::rt::err set_{name}({ctype} value)"
				" noexcept",
				"\t{",
				f"\t\tif ({version}() < {placement.since}u) {{",
				"\t\t\treturn ::situ::rt::err::version;",
				"\t\t}",
				# The declared version is the message's claim, not a fact
				# about the buffer: `ver = 2` in three bytes passed this and
				# wrote four bytes past the frame.
				*self._versioned_bounds(placement),
				f"\t\t{self._store(scalar, placement, stored, offset)}",
				"\t\treturn ::situ::rt::err::ok;",
				"\t}",
			]

		# A covered write takes the message, because it has to mark a bit that
		# lives there. This backend used to emit the plain setter for these
		# too, so a C++ caller could write a tag-covered byte and have
		# `transmittable()` go on saying the message was ready to send -- the
		# capability map's `auth = Covered(t)` is a claim that writing marks
		# `t` stale, and here it was not true. C and Python both refuse it.
		if placement.covered_by:
			bits = self._dirty_bits(struct, placement)
			what = ", ".join(placement.covered_by)
			# ...and where the offset is the message's, the frame is not known
			# to hold it. The plain setter below has said so since 26.27 and
			# the covered one above it did not, so the one write that carries a
			# security obligation was the one without the bound.
			body = ([f"\t\t{self._store(scalar, placement, stored, offset)}",
			         f"\t\towner.mark_dirty({bits});"]
			        if fits is None else [
				f"\t\tif ({fits}) {{",
				f"\t\t\t{self._store(scalar, placement, stored, offset)}",
				f"\t\t\towner.mark_dirty({bits});",
				"\t\t}",
			])
			lines.extend([
				f"\t/* Writing this leaves {what} stale, so it takes the message",
				"\t * and marks the bit. The cost is in the signature rather than",
				"\t * in a comment somebody may not read. */",
				f"\tvoid set_{name}(::situ::rt::message &owner, {ctype} value) noexcept",
				"\t{",
				*body,
				"\t}",
			])
			return lines

		# A write at an offset the message chose is the same hole as a read,
		# and worse: reading past the frame is a wrong answer, writing past it
		# is somebody else's data. No error channel here, so it does nothing.
		lines.extend([
			*([] if fits is None else [
				"\t/* Does nothing where the member does not fit the view:"
				" writing past",
				"\t * the frame is somebody else's data, and `validate`"
				" reports it. */",
			]),
			f"\tvoid set_{name}({ctype} value) noexcept",
			"\t{",
			*([f"\t\t{self._store(scalar, placement, stored, offset)}"]
			  if fits is None else [
				f"\t\tif ({fits}) {{",
				f"\t\t\t{self._store(scalar, placement, stored, offset)}",
				"\t\t}",
			]),
			"\t}",
		])
		return lines

	def _dirty_bits(self, struct: ResolvedStruct, placement: Placement) -> str:
		"""The bits every obligation over this field stands for, ORed.

		Every one, not the first: a field under a tag *and* an invariant leaves
		both stale, and marking one of the two is a message that reports itself
		ready to send while a covered byte no longer matches what
		authenticates it.
		"""
		names = [f"dirty_{c_name(held.name)}"
		         for label in placement.covered_by
		         if (held := obligation(self.schema, struct, label)) is not None]
		return " | ".join(names) if names else "0u"

	def _load(self, scalar: ScalarType, placement: Placement,
			offset: str | None = None, on: str = "") -> str:
		"""`on` names another view to read through -- `element` inside a run's
		walk, where `base()` alone would be this struct's rather than the
		element's."""
		prefix = f"{on}." if on else ""
		base   = (f"{prefix}base() + "
		          f"{offset if offset is not None else placement.offset_bytes}")
		ctype  = self._ctype(scalar)

		if scalar.is_bcd:
			raw = self._raw_load(scalar, placement, base)
			return (f"static_cast<{ctype}>(situ_bcd_decode("
			        f"static_cast<std::uint64_t>({raw}), {scalar.digits}))")
		return self._raw_load(scalar, placement, base)

	def _raw_load(self, scalar: ScalarType, placement: Placement,
			base: str) -> str:
		ctype = self._ctype(scalar)

		if scalar.is_bit_packed:
			order = "lsb" if placement.bit_order is ast.BitOrder.LSB_FIRST else "msb"
			raw   = (f"situ_bits_get_{order}(base(), {placement.offset_bits},"
			         f" {scalar.bits})")
			if scalar.signed:
				return (f"static_cast<{ctype}>(situ_sign_extend({raw},"
				        f" {scalar.bits}))")
			return f"static_cast<{ctype}>({raw})"

		if scalar.bits == BITS_PER_BYTE:
			return f"static_cast<{ctype}>(*({base}))"

		# A field the data decides the order of. The branch is on a public,
		# layout-irrelevant value, so it is not a side channel (11.1) -- and
		# without it this read the marker's own format big-endian whatever the
		# marker said.
		if placement.marker is not None and scalar.bits in WORD_WIDTHS:
			predicate = self._marker_predicate(placement)
			return (f"static_cast<{ctype}>({predicate}"
			        f" ? situ_get_le{scalar.bits}({base})"
			        f" : situ_get_be{scalar.bits}({base}))")

		suffix = _order_suffix(placement.endian)
		if scalar.bits in WORD_WIDTHS:
			return f"static_cast<{ctype}>(situ_get_{suffix}{scalar.bits}({base}))"

		assembly = _bit_assembly(placement.endian)
		return (f"static_cast<{ctype}>(situ_bits_get_{assembly}(base(),"
		        f" {placement.offset_bits}, {scalar.bits}))")

	def _store(self, scalar: ScalarType, placement: Placement,
			value: str, offset: str | None = None) -> str:
		base = f"base() + {offset if offset is not None else placement.offset_bytes}"

		if scalar.is_bcd:
			value = (f"situ_bcd_encode(static_cast<std::uint64_t>({value}),"
			         f" {scalar.digits})")

		if scalar.is_bit_packed:
			order = "lsb" if placement.bit_order is ast.BitOrder.LSB_FIRST else "msb"
			return (f"situ_bits_set_{order}(base(), {placement.offset_bits},"
			        f" {scalar.bits}, static_cast<std::uint64_t>({value}));")

		if scalar.bits == BITS_PER_BYTE:
			return f"*({base}) = static_cast<std::uint8_t>({value});"

		# The write has to agree with the read, or a round trip through this
		# view swaps the value: the getter branched on the marker and the
		# setter did not.
		if placement.marker is not None and scalar.bits in WORD_WIDTHS:
			predicate = self._marker_predicate(placement)
			cast      = f"static_cast<std::uint{scalar.bits}_t>({value})"
			return (f"if ({predicate}) {{\n"
			        f"\t\t\tsitu_put_le{scalar.bits}({base}, {cast});\n"
			        f"\t\t}} else {{\n"
			        f"\t\t\tsitu_put_be{scalar.bits}({base}, {cast});\n"
			        f"\t\t}}")

		suffix = _order_suffix(placement.endian)
		if scalar.bits in WORD_WIDTHS:
			return (f"situ_put_{suffix}{scalar.bits}({base},"
			        f" static_cast<std::uint{scalar.bits}_t>({value}));")

		assembly = _bit_assembly(placement.endian)
		return (f"situ_bits_set_{assembly}(base(), {placement.offset_bits},"
		        f" {scalar.bits}, static_cast<std::uint64_t>({value}));")

	# -- aggregates ----------------------------------------------------

	def _located(self, struct: ResolvedStruct, placement: Placement) -> list[str]:
		"""A member the data positions, reached from the message (9.8).

		Takes the message as well as `this`, for the reason the C backend
		does: `::situ::rt::view` wraps a `situ_view_t` and nothing else, so it
		cannot say where offset zero is. Python needs no such parameter, its
		view already holding the message -- which is a difference in the
		runtimes rather than in the construct.
		"""
		name   = c_name(local_name(struct, placement))
		offset = self._over_fields(struct, placement.located or "")
		length = self._length_expression(struct, placement)
		if length is None and placement.is_fixed_size \
				and placement.size_bits % BITS_PER_BYTE == 0:
			length = str(placement.size_bits // BITS_PER_BYTE)
		if length is None:
			return ["",
			        f"\t/* No accessor for {placement.path}: it is placed by",
			        f"\t * `{placement.located}`, and how long it is is not",
			        "\t * something this backend can work out. */"]

		return [
			"",
			f"\t/* {placement.path}, at `{placement.located}` bytes from the start",
			"\t * of the *message* rather than of this view. The offset is the",
			"\t * message's, so nothing about this frame says it is inside the",
			"\t * buffer -- checked here, on every call, which is what",
			"\t * `offset = DataPlaced` in the map costs. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}(const situ_msg_t *msg,",
			"\t\t\t::situ::rt::bytes &out) const noexcept",
			"\t{",
			f"\t\tconst std::uint32_t at = static_cast<std::uint32_t>({offset});",
			f"\t\tconst std::uint32_t n  = static_cast<std::uint32_t>({length});",
			"",
			"\t\tif (n > msg->size || at > msg->size - n) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"\t\tout = ::situ::rt::bytes(msg->base + at, n);",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]

	def _nested(self, struct: ResolvedStruct, placement: Placement) -> list[str]:
		name   = c_name(local_name(struct, placement))
		nested = f"::{self.namespace}::{c_name(placement.type_name or '')}"
		inner  = self.resolved.structs.get(placement.type_name or "")
		start  = self._offset_expression(struct, placement)

		if inner is not None and not inner.layout.is_fixed_size and start is not None:
			# `size_bytes` exists only where a struct has one size, so this
			# named a constant that was never declared and the header did not
			# compile. The extent comes from the bytes instead: hand the
			# member everything that is left, ask how much of it is one of
			# these, and hand back that.
			#
			# And `extent()` is emitted on the same condition, so asking for
			# one that was never emitted is the identical failure a round
			# later -- which is how it arrived the second time.
			if not has_computable_extent(self.resolved.structs, inner):
				return [
					"",
					f"\t/* No accessor for {placement.path}: one "
					f"`{placement.type_name}` has no",
					"\t * extent this backend can compute, so nothing can say"
					" where it ends. */",
				]
			return [
				"",
				f"\t/* {placement.path}. No one size, so its extent is read from",
				"\t * the bytes -- and so is where the member after it starts. */",
				f"\t[[nodiscard]] std::uint32_t {name}_extent() const noexcept",
				"\t{",
				f"\t\treturn {nested}(situ_view_t{{ base() + ({start}),",
				f"\t\t\tlimit() - ({start}), raw().generation }}).extent();",
				"\t}",
				*self._nested_accessor(name, nested, f"({start})",
				                       f"{name}_extent()"),
			]

		# A fixed-size nested struct at whatever offset the members before it
		# leave. This asked the placement for a constant and crashed the
		# compiler on the assertion inside `offset_bytes` -- for a header, a
		# variable-length field and another header, which is as ordinary as a
		# protocol gets. C reads its own offset function here and always has.
		if start is None:
			return ["",
			        f"\t/* No accessor for {placement.path}: this backend cannot",
			        "\t * resolve where it starts. */"]
		where = (str(placement.offset_bytes) if placement.offset_bits is not None
		         else f"({start})")

		return [
			"",
			f"\t/* {placement.path} at {placement.offset_bytes}. Its own class"
			if placement.offset_bits is not None else
			f"\t/* {placement.path}, at an offset the message decides. Its own class",
			"\t * carries its accessors; this is where the parent puts it. */",
			*self._nested_accessor(name, nested, where,
			                       f"{nested}::size_bytes"),
		]

	def _nested_accessor(self, name: str, nested: str, start: str,
			extent: str) -> list[str]:
		"""A sub-view, refused where the parent does not contain it.

		It handed one back unchecked: a view claiming the nested struct's size
		whatever the parent held, which is 20.2's acquisition invariant one
		level in -- every constant-offset accessor on the result trusts that
		its own bytes are all there. C has bounds-checked this since phase 4,
		through `situ_view_sub`, and the other three could not refuse at all;
		the differential check could not even ask the question, because three
		of the four had no way to answer it.

		So the signature changes rather than the body: an out-parameter and an
		error, which is what every other fallible accessor here already looks
		like.
		"""
		return [
			f"\t[[nodiscard]] ::situ::rt::err {name}({nested} &out)"
			" const noexcept",
			"\t{",
			"\t\tsitu_view_t raw;",
			f"\t\tconst situ_err_t e = situ_view_sub(this->raw(), {start},"
			f" {extent}, &raw);",
			"",
			"\t\tif (e == SITU_OK) {",
			f"\t\t\tout = {nested}(raw);",
			"\t\t}",
			"\t\treturn static_cast<::situ::rt::err>(e);",
			"\t}",
		]

	def _marker(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""The byte-order marker's constants and accessors (section 8.3).

		The marker is compared as a byte sequence, not decoded as a number: it
		has to be readable before its own byte order is known. Reading it big
		endian and comparing against the literal as written is the only
		interpretation that does not presuppose the answer.

		This backend emitted "not in the static subset yet" for the marker and
		then read every field it governs big-endian regardless -- so a
		little-endian TIFF, which is most of them, came back byte-swapped with
		no diagnostic. The map said `ConditionallyConverted(byte_order)` on
		each of those fields the whole time.
		"""
		marker = self.markers.get(placement.name)
		scalar = placement.scalar
		if marker is None or scalar is None:
			return []

		env    = self.resolved.layout.env
		little = evaluate(marker.little, env)
		big    = evaluate(marker.big, env)
		width  = scalar.bits
		name   = c_name(local_name(struct, placement))
		digits = width // 4

		return [
			"",
			f"\t/* {placement.path}: which byte order the rest of this frame",
			"\t * uses, read from the data (8.3). The marker is compared as a",
			"\t * byte sequence rather than decoded as a number -- it has to be",
			"\t * readable before its own order is known. */",
			f"\tstatic constexpr std::uint{width}_t {name}_little ="
			f" 0x{little:0{digits}X}u;",
			f"\tstatic constexpr std::uint{width}_t {name}_big ="
			f" 0x{big:0{digits}X}u;",
			"",
			"\t/* The host's own order. A writer stores this rather than",
			"\t * picking an order, which is what makes the writer",
			"\t * deterministic even though the format admits both. */",
			f"\tstatic constexpr std::uint{width}_t {name}_host =",
			f"\t\tSITU_HOST_BIG ? {name}_big : {name}_little;",
			"",
			f"\t[[nodiscard]] bool {name}_is_little() const noexcept",
			"\t{",
			f"\t\treturn situ_get_be{width}(base() + {placement.offset_bytes})"
			f" == {name}_little;",
			"\t}",
			f"\t[[nodiscard]] static constexpr std::uint{width}_t"
			f" {name}_of_host() noexcept",
			"\t{",
			f"\t\treturn {name}_host;",
			"\t}",
			f"\tvoid set_{name}_host() noexcept",
			"\t{",
			f"\t\tsitu_put_be{width}(base() + {placement.offset_bytes},"
			f" {name}_host);",
			"\t}",
		]

	def _marker_predicate(self, placement: Placement) -> str:
		"""Whether the marker this field is governed by says little-endian."""
		return f"{c_name(placement.marker or '')}_is_little()"

	def _fixed_text_number(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""Digits in a field of declared width, padded (section 8.6.2).

		SMTP's reply code and HTTP's status are both this: exactly three
		digits, no delimiter, and the leading zero is required rather than
		tolerated. That is why it is `Canonical` where a delimited text number
		is not -- `007` is the only spelling of seven here.

		It read as an array before: the bracket is a width in bytes and the
		branch took it for a count, so this backend reported an element type
		problem about a number.
		"""
		scalar = placement.scalar
		if scalar is None:
			return []

		name  = c_name(local_name(struct, placement))
		width = placement.array_count or 0
		limit = placement.radix_max or 0
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the digits start. */"]

		ctype = self._ctype(scalar)

		return [
			"",
			f"\t/* {placement.path}: {width} digits, padded, holding"
			f" 0..{limit}.",
			"\t *",
			f"\t * The range is the field's rather than {scalar.name}'s:"
			f" {width} bytes",
			f"\t * cannot hold what {scalar.name} can, and a check against the",
			"\t * type would accept a value the field cannot represent. */",
			f"\t[[nodiscard]] ::situ::rt::const_bytes {name}_digits()"
			" const noexcept",
			"\t{",
			f"\t\treturn ::situ::rt::const_bytes(base() + ({start}),"
			f" {width});",
			"\t}",
			"",
			f"\t[[nodiscard]] ::situ::rt::err {name}({ctype} &out)"
			" const noexcept",
			"\t{",
			"\t\tstd::uint64_t value = 0;",
			"",
			f"\t\t/* Zero is success, which is C's convention here and not",
			"\t\t * this backend's. */",
			f"\t\tif (situ_parse_uint(base() + ({start}), {width}u,"
			f" {placement.radix}u, {limit}u, &value) != 0) {{",
			"\t\t\treturn ::situ::rt::err::constraint;",
			"\t\t}",
			f"\t\tout = static_cast<{ctype}>(value);",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]

	def _tag(self, struct: ResolvedStruct, placement: Placement) -> list[str]:
		"""A tag's bytes, the span it covers, and its dirty bit (14.2).

		This backend emitted the dirty constant and the setters that mark it,
		and then said "not in the static subset yet" about the tag itself --
		so a caller could be told a write left the tag stale and had no way to
		reach the tag, ask whether it was stale, or say it no longer was.

		The span is what the algorithm runs over. Write the result through the
		pointer and then call `finalize`, which clears the bit; until then the
		message is not transmittable.
		"""
		name  = c_name(local_name(struct, placement))
		count = placement.array_count or 0
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the tag sits. */"]

		# Empty where it does not fit: a tag sits after everything it covers,
		# so its offset is a sum of lengths the message chose -- and a span
		# with a length is what lets this answer safely at all, where C has
		# only a pointer and returns NULL (26.27).
		fits = self._fits(struct, placement, count)
		lines = [
			"",
			f"\t/* {placement.path}: {count} bytes. The algorithm is the",
			"\t * caller's to run -- situ says which bytes it covers and when",
			"\t * the result has gone stale, not how to compute it.",
			*([] if fits is None else [
				"\t *",
				"\t * Empty where the member does not fit the view: its offset"
				" is a sum",
				"\t * of lengths the message chose, and `validate` reports"
				" such a",
				"\t * message as malformed.",
			]),
			"\t */",
			f"\t[[nodiscard]] ::situ::rt::bytes {name}() const noexcept",
			"\t{",
			(f"\t\treturn ::situ::rt::bytes(base() + ({start}), {count});"
			 if fits is None else
			 f"\t\treturn {fits}\n"
			 f"\t\t\t? ::situ::rt::bytes(base() + ({start}), {count})\n"
			 "\t\t\t: ::situ::rt::bytes();"),
			"\t}",
		]

		run = covered_run(struct, placement)
		if run is not None:
			first, last = run
			lines.extend([
				"",
				f"\t/* The bytes {placement.name} covers:"
				f" `{'`, `'.join(placement.tag_covers)}`.",
				"\t *",
				"\t * Write the result through the pointer above and then call",
				f"\t * `{name}_finalize`, which clears the dirty bit. A gap in",
				"\t * the coverage is reported rather than papered over with a",
				"\t * range covering bytes the tag does not. */",
				f"\t[[nodiscard]] ::situ::rt::err {name}_covered("
				"std::uint32_t &offset,",
				"\t\t\tstd::uint32_t &len) const noexcept",
				"\t{",
				f"\t\tconst std::uint32_t start ="
				f" {self._offset_expression(struct, first) or '0'};",
				f"\t\tconst std::uint32_t end   ="
				f" {self._region_end(struct, last)};",
				"",
				"\t\tif (end < start || !situ_in_bounds(raw(), start,"
				" end - start)) {",
				"\t\t\treturn ::situ::rt::err::bounds;",
				"\t\t}",
				"",
				"\t\toffset = start;",
				"\t\tlen    = end - start;",
				"\t\treturn ::situ::rt::err::ok;",
				"\t}",
			])

		filler = _self_as(placement.attrs)
		if filler is not None:
			# A checksum defined over its own field runs the algorithm with
			# those bytes taken as a constant. They are still there, so what
			# the compiler hands out is where they are and what they read as
			# (14.2); substituting them is the caller's loop.
			lines.extend([
				"",
				f"\t/* What {placement.name}'s own bytes read as while it is",
				"\t * computed, and where they are. Sum the covered span,",
				"\t * substituting this value for those bytes. RFC 1071 is the",
				"\t * case this exists for. */",
				f"\tstatic constexpr std::uint8_t"
				f" self_as_{c_name(placement.name)} = {filler:#04x};",
				"",
				f"\t[[nodiscard]] ::situ::rt::err {name}_self_span("
				"std::uint32_t &offset,",
				"\t\t\tstd::uint32_t &len) const noexcept",
				"\t{",
				f"\t\tconst std::uint32_t at ="
				f" {self._offset_expression(struct, placement) or '0'};",
				f"\t\tconst std::uint32_t n  ="
				f" {placement.size_bits // BITS_PER_BYTE};",
				"",
				"\t\tif (!situ_in_bounds(raw(), at, n)) {",
				"\t\t\treturn ::situ::rt::err::bounds;",
				"\t\t}",
				"",
				"\t\toffset = at;",
				"\t\tlen    = n;",
				"\t\treturn ::situ::rt::err::ok;",
				"\t}",
			])

		held = obligation(self.schema, struct, placement.name)
		if held is not None:
			lines.extend([
				"",
				f"\t/* Whether {placement.name} no longer matches the bytes it",
				"\t * covers, and how to say it does again. */",
				f"\t[[nodiscard]] static bool {name}_is_dirty("
				"const ::situ::rt::message &owner) noexcept",
				"\t{",
				# The runtime's query is `is_stale` for both kinds of
				# obligation; the accessor is named after this one's, which is
				# `dirty` for a tag (traverse.Obligation).
				f"\t\treturn owner.is_stale(dirty_{name});",
				"\t}",
				f"\tstatic void {name}_finalize(::situ::rt::message &owner)"
				" noexcept",
				"\t{",
				f"\t\towner.clear_dirty(dirty_{name});",
				"\t}",
			])

		return lines

	def _region_end(self, struct: ResolvedStruct, region: Placement) -> str:
		"""Where a region stops, taken from where the next member starts.

		Summing the region's own contents would duplicate the solver badly:
		a region's extent is its interior put through a codec's expansion, and
		the interior is not addressable from outside the gate.
		"""
		if region.is_fixed_size and region.offset_bits is not None:
			return f"{region.offset_bytes + region.size_bits // BITS_PER_BYTE}u"

		members = [entry.placement for entry in own_entries(struct)]
		index   = next((i for i, held in enumerate(members)
		                if held.path == region.path), None)
		if index is not None and index + 1 < len(members):
			return self._offset_expression(struct, members[index + 1]) or "limit()"
		return "limit()"

	def _offsets(self, struct: ResolvedStruct) -> list[str]:
		"""Every dynamic offset in this struct, resolved in one pass.

		The other half of what `access = Sequential` costs. A run makes
		reaching element N a walk of the N-1 before it; a scan makes reaching
		member N a rescan of the N-1 before it, and the per-member offset does
		that on every call -- so reading three members of an HTTP request line
		scans the target twice.

		The memory is the caller's, which is why this is behind
		`--materialize` and not the default: one word per dynamically-placed
		member, and the schema decides how many that is.
		"""
		if not self.materialize:
			return []

		members = [entry.placement for entry in own_entries(struct)]
		dynamic = [held for held in members
		           if held.offset_bits is None and held.located is None]
		if not dynamic:
			return []

		plan = offset_plan(struct, members,
		                   lambda held: self._length_expression(struct, held)
		                   is not None or held.is_fixed_size)
		if plan is None:
			return ["",
			        f"\t/* No offset cache for {struct.name}: a member has no",
			        "\t * length this can compute, so the offsets after it",
			        "\t * cannot be resolved in one pass any more than one at",
			        "\t * a time. */"]

		steps: list[str] = []
		for step in plan:
			if step.kind == "record":
				assert step.placement is not None
				steps.append(f"\t\tout.{c_name(local_name(struct, step.placement))}"
				             " = at;")
			elif step.placement is None:
				steps.append(f"\t\tat += {step.size};")
			else:
				length = self._length_expression(struct, step.placement,
				                                 running="at")
				steps.append(f"\t\tat += {length};")

		fields = [f"\t\tstd::uint32_t {c_name(local_name(struct, held))};"
		          for held in dynamic]

		return [
			"",
			f"\t/* Where each dynamically-placed member of {struct.name}"
			" starts.",
			"\t *",
			"\t * The per-member offset resolves one by summing what precedes",
			"\t * it, so it rescans every delimited member ahead of the one",
			"\t * asked for, on every call. This is that sum once, for all of",
			"\t * them. The memory is the caller's: one word per member. */",
			"\tstruct offsets {",
			*fields,
			"\t};",
			"",
			"\tvoid resolve_offsets(offsets &out) const noexcept",
			"\t{",
			"\t\tstd::uint32_t at = 0;",
			"",
			*steps,
			"\t\t(void)at;",
			"\t}",
		]

	def _opaque(self, struct: ResolvedStruct, placement: Placement) -> list[str]:
		"""Treat-as-bytes, which is the whole of what an `opaque` region
		supports: no interior access, and whole-region replacement only at the
		same size (9.4).

		It reached the fallthrough note, which claims the language does not
		support the construct. The language supports exactly this much of it,
		and said so in C.
		"""
		name   = c_name(local_name(struct, placement))
		start  = self._offset_expression(struct, placement)
		length = self._length_expression(struct, placement)
		if start is None or length is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the region is. */"]

		return [
			"",
			f"\t/* {placement.path}: bytes and nothing more. An opaque region",
			"\t * has no interior to address -- that is what it trades for",
			"\t * carrying anything at all (9.4). */",
			f"\t[[nodiscard]] ::situ::rt::bytes {name}() const noexcept",
			"\t{",
			f"\t\treturn ::situ::rt::bytes(base() + ({start}), {length});",
			"\t}",
		]

	def _array(self, struct: ResolvedStruct, placement: Placement) -> list[str]:
		name   = c_name(local_name(struct, placement))
		scalar = placement.scalar
		count  = placement.array_count or 0

		# An array of structs: one accessor taking an index, which is what the
		# other three backends emit and this one called "not in the static
		# subset yet". The subset had nothing to do with it -- the branch
		# below wants a byte scalar, and a struct element has no scalar at all.
		element = self.resolved.structs.get(placement.type_name or "")
		if scalar is None and element is not None:
			return self._element_array(struct, placement, element)

		# A wide scalar element: an indexed getter, which is what C emits and
		# what the note called "not in the static subset yet". No pointer, for
		# the reason C gives -- the element is ValueConverted, so a pointer
		# into it would alias bytes that are not the value.
		if scalar is not None and scalar.bits != BITS_PER_BYTE \
				and not scalar.is_bit_packed \
				and scalar.bits % BITS_PER_BYTE == 0:
			return self._scalar_array(struct, placement, scalar)

		if scalar is None or scalar.bits != BITS_PER_BYTE:
			return ["", f"\t/* {placement.path}: element type"
			        f" {placement.type_name} is not in the static subset yet. */"]

		lines = [
			"",
			f"\t/* {placement.path}: {count} bytes, MemoryIdentical, so the",
			"\t * pointer and the length travel together. */",
			f"\t[[nodiscard]] ::situ::rt::bytes {name}() const noexcept",
			"\t{",
			f"\t\treturn ::situ::rt::bytes(base() + {placement.offset_bytes},"
			f" {count});",
			"\t}",
		]

		if any(attr.name == "nul_terminated" for attr in placement.attrs):
			lines.extend([
				"",
				f"\t/* Content length: to the first zero byte, or {count}. */",
				f"\t[[nodiscard]] std::uint32_t {name}_len() const noexcept",
				"\t{",
				f"\t\treturn situ_nul_len(base() + {placement.offset_bytes},"
				f" {count});",
				"\t}",
			])
		return lines

	def _variable_elements(self, struct: ResolvedStruct, placement: Placement,
			length: str) -> list[str]:
		"""`u16 x[n]`: a count the message gives, and a getter taking an index.

		The count is clamped to the frame, so a caller looping to it stays
		inside the message however large a number the length field carries --
		which the byte spelling above gets from the same clamp on its span.
		Out of range still reads zero rather than the buffer: this is a count
		the message chose, so a caller who loops to *it* is not making the
		mistake a fixed array's index is (invariant 41).
		"""
		name   = c_name(local_name(struct, placement))
		scalar = placement.scalar
		assert scalar is not None
		width  = scalar.bits // BITS_PER_BYTE
		ctype  = self._ctype(scalar)
		load   = self._load(scalar, placement,
		                    offset=f"{name}_offset() + index * {width}")

		return [
			f"\t[[nodiscard]] std::uint32_t {name}_count() const noexcept",
			"\t{",
			f"\t\treturn situ_min_u32({length},",
			f"\t\t\tsitu_remaining_u32(limit(), {name}_offset())) / {width}u;",
			"\t}",
			f"\t/* Zero past the count: the element is ValueConverted, so a",
			"\t * span of the bytes would not be the values, and the count is",
			"\t * the message's rather than the schema's. */",
			f"\t[[nodiscard]] {ctype} {name}(std::uint32_t index) const noexcept",
			"\t{",
			f"\t\treturn index < {name}_count() ? {load} : static_cast<{ctype}>(0);",
			"\t}",
		]

	def _scalar_array(self, struct: ResolvedStruct, placement: Placement,
			scalar: ScalarType) -> list[str]:
		"""`u16 samples[4]`: one getter taking an index.

		No pointer: the element is `ValueConverted`, so a pointer into it
		would alias bytes that are not the value. Index them individually,
		which is C's rule and the reason it gives.
		"""
		name  = c_name(local_name(struct, placement))
		count = placement.array_count or 0
		width = scalar.bits // BITS_PER_BYTE
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the array starts. */"]

		ctype = self._ctype(scalar)
		load  = self._load(scalar, placement,
		                   offset=f"({start}) + index * {width}")

		return [
			"",
			f"\t/* {placement.path}: {count} elements of {scalar.name}.",
			"\t *",
			"\t * No pointer accessor: the element is ValueConverted, so a",
			"\t * pointer into it would alias bytes that are not the value.",
			"\t * Out of range is the caller's to avoid, as with any array. */",
			f"\tstatic constexpr std::uint32_t {name}_count = {count};",
			f"\t[[nodiscard]] {ctype} {name}(std::uint32_t index)"
			" const noexcept",
			"\t{",
			f"\t\treturn {load};",
			"\t}",
		]

	def _element_array(self, struct: ResolvedStruct, placement: Placement,
			element: ResolvedStruct) -> list[str]:
		"""`reading readings[8]`: one accessor, bounded by the count.

		Bounded by the count and not only by the extent, because bytes after
		the array are inside the view and are not elements -- which is the
		distinction an index check makes and a pointer does not.
		"""
		if not element.layout.is_fixed_size:
			return ["", f"\t/* {placement.path}: one {placement.type_name} has"
			        " no single size,",
			        "\t * so element N is not at a constant stride. */"]

		name  = c_name(local_name(struct, placement))
		inner = c_name(element.name)
		start = self._offset_expression(struct, placement)
		if start is None:
			return ["", f"\t/* {placement.path}: this backend cannot resolve"
			        " where the array starts. */"]

		count = placement.array_count or 0

		return [
			"",
			f"\t/* Element `index` of {count}. Bounded by the count as well as",
			"\t * the extent: bytes after the array are inside the view and are",
			"\t * not elements. */",
			f"\t[[nodiscard]] ::situ::rt::err {name}(std::uint32_t index,",
			f"\t\t\t{inner} &out) const noexcept",
			"\t{",
			f"\t\tif (index >= {count}u) {{",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"",
			f"\t\tsitu_view_t raw;",
			f"\t\tconst std::uint32_t at = ({start})"
			f" + index * {inner}::size_bytes;",
			"",
			f"\t\tif (situ_view_sub(this->raw(), at, {inner}::size_bytes,"
			" &raw) != SITU_OK) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			f"\t\tout = ::situ::{inner}(raw);",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
		]

	# -- validation ----------------------------------------------------

	def _validate(self, struct: ResolvedStruct) -> list[str]:
		checks: list[str] = []

		for entry in own_entries(struct):
			checks.extend(self._check(struct, entry))

		lines = [
			"",
			"\t/* Every constraint the schema declares, on parse. */",
			"\t[[nodiscard]] ::situ::rt::err validate() const noexcept",
			"\t{",
		]
		if not checks:
			lines.append("\t\t/* Nothing in this struct is constrained. */")
		lines.extend(checks)
		lines.extend(["\t\treturn ::situ::rt::err::ok;", "\t}"])
		return lines

	def _delimiter_check(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""The delimiter is there, and a text number's digits are digits.

		That the content excludes the delimiter needs no check: the scan stops
		at the first one, so it holds by construction. A missing delimiter is
		the truncated-frame case, and is the only thing parse can catch.
		"""
		if "." in placement.path[len(struct.name) + 1:]:
			return []		# checked under the element's own struct

		name  = c_name(local_name(struct, placement))
		delim = placement.delimiter
		assert delim is not None

		lines = [
			f"\t\t/* {placement.path} runs to {render_delimiter(delim)}; a frame",
			"\t\t * without it was cut short. */",
			f"\t\tif (!{name}_terminated()) {{",
			"\t\t\treturn ::situ::rt::err::constraint;",
			"\t\t}",
		]

		if placement.radix_minimal:
			# The trimmed bytes, not `{name}()` -- for a text number that is
			# the fallible getter and takes an out-parameter, so calling it
			# here did not compile. The digits to check are the value's, which
			# with `[trim]` start past the whitespace.
			at = (f"base() + {name}_offset()" if not placement.trimmed else
			      f"base() + {name}_offset() + situ_trim_start("
			      f"base() + {name}_offset(), {name}_raw_len())")
			lines.extend([
				"\t\t/* `[minimal]`: one spelling per value. */",
				f"\t\tif (!situ_digits_minimal({at}, {name}_len(),"
				f" {placement.radix}u)) {{",
				"\t\t\treturn ::situ::rt::err::constraint;",
				"\t\t}",
			])

		if placement.radix is not None:
			scalar = placement.scalar
			assert scalar is not None
			lines.extend([
				f"\t\t{{",
				f"\t\t\t{self._ctype(scalar)} parsed;",
				f"\t\t\tif (const ::situ::rt::err e = {name}(parsed);"
				" e != ::situ::rt::err::ok) {",
				"\t\t\t\treturn e;",
				"\t\t\t}",
				"\t\t}",
			])
		return lines

	def _check(self, struct: ResolvedStruct, entry: Resolved) -> list[str]:
		"""Everything `validate` says about one member.

		The bounds question first, and it does not replace the rest: a member
		can be both outside the frame and constrained, and returning on the
		first left `[must_eq]` unchecked for every dynamically placed field.
		"""
		return [*self._fits_check(struct, entry.placement),
		        *self._arm_checks(struct, entry.placement),
		        *self._member_check(struct, entry)]

	def _arm_checks(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""Every arm of this variant, in declaration order.

		Asked at the variant rather than at the arm: `own_entries` drops a
		dotted path, and every arm member has one, so an arm never reaches
		the validate loop on its own.
		"""
		if placement.kind != "variant":
			return []
		found: list[str] = []
		for _, member in arm_members(struct, placement):
			if member is not None:
				found.extend(self._arm_fits_check(struct, member))
				found.extend(self._arm_validation(struct, member))
		return found

	def _arm_validation(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""Validate the arm the discriminant selects, through its own type.

		Nothing did, in any backend: a variant's check was the discriminant
		and nothing else, so every constraint inside an arm was declared by
		the schema and enforced by nobody. Through the arm's own accessor,
		which already refuses the arm that is not present.
		"""
		inner = self.resolved.structs.get(placement.type_name or "")
		if inner is None:
			return []
		if not inner.layout.is_fixed_size \
				and not has_computable_extent(self.resolved.structs, inner):
			return []

		# One of them, not a run of them. The arm accessor is emitted for an
		# arm that *is* a struct, and this named it for an arm that is a run
		# of one -- so `validate` called `body_run(arm)` for `vrec run[n]`,
		# which the arm emitter had declined a page earlier. A validator
		# naming what its own backend refused to emit is that refusal arriving
		# as a compile error.
		if not self._is_arm_struct(placement):
			return []

		name = c_name(local_name(struct, placement))
		return [
			f"\t\t/* {placement.path}: the arm the discriminant selects",
			"\t\t * carries its own constraints, and its own validator is",
			"\t\t * what knows them. */",
			"\t\t{",
			f"\t\t\t::situ::{class_name(inner)} arm;",
			"",
			f"\t\t\tif ({name}(arm) == ::situ::rt::err::ok) {{",
			"\t\t\t\tconst ::situ::rt::err inner = arm.validate();",
			"",
			"\t\t\t\tif (inner != ::situ::rt::err::ok) {",
			"\t\t\t\t\treturn inner;",
			"\t\t\t\t}",
			"\t\t\t}",
			"\t\t}",
		]

	def _is_arm_struct(self, placement: Placement) -> bool:
		"""Whether an arm is one struct rather than a run of them.

		The same question C asks before naming an arm's sub-view, and the same
		answer: a bracket after the type makes it a run, whichever way the
		count is written.
		"""
		return (placement.array_count is None
		        and placement.delimiter is None
		        and placement.repeat_while is None
		        and not data_sized(placement))

	def _arm_fits_check(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""The arm the discriminant selects has to fit the frame it is in.

		`_fits_check` skips a dotted path and every arm member has one, so a
		variant was outside the length checks entirely -- and a DNS label
		declaring 55 bytes in a five-byte frame is the same lie
		`u8 opts[hdr.length]` tells. The accessors clamp it (26.35); this is
		the other half, without which clamping turns a lie into a truncation.

		Through the accessor rather than by re-deriving the discriminant test:
		it refuses the arm that is not present and clamps the one that is, so
		a short answer is the mismatch.
		"""
		scalar = placement.scalar
		if placement.sized_by is None or scalar is None:
			return []
		if scalar.bits != BITS_PER_BYTE:
			return []
		declared = self._length_expression(struct, placement)
		if declared is None:
			return []

		name = c_name(local_name(struct, placement))
		return [
			f"\t\t/* {placement.path}: the arm the discriminant selects has",
			"\t\t * to fit the frame. The accessor clamps; this is where a",
			"\t\t * message that does not fit is called malformed. */",
			"\t\t{",
			"\t\t\t::situ::rt::bytes held;",
			"",
			f"\t\t\tif ({name}(held) == ::situ::rt::err::ok",
			f"\t\t\t\t\t&& held.size() < ({declared})) {{",
			"\t\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t\t}",
			"\t\t}",
		]

	def _member_check(self, struct: ResolvedStruct,
			entry: Resolved) -> list[str]:
		from situc.expr import evaluate

		placement = entry.placement
		scalar    = placement.scalar

		check = classify_check(struct, placement, self.structs)

		if check is Check.NOTHING:
			return []
		if check is Check.DISCRIMINANT:
			return self._discriminant_check(struct, placement)
		if check is Check.DELIMITED:
			return self._delimiter_check(struct, placement)
		if check is Check.REPEATED:
			assert scalar is not None
			return self._array_checks(struct, placement, scalar)
		if check is Check.NESTED:
			# Only where the accessor exists.
			inner = self.resolved.structs.get(placement.type_name or "")
			if inner is not None and not inner.layout.is_fixed_size \
					and not has_computable_extent(self.resolved.structs, inner):
				return [f"\t\t/* {placement.path}: no accessor to validate"
				        " through. */"]
			name  = c_name(local_name(struct, placement))
			held  = f"::{self.namespace}::{c_name(placement.type_name or '')}"
			# Two errors rather than one, because they are two things: the
			# frame does not contain the member, or the member is there and
			# malformed. The accessor refuses the first now (26.31), and
			# `validate` is where a caller who does validate hears about it.
			return [
				"\t\t{",
				f"\t\t\t{held} held;",
				f"\t\t\tif (const ::situ::rt::err e = {name}(held);"
				" e != ::situ::rt::err::ok) {",
				"\t\t\t\treturn e;",
				"\t\t\t}",
				"\t\t\tif (const ::situ::rt::err e = held.validate();"
				" e != ::situ::rt::err::ok) {",
				"\t\t\t\treturn e;",
				"\t\t\t}",
				"\t\t}",
			]

		assert scalar is not None
		lines: list[str] = []

		if check is Check.RESERVED:
			# At a dynamic offset there is no constant to load from, and
			# reaching for one crashed the compiler. For a whole-byte scalar
			# the byte loop says the same thing -- zero is zero in either
			# byte order -- so the two cases share one emitter.
			if placement.offset_bits is None:
				return self._reserved_checks(struct, placement)
			policy = _reserved_policy(placement.attrs)
			if policy in ("must_be_zero", "must_be_one"):
				want = "0" if policy == "must_be_zero" \
					else f"0x{(1 << scalar.bits) - 1:X}"
				lines.extend([
					f"\t\t/* reserved {placement.type_name} [{policy}] */",
					f"\t\tif ({self._raw_load(scalar, placement, f'base() + {placement.offset_bytes}')}"
					f" != {want}) {{",
					"\t\t\treturn ::situ::rt::err::constraint;",
					"\t\t}",
				])
			return lines

		name = c_name(local_name(struct, placement))

		enum = self.enums.get(placement.type_name or "")
		if enum is not None and enum.effective_default is ast.EnumDefault.ERROR:
			lines.extend([
				f"\t\t/* {placement.path}: `{enum.name}` rejects unknown values"
				f" (section 8.7) */",
				f"\t\tif (!is_known({name}())) {{",
				"\t\t\treturn ::situ::rt::err::constraint;",
				"\t\t}",
			])

		for attr in placement.attrs:
			if attr.name not in ("must_eq", "max", "min") or attr.value is None:
				continue
			expected = evaluate(attr.value, self.resolved.layout.env)
			operator = {"must_eq": "!=", "max": ">", "min": "<"}[attr.name]
			cast     = (f"static_cast<{self._ctype(scalar)}>({name}())"
			            if placement.type_name in self.enums else f"{name}()")
			lines.extend([
				f"\t\t/* {placement.path} [{attr.name} = {expected}] */",
				f"\t\tif ({cast} {operator} {expected}) {{",
				"\t\t\treturn ::situ::rt::err::constraint;",
				"\t\t}",
			])
		return lines

	def _reserved_checks(self, struct: ResolvedStruct,
			placement: Placement) -> list[str]:
		"""Reserved bytes hold their pattern, however many of them there are.

		A run the *message* sizes -- padding after a variable-length member --
		has no constant to loop to and no static offset to read from, and
		reaching for either crashed the compiler rather than diagnosing
		anything.
		"""
		policy  = _reserved_policy(placement.attrs)
		scalar  = placement.scalar
		if policy not in ("must_be_zero", "must_be_one") or scalar is None:
			return []
		if scalar.is_bit_packed or scalar.bits % BITS_PER_BYTE != 0:
			return []

		start = self._offset_expression(struct, placement)
		if start is None:
			return [f"\t\t/* {placement.path}: this backend cannot resolve"
			        " where the reserved bytes are. */"]

		width = scalar.bits // BITS_PER_BYTE
		if placement.array_count is not None:
			count: str | None = str(placement.array_count * width)
		elif data_sized(placement):
			count = self._length_expression(struct, placement)
			if count is None:
				return [f"\t\t/* {placement.path}: this backend cannot resolve"
				        " how many reserved bytes there are. */"]
		else:
			count = str(width)

		want = "0" if policy == "must_be_zero" else "0xFF"
		return [
			f"\t\t/* reserved {placement.type_name}"
			f"[{placement.array_count or placement.size_expr or width}]"
			f" [{policy}] */",
			"\t\t{",
			f"\t\t\tconst std::uint32_t at = {start};",
			f"\t\t\tconst std::uint32_t n  = {count};",
			"\t\t\tfor (std::uint32_t i = 0; i < n; i++) {",
			f"\t\t\t\tif (*(base() + at + i) != {want}) {{",
			"\t\t\t\t\treturn ::situ::rt::err::constraint;",
			"\t\t\t\t}",
			"\t\t\t}",
			"\t\t}",
		]

	def _array_checks(self, struct: ResolvedStruct, placement: Placement,
			scalar: ScalarType) -> list[str]:
		if scalar.bits != BITS_PER_BYTE:
			return []

		name  = c_name(local_name(struct, placement))
		count = placement.array_count or 0
		lines: list[str] = []

		if placement.kind == "reserved":
			return self._reserved_checks(struct, placement)

		for attr in placement.attrs:
			if attr.name == "encoding":
				named = getattr(attr.value, "name", None)
				if named in ("ascii", "utf8"):
					lines.extend([
						f"\t\t/* {placement.path} [encoding = {named}] */",
						f"\t\tif (!situ_{named}_valid({name}().data(),"
						f" {count})) {{",
						"\t\t\treturn ::situ::rt::err::constraint;",
						"\t\t}",
					])
			if attr.name == "nul_terminated":
				lines.extend([
					f"\t\t/* {placement.path} [nul_terminated] */",
					f"\t\tif (!situ_nul_terminated({name}().data(), {count})) {{",
					"\t\t\treturn ::situ::rt::err::constraint;",
					"\t\t}",
				])
		return lines

	# -- helpers -------------------------------------------------------

	def _axes_comment(self, entry: Resolved) -> list[str]:
		vector = entry.vector
		axes   = " ".join(f"{axis.value}={vector.get(axis).render()}"
		                  for axis in (Axis.SIZE, Axis.ALIGN, Axis.REPR,
		                               Axis.ATOMIC, Axis.MUTATE))
		return [f"\t/* {entry.placement.path} at"
		        f" {vector.get(Axis.OFFSET).render()}",
		        f"\t * {axes} */"]

	def _field_ctype(self, placement: Placement) -> str:
		"""The type an accessor uses, enums fully qualified.

		A field may share a name with its own enum -- IPv4's `protocol` field
		has type `protocol` -- and an unqualified use inside the class would
		change what that name means partway through it, which C++ rejects
		outright. Qualifying costs nothing and the hazard is not the author's
		to avoid (decision 0013).
		"""
		if placement.type_name in self.enums:
			return f"::{self.namespace}::{c_name(placement.type_name)}"
		scalar = placement.scalar
		assert scalar is not None
		return self._ctype(scalar)

	def _ctype(self, scalar: ScalarType) -> str:
		if scalar.kind is ScalarKind.FLOAT:
			return {16: "std::uint16_t", 32: "float", 64: "double"}[scalar.bits]
		width = _storage_width(scalar.bits)
		return f"std::int{width}_t" if scalar.signed else f"std::uint{width}_t"


def _storage_width(bits: int) -> int:
	for width in WORD_WIDTHS:
		if bits <= width:
			return width
	return 64


def _self_as(attrs: tuple[ast.Attr, ...]) -> int | None:
	"""What a self-covering tag's own bytes read as, or None (14.2)."""
	for attr in attrs:
		if attr.name == "self_as" and isinstance(attr.value, ast.IntLiteral):
			return int(attr.value.value)
	return None


def _order_suffix(endian: ast.Endian | None) -> str:
	if endian is ast.Endian.NATIVE:
		return "ne"
	return "le" if endian is ast.Endian.LITTLE else "be"


def _bit_assembly(endian: ast.Endian | None) -> str:
	"""The same choice for widths that are not a word: u24, u48."""
	if endian is ast.Endian.NATIVE:
		return "ne"
	return "lsb" if endian is ast.Endian.LITTLE else "msb"


def _reserved_policy(attrs: tuple[ast.Attr, ...]) -> str | None:
	for attr in attrs:
		if attr.name in ("must_be_zero", "must_be_one"):
			return str(attr.name)
		if attr.name in ("preserve", "unknown"):
			return None
	return "must_be_zero"

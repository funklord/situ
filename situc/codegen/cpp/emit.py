"""The C++ backend (section 26.16).

C++ is the second backend because it is the largest population after C, and
because parts of the capability lattice that C can only document it can
enforce. Three, specifically:

  * a byte array is a `situ::span`, so its length travels with its pointer
  * an error is `[[nodiscard]]`, so ignoring one is a diagnostic
  * a sealed region's view has no public constructor, so it cannot be made
    except by the function that verifies the tag -- in C the struct is there
    for anybody determined enough to fill in

What it deliberately does not do is reinvent anything. The layout, the
propagation table and the runtime arithmetic are the same ones the C backend
uses; this emits a different surface over identical bytes. A view is a value
for the same reason it is in C -- it owns nothing, so a destructor would be a
lie about what it is -- and errors are return codes rather than exceptions
because the target may have neither unwinding nor a heap.

Header-only. Every accessor is a constant offset from a base and inlines to
nothing, so there is no translation unit worth having; `validate` is the one
function with a body and it is `inline` too.
"""


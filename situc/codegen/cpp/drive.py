"""Retransmission in C++ (26.98).

I/O is an abstract interface rather than a struct of function pointers: the
caller implements `io` and passes a reference. That is C's vtable said in the
language that has one, and it keeps the same property -- the shipped path and
the tested path differ in what implements this and in nothing else.

Otherwise the C driver's shape, with the parameters typed so the two halves
of an exchange cannot be passed the wrong way round.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.c.names import c_name
from situc.codegen.cpp.names import class_name
from situc.relation import Read, KeyLayout, ReadBytes, Refused, Side, SubView, key_layout
from situc.resolve import ResolvedSchema
from situc import __version__

__all__ = ["generate"]


def _policy(relation: ast.Relation) -> tuple[int, int] | None:
	found: dict[str, int] = {}
	for attr in relation.attrs:
		value = getattr(attr.value, "value", None)
		if attr.name in ("timeout_ms", "retries") and isinstance(value, int):
			found[attr.name] = value
	return (found["timeout_ms"], found["retries"]) if len(found) == 2 else None


def _key(sides: Side, view: str, resolved: ResolvedSchema) -> list[str]:
	lines = ["\t\tstd::uint64_t key = 0u;"]
	for chain, width in sides:
		source = view
		for step in chain:
			if isinstance(step, Read):
				lines.append(f"\t\tkey = (key << {width}u) | "
				             f"static_cast<std::uint64_t>("
				             f"{source}.{c_name(step.member)}());")
			elif isinstance(step, SubView):
				held  = class_name(resolved.structs[step.into])
				local = f"held_{c_name(step.member)}"
				lines += [
					f"\t\t::situ::{held} {local};",
					f"\t\tif ({source}.{c_name(step.member)}({local}) != "
					"::situ::rt::err::ok) {",
					"\t\t\treturn ::situ::rt::err::bounds;",
					"\t\t}",
				]
				source = local
	return lines


def _key_bytes(sides: Side, view: str, resolved: ResolvedSchema,
		total: int) -> list[str]:
	"""The exact-bytes key (0042); see the converse twin for the layout."""
	lines = [f"\t\tstd::uint8_t key[{total}u];",
	         "\t\tstd::uint32_t at = 0u;"]
	for chain, width in sides:
		source = view
		for step in chain:
			if isinstance(step, ReadBytes):
				count = width // 8
				lines += [
					f"\t\tconst ::situ::rt::const_bytes b_{step.target} = "
					f"{source}.{c_name(step.member)}();",
					f"\t\tfor (std::uint32_t b = 0u; b < {count}u; b++) {{",
					f"\t\t\tkey[at + b] = b_{step.target}[b];",
					"\t\t}",
					f"\t\tat += {count}u;",
				]
			elif isinstance(step, Read):
				count = (width + 7) // 8
				lines += [
					f"\t\tconst std::uint64_t v_{step.target} = "
					f"static_cast<std::uint64_t>("
					f"{source}.{c_name(step.member)}());",
					f"\t\tfor (std::uint32_t b = 0u; b < {count}u; b++) {{",
					f"\t\t\tkey[at + b] = static_cast<std::uint8_t>("
					f"v_{step.target} >> (8u * ({count}u - 1u - b)));",
					"\t\t}",
					f"\t\tat += {count}u;",
				]
			elif isinstance(step, SubView):
				held  = class_name(resolved.structs[step.into])
				local = f"held_{c_name(step.member)}"
				lines += [
					f"\t\t::situ::{held} {local};",
					f"\t\tif ({source}.{c_name(step.member)}({local}) != "
					"::situ::rt::err::ok) {",
					"\t\t\treturn ::situ::rt::err::bounds;",
					"\t\t}",
				]
				source = local
	lines.append("\t\t(void)at;")
	return lines


def _key_equal(total: int) -> str:
	return (f"[&]() {{ for (std::uint32_t b = 0u; b < {total}u; b++) "
	        "{ if (slots_[i].key[b] != key[b]) return false; } "
	        "return true; }()")


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str) -> dict[str, str]:
	ready = []
	for relation in schema.relations():
		policy = _policy(relation)
		if policy is None:
			continue
		try:
			ready.append((relation, policy, key_layout(relation, resolved)))
		except Refused:
			continue
	if not ready:
		return {}

	guard = f"SITU_{c_name(basename).upper()}_DRIVE_HPP"
	lines = [
		f"/* Generated by situc {__version__} from {basename}.situ -- do not edit.",
		" *",
		" * Retransmission and timeout. Owns I/O through an interface you",
		" * implement and never owns the clock. Nothing allocates.",
		" */",
		"",
		f"#ifndef {guard}",
		f"#define {guard}",
		"",
		"#include <cstdint>",
		"",
		f"#include \"{basename}.hpp\"",
		"",
		"namespace situ {",
		"",
		"/** Where the bytes go. Yours, so a test substitutes a transcript",
		" * and never opens a socket. */",
		"class io {",
		"public:",
		"\tvirtual ~io() = default;",
		"\t[[nodiscard]] virtual ::situ::rt::err submit(",
		"\t\tconst std::uint8_t *data, std::uint32_t len) noexcept = 0;",
		"\t/** A retransmission, told which exchange it is, so a caller that",
		"\t * seals each send can reseal it (26.1036). The same bytes again",
		"\t * unless overridden. */",
		"\t[[nodiscard]] virtual ::situ::rt::err resend(std::uint32_t id,",
		"\t\tconst std::uint8_t *data, std::uint32_t len) noexcept",
		"\t{",
		"\t\t(void)id;",
		"\t\treturn submit(data, len);",
		"\t}",
		"\t/** Told each exchange that expires, by id, as `step` drops it",
		"\t * (fuzznet, 26.1055). Nothing unless overridden. */",
		"\tvirtual void expired(std::uint32_t id) noexcept",
		"\t{",
		"\t\t(void)id;",
		"\t}",
		"};",
		"",
	]

	from situc.codegen.c.drive import part_of, resend_of

	for relation, (timeout, retries), layout in ready:
		request, response = layout.request, layout.response
		resend = resend_of(relation)
		part   = part_of(relation) if resend else None
		name = f"{c_name(relation.name)}_driver"
		first, second = relation.params
		req  = class_name(resolved.structs[first.type_name])
		resp = class_name(resolved.structs[second.type_name])
		lines += [
			f"#define SITU_{c_name(relation.name).upper()}_TIMEOUT_MS {timeout}u",
			f"#define SITU_{c_name(relation.name).upper()}_RETRIES {retries}u",
			*([f"#define SITU_{c_name(relation.name).upper()}_RESEND_MS {resend}u",
			   "/* TIMEOUT_MS is the whole exchange's wait with a resend",
			   " * interval: C's (26.1039). */"] if resend else []),
			*([f"#define SITU_{c_name(relation.name).upper()}_RESEND_PART_MS"
			   f" {part[0]}u",
			   f"#define SITU_{c_name(relation.name).upper()}_RETRIES_PART"
			   f" {part[1]}u",
			   "/* Once `part_held` says part of the reply is in: C's. */"]
			  if part else []),
			"",
			f"/** Retransmission for `{relation.name}`. */",
			f"class {name} {{",
			"public:",
			"\tstruct slot {",
			"\t\tconst std::uint8_t *bytes;",
			"\t\tstd::uint32_t len;",
			("\t\tstd::uint64_t key;" if layout.packed
			 else f"\t\tstd::uint8_t  key[{layout.total_bytes}u];"),
			"\t\tstd::uint32_t id;",
			"\t\tstd::uint32_t deadline_ms;",
			"\t\tstd::uint32_t left;",
			"\t\tbool          live;",
			"\t\tbool          keyed;\t/* false for `track_by_id` */",
			*(["\t\tstd::uint32_t end_ms;\t/* the whole exchange's end */"]
			  if resend else []),
			*(["\t\tstd::uint32_t sent_ms;\t/* the last send */",
			   "\t\tbool          part;\t/* part of the reply is held */"]
			  if part else []),
			"\t\tstd::uint32_t retries;\t/* this exchange's own */",
			*(["\t\tstd::uint32_t resend_ms;"] if resend else []),
			*(["\t\tstd::uint32_t resend_part_ms;",
			   "\t\tstd::uint32_t retries_part;"] if part else []),
			"\t};",
			"",
			"\t/** One exchange's own numbers where they are not the",
			"\t *  relation's; nullptr takes the driver's (26.1055). */",
			"\tstruct policy {",
			"\t\tstd::uint32_t timeout_ms;",
			"\t\tstd::uint32_t retries;",
			*(["\t\tstd::uint32_t resend_ms;"] if resend else []),
			*(["\t\tstd::uint32_t resend_part_ms;",
			   "\t\tstd::uint32_t retries_part;"] if part else []),
			"\t};",
			"",
			# `store`, not `slots`: Qt defines `slots` as an empty macro, so a
			# parameter of that name vanishes in any translation unit that has
			# included a Qt header -- `slots_(slots)` becomes `slots_()`, a
			# null the constructor then writes through, and it compiles clean
			# under -Wall -Wextra. Measured: a segfault at construction. The
			# member keeps its trailing underscore and is unaffected.
			f"\t{name}(slot *store, std::uint32_t cap, ::situ::io &sink,",
			("\t       std::uint32_t timeout_ms, std::uint32_t retries,"
			 "\n\t       std::uint32_t resend_ms, std::uint32_t resend_part_ms,"
			 "\n\t       std::uint32_t retries_part) noexcept"
			 if part else
			 "\t       std::uint32_t timeout_ms, std::uint32_t retries,"
			 "\n\t       std::uint32_t resend_ms) noexcept"
			 if resend else
			 "\t       std::uint32_t timeout_ms, std::uint32_t retries) noexcept"),
			"\t\t: slots_(store), cap_(cap), io_(sink),",
			("\t\t  timeout_ms_(timeout_ms), retries_(retries),"
			 " resend_ms_(resend_ms),\n\t\t  resend_part_ms_(resend_part_ms),"
			 " retries_part_(retries_part)" if part else
			 "\t\t  timeout_ms_(timeout_ms), retries_(retries),"
			 " resend_ms_(resend_ms)" if resend else
			 "\t\t  timeout_ms_(timeout_ms), retries_(retries)"),
			"\t{",
			"\t\tfor (std::uint32_t i = 0u; i < cap_; i++) {",
			"\t\t\tslots_[i].live = false;",
			"\t\t}",
			"\t}",
			"",
			"\t/** The slot an exchange takes, filled but for its key: `cap_`",
			"\t *  where none is free. */",
			"\tstd::uint32_t hold(const std::uint8_t *bytes, std::uint32_t len,",
			"\t                   std::uint32_t id, std::uint32_t now_ms,",
			"\t                   const policy *own) noexcept",
			"\t{",
			"\t\tconst std::uint32_t timeout_ms = own != nullptr"
			" ? own->timeout_ms : timeout_ms_;",
			"\t\tconst std::uint32_t retries    = own != nullptr"
			" ? own->retries : retries_;",
			*(["\t\tconst std::uint32_t resend_ms  = own != nullptr"
			   " ? own->resend_ms : resend_ms_;"] if resend else []),
			"",
			"\t\tfor (std::uint32_t i = 0u; i < cap_; i++) {",
			"\t\t\tif (!slots_[i].live) {",
			"\t\t\t\tslots_[i].bytes = bytes;",
			"\t\t\t\tslots_[i].len   = len;",
			"\t\t\t\tslots_[i].id          = id;",
			"\t\t\t\tslots_[i].deadline_ms = now_ms + timeout_ms;",
			"\t\t\t\tslots_[i].left        = retries;",
			"\t\t\t\tslots_[i].retries     = retries;",
			"\t\t\t\tslots_[i].live        = true;",
			*(["\t\t\t\tslots_[i].resend_ms   = resend_ms;",
			   "\t\t\t\tslots_[i].end_ms      = now_ms + timeout_ms;",
			   "\t\t\t\tslots_[i].deadline_ms = retries == 0u ? slots_[i].end_ms",
			   "\t\t\t\t\t: sooner(now_ms + resend_ms, slots_[i].end_ms, now_ms);"]
			  if resend else []),
			*(["\t\t\t\tslots_[i].sent_ms     = now_ms;",
			   "\t\t\t\tslots_[i].part        = false;",
			   "\t\t\t\tslots_[i].resend_part_ms = own != nullptr"
			   " ? own->resend_part_ms : resend_part_ms_;",
			   "\t\t\t\tslots_[i].retries_part   = own != nullptr"
			   " ? own->retries_part : retries_part_;"] if part else []),
			"\t\t\t\treturn i;",
			"\t\t\t}",
			"\t\t}",
			"\t\treturn cap_;",
			"\t}",
			"",
			"\t/** Remember a request until it is answered, without sending it:",
			"\t *  one the caller sent already, or only awaits (26.1055). The",
			"\t *  bytes are the caller's and must not move until it ends. */",
			f"\t[[nodiscard]] ::situ::rt::err track(const ::situ::{req} "
			f"&{first.name},",
			"\t                                    const std::uint8_t *bytes,",
			"\t                                    std::uint32_t len,",
			"\t                                    std::uint32_t id,",
			"\t                                    std::uint32_t now_ms,",
			"\t                                    const policy *own = nullptr)"
			" noexcept",
			"\t{",
			*(_key(request, first.name, resolved) if layout.packed else
			  _key_bytes(request, first.name, resolved, layout.total_bytes)),
			"\t\tconst std::uint32_t i = hold(bytes, len, id, now_ms, own);",
			"\t\tif (i == cap_) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			*(["\t\tslots_[i].key   = key;"] if layout.packed else [
			  f"\t\tfor (std::uint32_t b = 0u; b < {layout.total_bytes}u; b++) {{",
			  "\t\t\tslots_[i].key[b] = key[b];",
			  "\t\t}"]),
			"\t\tslots_[i].keyed = true;",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
			"",
			"\t/** `track` for a caller that matches replies itself -- after",
			"\t *  opening them, where the key is inside sealed bytes -- so no",
			"\t *  request is read and no key is held: the exchange is its id",
			"\t *  alone, ended by `end` or by expiring (26.1064). */",
			"\t[[nodiscard]] ::situ::rt::err track_by_id(const std::uint8_t *bytes,",
			"\t                                          std::uint32_t len,",
			"\t                                          std::uint32_t id,",
			"\t                                          std::uint32_t now_ms,",
			"\t                                          const policy *own = nullptr)"
			" noexcept",
			"\t{",
			"\t\tconst std::uint32_t i = hold(bytes, len, id, now_ms, own);",
			"\t\tif (i == cap_) {",
			"\t\t\treturn ::situ::rt::err::bounds;",
			"\t\t}",
			"\t\tslots_[i].keyed = false;",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
			"",
			"\t/** `track`, then the first send -- through `io::resend`, told",
			"\t *  the id, so a caller sealing every send under it seals this",
			"\t *  one too (26.1055); unless overridden that is `submit`. */",
			f"\t[[nodiscard]] ::situ::rt::err send(const ::situ::{req} "
			f"&{first.name},",
			"\t                                   const std::uint8_t *bytes,",
			"\t                                   std::uint32_t len,",
			"\t                                   std::uint32_t id,",
			"\t                                   std::uint32_t now_ms,",
			"\t                                   const policy *own = nullptr)"
			" noexcept",
			"\t{",
			f"\t\tconst ::situ::rt::err e = track({first.name}, bytes, len, id,"
			" now_ms, own);",
			"\t\tif (e != ::situ::rt::err::ok) {",
			"\t\t\treturn e;",
			"\t\t}",
			"\t\treturn io_.resend(id, bytes, len);",
			"\t}",
			"",
			"\t/** End exchange `id` without a reply to match (26.1055).",
			"\t *  `err::constraint` where none is pending. */",
			"\t[[nodiscard]] ::situ::rt::err end(std::uint32_t id) noexcept",
			"\t{",
			"\t\tfor (std::uint32_t i = 0u; i < cap_; i++) {",
			"\t\t\tif (slots_[i].live && slots_[i].id == id) {",
			"\t\t\t\tslots_[i].live = false;",
			"\t\t\t\treturn ::situ::rt::err::ok;",
			"\t\t\t}",
			"\t\t}",
			"\t\treturn ::situ::rt::err::constraint;",
			"\t}",
			"",
			f"\t[[nodiscard]] ::situ::rt::err on_message(const ::situ::{resp} "
			f"&{second.name},",
			"\t                                         std::uint32_t &id) noexcept",
			"\t{",
			*(_key(response, second.name, resolved) if layout.packed else
			  _key_bytes(response, second.name, resolved, layout.total_bytes)),
			"",
			"\t\tfor (std::uint32_t i = 0u; i < cap_; i++) {",
			("\t\t\tif (slots_[i].live && slots_[i].keyed && slots_[i].key == key) {"
			 if layout.packed else
			 f"\t\t\tif (slots_[i].live && slots_[i].keyed"
			 f" && {_key_equal(layout.total_bytes)}) {{"),
			"\t\t\t\tid = slots_[i].id;",
			"\t\t\t\tslots_[i].live = false;",
			"\t\t\t\treturn ::situ::rt::err::ok;",
			"\t\t\t}",
			"\t\t}",
			"\t\treturn ::situ::rt::err::constraint;",
			"\t}",
			"",
			"\t/** `on_message` without ending the exchange: which request a",
			"\t *  reply answers, for a reply in pieces (26.1009). */",
			f"\t[[nodiscard]] ::situ::rt::err peek(const ::situ::{resp} "
			f"&{second.name},",
			"\t                                   std::uint32_t &id) const noexcept",
			"\t{",
			*(_key(response, second.name, resolved) if layout.packed else
			  _key_bytes(response, second.name, resolved, layout.total_bytes)),
			"",
			"\t\tfor (std::uint32_t i = 0u; i < cap_; i++) {",
			("\t\t\tif (slots_[i].live && slots_[i].keyed && slots_[i].key == key) {"
			 if layout.packed else
			 f"\t\t\tif (slots_[i].live && slots_[i].keyed"
			 f" && {_key_equal(layout.total_bytes)}) {{"),
			"\t\t\t\tid = slots_[i].id;",
			"\t\t\t\treturn ::situ::rt::err::ok;",
			"\t\t\t}",
			"\t\t}",
			"\t\treturn ::situ::rt::err::constraint;",
			"\t}",
			"",
			*_part_held(part),
			"\t/** Retransmit what is due; `next_ms` is when to come back.",
			"\t * `err::truncated` where nothing is outstanding. */",
			"\t[[nodiscard]] ::situ::rt::err step(std::uint32_t now_ms,",
			"\t                                   std::uint32_t &next_ms,",
			"\t                                   std::uint32_t &expired) noexcept",
			"\t{",
			"\t\tstd::uint32_t soonest = 0u;",
			"\t\tbool any = false;",
			"",
			"\t\texpired = 0u;",
			"\t\tfor (std::uint32_t i = 0u; i < cap_; i++) {",
			"\t\t\tif (!slots_[i].live) {",
			"\t\t\t\tcontinue;",
			"\t\t\t}",
			# Serially, modulo 2^32: C's (26.1008).
			"\t\t\tif (static_cast<std::uint32_t>(now_ms - slots_[i].deadline_ms)"
			" < 0x80000000u) {",
			("\t\t\t\tif (slots_[i].left == 0u || static_cast<std::uint32_t>("
			 "now_ms - slots_[i].end_ms) < 0x80000000u) {" if resend else
			 "\t\t\t\tif (slots_[i].left == 0u) {"),
			"\t\t\t\t\tslots_[i].live = false;",
			"\t\t\t\t\tio_.expired(slots_[i].id);",
			"\t\t\t\t\texpired += 1u;",
			"\t\t\t\t\tcontinue;",
			"\t\t\t\t}",
			"\t\t\t\tslots_[i].left -= 1u;",
			*(["\t\t\t\tslots_[i].sent_ms = now_ms;",
			   "\t\t\t\tslots_[i].deadline_ms = slots_[i].left == 0u"
			   " ? slots_[i].end_ms",
			   "\t\t\t\t\t: sooner(now_ms + (slots_[i].part"
			   " ? slots_[i].resend_part_ms : slots_[i].resend_ms),",
			   "\t\t\t\t\t         slots_[i].end_ms, now_ms);"]
			  if part else
			  ["\t\t\t\tslots_[i].deadline_ms = slots_[i].left == 0u"
			   " ? slots_[i].end_ms",
			   "\t\t\t\t\t: sooner(now_ms + slots_[i].resend_ms, slots_[i].end_ms,"
			   " now_ms);"]
			  if resend else
			  ["\t\t\t\tslots_[i].deadline_ms = now_ms + timeout_ms_;"]),
			"\t\t\t\t(void)io_.resend(slots_[i].id, slots_[i].bytes,"
			" slots_[i].len);",
			"\t\t\t}",
			"\t\t\tif (!any || static_cast<std::uint32_t>(slots_[i].deadline_ms"
			" - now_ms) < static_cast<std::uint32_t>(soonest - now_ms)) {",
			"\t\t\t\tsoonest = slots_[i].deadline_ms;",
			"\t\t\t\tany = true;",
			"\t\t\t}",
			"\t\t}",
			"",
			"\t\tif (!any) {",
			"\t\t\treturn ::situ::rt::err::truncated;",
			"\t\t}",
			"\t\tnext_ms = soonest;",
			"\t\treturn ::situ::rt::err::ok;",
			"\t}",
			"",
			"private:",
			"\tslot          *slots_;",
			"\tstd::uint32_t  cap_;",
			"\t::situ::io    &io_;",
			"\tstd::uint32_t  timeout_ms_;",
			"\tstd::uint32_t  retries_;",
			*(["\tstd::uint32_t  resend_ms_;",
			   *(["\tstd::uint32_t  resend_part_ms_;",
			      "\tstd::uint32_t  retries_part_;"] if part else []),
			   "",
			   "\t/* The sooner of two deadlines, serially from `now_ms`. */",
			   "\tstatic std::uint32_t sooner(std::uint32_t a, std::uint32_t b,",
			   "\t                            std::uint32_t now_ms) noexcept",
			   "\t{",
			   "\t\treturn static_cast<std::uint32_t>(a - now_ms)"
			   " < static_cast<std::uint32_t>(b - now_ms) ? a : b;",
			   "\t}"] if resend else []),
			"};",
			"",
		]

	lines += ["}  /* namespace situ */", "", f"#endif /* {guard} */"]
	return {f"{basename}_drive.hpp": "\n".join(lines) + "\n"}



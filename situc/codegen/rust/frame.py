"""Stream framing in Rust (26.96).

The rung where Rust's shape differs most, and not in spelling. `required`
answers a `Framing` enum -- `Complete(n)` or `Need(n)` -- rather than an
error code with an out-parameter, so there is no error to propagate and two
variants to match. A reader translated from the C one would have invented a
failure that does not exist here.

The borrow checker also does the lifetime comment C has to write. `next`
borrows the reader for as long as the view lives, so `advance` cannot be
called while a message is outstanding -- the mistake the C header warns about
in capitals does not compile here. That is the same trade section 26 records
for invalidation generally.
"""

from __future__ import annotations

from situc import ast
from situc.codegen.c.frame import framed_structs
from situc.codegen.rust.emit import _pascal
from situc.resolve import ResolvedSchema
from situc import __version__

__all__ = ["generate"]


def generate(schema: ast.Schema, resolved: ResolvedSchema,
		basename: str) -> dict[str, str]:
	structs = framed_structs(resolved)
	if not structs:
		return {}

	lines = [
		f"// Generated by situc {__version__} from {basename}.situ -- do not edit.",
		"//",
		"// Stream framing: a byte stream in, whole messages out. The buffer",
		"// is the caller's and nothing here allocates. A separate module --",
		"// a rung adds files rather than changing them (decision 0032).",
		"",
		f"use crate::{basename}::*;",
		"use crate::situ_rt::{self, Error, Framing, Result};",
		"",
	]

	for struct in structs:
		held = _pascal(struct.name)
		name = f"{held}Reader"
		lines += [
			f"/// A stream reader for `{struct.name}`.",
			"///",
			"/// Push bytes as they arrive and call `next` until it answers",
			"/// `Error::Truncated`. There is no `advance`: `next` borrows the",
			"/// reader for as long as the message lives, so dropping one",
			"/// early does not compile rather than being warned about.",
			f"pub struct {name}<'a> {{",
			"\tbuf: &'a mut [u8],",
			"\thave: usize,",
			"}",
			"",
			f"impl<'a> {name}<'a> {{",
			"\tpub fn new(buf: &'a mut [u8]) -> Self {",
			"\t\tSelf { buf, have: 0 }",
			"\t}",
			"",
			"\t/// Append what arrived. `Error::Bounds` where it does not fit,",
			"\t/// which says the buffer is smaller than the message being",
			"\t/// assembled -- a capacity question, not a malformed one.",
			"\tpub fn push(&mut self, data: &[u8]) -> Result<()> {",
			"\t\tif data.len() > self.buf.len() - self.have {",
			"\t\t\treturn Err(Error::Bounds);",
			"\t\t}",
			"\t\tself.buf[self.have..self.have + data.len()].copy_from_slice(data);",
			"\t\tself.have += data.len();",
			"\t\tOk(())",
			"\t}",
			"",
			"\t/// How long the next whole message is, or `Error::Truncated`.",
			"\t///",
			"\t/// `Error::Bounds` where a whole one needs more than this",
			"\t/// buffer can ever hold: waiting never makes that true.",
			"\tpub fn ready(&self) -> Result<usize> {",
			f"\t\tmatch {held}::required(&self.buf[..self.have]) {{",
			"\t\t\tFraming::Complete(n) => Ok(n),",
			"\t\t\tFraming::Need(n) if n > self.buf.len() => Err(Error::Bounds),",
			"\t\t\tFraming::Need(_) => Err(Error::Truncated),",
			"\t\t}",
			"\t}",
			"",
			"\t/// The next whole message. Borrows until it is dropped.",
			f"\tpub fn next(&self) -> Result<{held}<'_>> {{",
			"\t\tlet n = self.ready()?;",
			f"\t\t{held}::new(&self.buf[..n])",
			"\t}",
			"",
			"\t/// Drop the message `next` returned, which the borrow checker",
			"\t/// has already proved is no longer outstanding.",
			"\tpub fn advance(&mut self) -> Result<()> {",
			"\t\tlet n = self.ready()?;",
			"\t\tself.buf.copy_within(n..self.have, 0);",
			"\t\tself.have -= n;",
			"\t\tOk(())",
			"\t}",
			"}",
			"",
		]

	# `situ_rt` is named in the use line for the runtime's own path; a module
	# that reaches none of its free functions would otherwise warn under
	# `-D warnings`, which is what the suite builds with.
	lines.insert(7, "#[allow(unused_imports)]")

	return {f"{basename}_frame.rs": "\n".join(lines).rstrip("\n") + "\n"}

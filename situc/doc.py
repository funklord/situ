def _table(struct: ResolvedStruct, fmt: str) -> list[str]:
	"""What the diagram cannot say: types, constraints and byte order."""
	rows = [_row(struct, entry.placement) for entry in struct.entries
	        if entry.placement.kind != "element"
	        and "." not in entry.placement.path[len(struct.name) + 1:]]
	if not rows:
		return []

	headers = ("Field", "Offset", "Size", "Type", "Notes")
	if fmt == "markdown":
		lines = ["| " + " | ".join(headers) + " |",
		         "|" + "|".join(["---"] * len(headers)) + "|"]
		lines.extend("| " + " | ".join(row) + " |" for row in rows)
		return lines

	widths = [max(len(headers[i]), max(len(row[i]) for row in rows))
	          for i in range(len(headers))]
	lines  = ["  ".join(headers[i].ljust(widths[i]) for i in range(len(headers))),
	          "  ".join("-" * widths[i] for i in range(len(headers)))]
	lines.extend("  ".join(row[i].ljust(widths[i]) for i in range(len(headers))).rstrip()
	             for row in rows)
	return [line.rstrip() for line in lines]


def _row(struct: ResolvedStruct, placement: Placement) -> tuple[str, ...]:
	return (
		_label(struct, placement),
		_offset(placement),
		_size(placement),
		placement.type_name or "-",
		"; ".join(_notes(placement)) or "",
	)


def _offset(placement: Placement) -> str:
	if placement.offset_bits is None:
		return "dynamic"
	if placement.offset_bits % BITS_PER_BYTE == 0:
		return str(placement.offset_bits // BITS_PER_BYTE)
	return f"{placement.offset_bits // BITS_PER_BYTE}.{placement.offset_bits % BITS_PER_BYTE}"


def _stride(placement: Placement) -> str:
	"""How wide one element is, where a count alone would not say.

	Nothing for a byte element, where the count *is* the byte count, and for
	an element of a struct type, whose name the Type column carries.
	"""
	if not indexed_elements(placement):
		return ""
	return f" x {element_bytes(placement)} bytes"


def _size(placement: Placement) -> str:
	if placement.delimiter is not None:
		# What a reader needs is where it stops, not how many bytes the
		# delimiter takes -- which is what the fixed-size branch below
		# reported, and it is the one number nobody wants.
		shown = render_delimiter(placement.delimiter).strip("`")
		if placement.delimiter_cap is not None:
			return f"to {shown}, max {placement.delimiter_cap}"
		return f"to {shown}"
	# The count is in elements, and this column is otherwise in bytes: a
	# constant array two rows down says "8 bytes" for four `u16`s. So `[n]`
	# beside a `u16` read as n bytes, and half the array was invisible to
	# somebody sizing a buffer from the table. The two coincide for a byte
	# element, which is every data-sized array anybody had written.
	if placement.sized_by is not None:
		return f"[{placement.sized_by}]{_stride(placement)}"
	if placement.size_expr is not None and placement.array_count is None:
		# The same question `sized_by` answers, for a length written as
		# arithmetic rather than as a bare field reference. Without it this
		# fell to the fixed-size branch below and printed the *minimum* --
		# "0 bytes" for a payload that is `nla_len - 4`, beside a diagram
		# saying "(variable)". Three constructs above have their own comment
		# recording this same mistake; the fourth is here because the
		# predicate was `sized_by` rather than `traverse.data_sized`.
		return f"[{placement.size_expr}]{_stride(placement)}"
	if placement.kind == "variant" and placement.discriminant is not None:
		# The fixed-size branch below reported `size_bits`, which for a
		# variant is the *smallest* arm -- printed as "0 bytes" beside a
		# diagram saying "(variable)", in a column where every other variable
		# member says how its length is decided. A true number answering a
		# question nobody asked, which is the `array_count` lesson again.
		return f"by {placement.discriminant}"
	if placement.repeat_while is not None:
		return f"while {placement.repeat_while}"
	if placement.size_bits % BITS_PER_BYTE:
		bits = placement.size_bits
		return f"{bits} bit" if bits == 1 else f"{bits} bits"
	return _bytes(placement.size_bits // BITS_PER_BYTE)


#: Attributes this module says in words rather than passing through.
RENDERED_IN_PROSE = ("since",)


def _notes(placement: Placement) -> list[str]:
	notes = []
	scalar = placement.scalar
	if scalar is not None and scalar.is_fixed_point:
		notes.append(f"fixed point, /{scalar.scale}")
	if scalar is not None and scalar.is_bcd:
		notes.append(f"{scalar.digits} packed digits, 0 to {scalar.decimal_max}")
	# Byte order is a property of a multi-byte *number*, and the test was the
	# member's total width -- so a two-byte marker, a four-byte address and a
	# 110-byte nested struct all carried it. `bmp.signature` is the sharpest
	# case: its own comment says it is bytes rather than a `u16` so that its
	# value does not depend on byte order, and the document said it did.
	#
	# The element's width is the question, which also keeps the note where it
	# belongs on `u16 samples[4]`. A number written as digits has no byte
	# order at all: the bytes are characters, and `repr = TextConverted` is
	# the axis saying so.
	if placement.marker is not None and placement.kind != "marker" \
			and scalar is not None and scalar.bits > BITS_PER_BYTE:
		# A field whose byte order the *message* decides. The column said
		# nothing, which reads as host order beside every neighbour that names
		# one -- and the fact a reader most needs about such a field is which
		# other field to read first.
		notes.append(f"byte order from {placement.marker}")
	elif placement.endian is not None and placement.radix is None \
			and scalar is not None and not scalar.is_bit_packed \
			and scalar.bits > BITS_PER_BYTE:
		notes.append(f"{placement.endian.value} endian")
	for attr in placement.attrs:
		# Skip the ones rendered in prose above. `since = 2` and "from version
		# 2" in one row is the same fact twice, and a reader who sees a
		# document repeat itself starts skimming it.
		if attr.name in RENDERED_IN_PROSE:
			continue
		notes.append(attr.name if attr.value is None
		             else f"{attr.name} = {_attr_value(attr)}")
	if placement.covered_by:
		notes.append("covered by " + ", ".join(placement.covered_by))
	if placement.radix is not None:
		base = {10: "decimal", 16: "hexadecimal"}.get(placement.radix,
		                                             f"base {placement.radix}")
		notes.append(f"{base} digits")
	if placement.since is not None:
		notes.append(f"from version {placement.since}")
	if placement.derived_by is not None:
		# The half of section 16.1 a reader of this table most needs. The
		# fields an invariant *reads* already showed up here, through
		# `covered_by`, so the dependency was documented from one end only --
		# and the end that was missing is the one somebody writing an encoder
		# from this table has to know about, because it says the value is not
		# theirs to choose.
		notes.append(f"derived: {placement.derived_by} computes it")
	if placement.sealed_by is not None:
		notes.append(f"sealed by {placement.sealed_by}")
	return notes


def _attr_value(attr: ast.Attr) -> str:
	"""The attribute's value as a user wrote it.

	Through the unparser rather than `str()`: an expression node is a dataclass
	holding its own span, and its span holds the whole source file, so the
	default repr renders the entire schema into one table cell.
	"""
	if attr.raw is not None:
		return str(attr.raw)
	return "" if attr.value is None else expr_to_source(attr.value)

"""`bin/situc` -- the command, as opposed to the module.

Section 24 requires situc to run from a bare interpreter with nothing
installed. That rules out a console entry point generated by an installer, so
the launcher finds its own package, and these check the three ways it has to
work: from the tree, through a symlink, and from an installed prefix where the
source tree is not present at all.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT     = Path(__file__).resolve().parent.parent.parent
LAUNCHER = ROOT / "bin" / "situc"
SCHEMA   = ROOT / "examples" / "icmp" / "icmp.situ"


def run(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
	# An empty PYTHONPATH, so a pass is the launcher's own doing rather than an
	# inherited path that happens to contain the tree.
	env = dict(os.environ, PYTHONPATH="")
	return subprocess.run(command, cwd=cwd, env=env, capture_output=True,
	                      text=True, check=False)


def test_the_launcher_is_executable() -> None:
	assert LAUNCHER.is_file(), "bin/situc is missing"
	assert os.access(LAUNCHER, os.X_OK), "bin/situc is not executable"


def test_it_runs_from_the_tree(tmp_path: Path) -> None:
	result = run([str(LAUNCHER), "map", str(SCHEMA)], cwd=tmp_path)

	assert result.returncode == 0, result.stderr
	assert "situ capability map" in result.stdout


def test_it_runs_through_a_symlink(tmp_path: Path) -> None:
	"""The usual way it reaches a PATH directory, and the one that breaks if
	the launcher looks at __file__ without resolving it."""
	link = tmp_path / "situc"
	link.symlink_to(LAUNCHER)

	result = run([str(link), "map", str(SCHEMA)], cwd=tmp_path)

	assert result.returncode == 0, result.stderr
	assert "situ capability map" in result.stdout


def test_it_runs_from_an_installed_prefix(tmp_path: Path) -> None:
	"""The layout `make install` produces, with no source tree in sight."""
	prefix = tmp_path / "prefix"
	(prefix / "bin").mkdir(parents=True)
	(prefix / "lib").mkdir(parents=True)

	shutil.copy2(LAUNCHER, prefix / "bin" / "situc")
	shutil.copytree(ROOT / "situc", prefix / "lib" / "situc",
	                ignore=shutil.ignore_patterns("__pycache__"))
	# `make install` puts VERSION beside the module, and situc.__version__
	# reads it there. Without this the fixture is not the layout it claims
	# to be, and the launcher fails on import for a reason the real install
	# does not have.
	shutil.copy2(ROOT / "VERSION", prefix / "lib" / "situc" / "VERSION")

	schema = tmp_path / "copy.situ"
	schema.write_text(SCHEMA.read_text(encoding="ascii"), encoding="ascii")

	result = run([str(prefix / "bin" / "situc"), "map", str(schema)], cwd=tmp_path)

	assert result.returncode == 0, result.stderr
	assert "situ capability map" in result.stdout


def test_it_says_so_when_the_package_is_missing(tmp_path: Path) -> None:
	"""A launcher on its own must explain itself rather than raise ImportError."""
	lonely = tmp_path / "bin"
	lonely.mkdir()
	shutil.copy2(LAUNCHER, lonely / "situc")

	result = run([str(lonely / "situc"), "--help"], cwd=tmp_path)

	assert result.returncode == 2
	assert "cannot find the situc package" in result.stderr


@pytest.mark.skipif(sys.platform == "win32", reason="module form is posix-tested")
def test_the_module_form_still_works() -> None:
	"""`python3 -m situc`, which is what someone guesses before finding bin/."""
	result = subprocess.run([sys.executable, "-m", "situc", "map", str(SCHEMA)],
	                        cwd=ROOT, capture_output=True, text=True, check=False)

	assert result.returncode == 0, result.stderr
	assert "situ capability map" in result.stdout
